/**
 * Build the prototype bundle: copies the repo fixture contracts/fixtures/plan_geometry/sample-v2.json into
 * src/data/fixture-sample-v2.generated.js and bundles src/main.js + three.js (from the frontend's node_modules, the
 * same r0.186 the product ships) into dist/studio6.js - one classic script, so index.html opens from file:///.
 *
 *   node build.mjs                      (uses <repo>/frontend/node_modules)
 *   SW_NODE_MODULES=<path> node build.mjs
 */
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../../../..');
const nm = process.env.SW_NODE_MODULES || path.join(repo, 'frontend', 'node_modules');
if (!existsSync(path.join(nm, 'esbuild'))) {
  console.error(`esbuild not found under ${nm} - run npm install in frontend/ or set SW_NODE_MODULES`);
  process.exit(1);
}
const require = createRequire(path.join(nm, 'x.js'));
const esbuild = require('esbuild');
const threeVersion = JSON.parse(readFileSync(path.join(nm, 'three', 'package.json'), 'utf8')).version;

const fixturePath = path.join(repo, 'contracts', 'fixtures', 'plan_geometry', 'sample-v2.json');
const fixture = readFileSync(fixturePath, 'utf8');
writeFileSync(path.join(here, 'src', 'data', 'fixture-sample-v2.generated.js'),
  `// GENERATED by build.mjs from contracts/fixtures/plan_geometry/sample-v2.json - do not edit.\nexport const FIXTURE_SAMPLE_V2 = ${fixture.trim()};\n`);

const out = path.join(here, 'dist', 'studio6.js');
await esbuild.build({
  entryPoints: [path.join(here, 'src', 'main.js')],
  bundle: true,
  format: 'iife',
  minify: true,
  sourcemap: false,
  target: ['es2020'],
  outfile: out,
  nodePaths: [nm],
  legalComments: 'none',
  banner: { js: `/* SmplWise Arx - Plan Studio 6 prototype bundle. three.js ${threeVersion} (MIT, see LICENSES.md). Built ${new Date().toISOString().slice(0, 10)}. */` },
  logLevel: 'info',
});
console.log(`bundle: ${out} (${(statSync(out).size / 1024).toFixed(0)} KB), three ${threeVersion}`);
