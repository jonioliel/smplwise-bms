-- WISKEY-SCHED-WRITE-2390 follow-up, row WISKEY-SCHED-READS-2520 (owner decision B2-ABI = a; WisKey contract `wiskey-schedule-reads.v1`):
-- Arx's record of each signed schedule inspection it asked WisKey to run (services/wiskey_schedule_reads.py). The row - with the
-- request UUID - is committed BEFORE `schedules/read_start_v1` is written, so a lost start acknowledgement stays an UNKNOWN that is
-- settled only by `schedules/read_status_v1` with the same UUID; the start is never sent again (WisKey refuses a reused UUID anyway).
-- What is kept: ids, the Arx action, the station / plan it read, the requested and the returned plan revision, WisKey's status and
-- code, and the closed projection of a completed result with every one-use token removed. Never a person, a name, a PIN or a card.
-- Number 0225: the last number on release/2520-train is 0224; renumber at the train if another branch takes it.
-- Additive only; older code never reads it. Rollback: drop the table (the reads are runtime-local in WisKey and cannot be resumed).

CREATE TABLE IF NOT EXISTS wiskey_schedule_reads (
  request_id     TEXT PRIMARY KEY,           -- canonical lowercase UUID, generated by Arx before the start frame
  action         TEXT NOT NULL,              -- the Arx action (readiness | dependencies | assess | plan_preview | plan_recheck | claim_preview)
  operation      TEXT NOT NULL,              -- the WisKey operation it starts (schedules/...)
  subject        TEXT NOT NULL,              -- the station id or the plan id it reads
  revision       INTEGER,                    -- the plan / schedule revision the request named
  state          TEXT NOT NULL CHECK (state IN ('sending', 'not_sent', 'accepted', 'running', 'completed', 'refused', 'unknown')),
  start_outcome  TEXT CHECK (start_outcome IN ('ok', 'refused', 'unknown', 'not_sent')),
  wiskey_code    TEXT,                       -- WisKey's refusal / error code, or the transport code of an unknown outcome
  plan_revision  INTEGER,                    -- the plan revision a completed result returned (never assumed)
  result_json    TEXT,                       -- the closed projection of a completed result (tokens removed)
  requested_by   TEXT NOT NULL,              -- the Arx user who started it
  created_at     TEXT NOT NULL,
  updated_at     TEXT NOT NULL,
  status_at      TEXT,                       -- the last status read that WisKey answered
  status_reads   INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS wiskey_schedule_reads_created ON wiskey_schedule_reads(created_at);
