def register_verbs(verbs_he: dict[str, str]) -> None:
    """Per service: `auto.word.<action>` (the verb as written, a `{n}` included - the automation role quotes the name after it),
    `auto.verb.<action>` (the verb with the names in place: where `{n}` stands, glued after a trailing maqaf, else after a space) and
    `auto.label.<action>` (the picker's short label: the verb without its placeholder)."""
    table: dict[str, tuple[str, str]] = {}
    for action, he in verbs_he.items():
        en = VERBS_EN[action]
        table[f"word.{action}"] = (he, en)
        he_full = he if "{n}" in he else f"{he}{{n}}" if he.endswith("־") else f"{he} {{n}}"
        en_full = en if "{n}" in en else f"{en} {{n}}"
        table[f"verb.{action}"] = (he_full, en_full)
        table[f"label.{action}"] = (he.replace("{n}", "").rstrip("־").strip(), en.replace("{n}", "").strip())
    register("auto", table)


