"""PY-CONSTRAINTS-LOCK-2407: the add-on image installs `-r requirements.txt -c constraints.txt`, and constraints.txt pins every
package of the resolved set exactly (CPython 3.12, musl, amd64 and aarch64). These tests keep the pair consistent offline:
every direct requirement is pinned at a version that satisfies it, the lock has only `name==version` lines, the extras of
uvicorn[standard] are locked too, and the build inputs (Dockerfile, the gate's Supervisor build check, the bill PDF image check)
carry the file. The online checks (wheels per arch, pip's own resolution, a fresh uv resolution) are scripts/lock_python.py
modes run by scripts/gate/addon_build_check.sh."""
from __future__ import annotations

import importlib.util
import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[3]
BACKEND = ROOT / "smplwise_vms" / "backend"
REQS = BACKEND / "requirements.txt"
CONS = BACKEND / "constraints.txt"

_spec = importlib.util.spec_from_file_location("lock_python_2407", ROOT / "scripts" / "lock_python.py")
lp = importlib.util.module_from_spec(_spec)
assert _spec.loader
_spec.loader.exec_module(lp)


def _pins() -> dict[str, str]:
    return lp.parse_constraints(CONS.read_text(encoding="utf-8"))


def test_requirements_and_constraints_agree():
    problems = lp.check(REQS.read_text(encoding="utf-8"), CONS.read_text(encoding="utf-8"))
    assert problems == [], problems


def test_constraints_is_generated_exact_and_plain():
    text = CONS.read_text(encoding="utf-8")
    assert text.startswith("# GENERATED by scripts/lock_python.py"), "regenerate with scripts/lock_python.py --write"
    assert "\r" not in text and text.endswith("\n")
    pins = _pins()   # raises on extras, markers, ranges, hashes or a duplicate
    assert len(pins) >= 40, f"suspiciously small lock: {len(pins)}"
    names = [lp.norm(ln.split("==")[0]) for ln in text.splitlines() if ln and not ln.startswith("#")]
    assert names == sorted(names), "the generator writes the pins sorted by normalized name"


def test_every_direct_requirement_and_the_uvicorn_standard_extras_are_locked():
    pins = _pins()
    for r in lp.parse_requirements(REQS.read_text(encoding="utf-8")):
        assert lp.norm(r["name"]) in pins, r["name"]
    # uvicorn[standard] pulls these in on Linux; an unlocked one would resolve freely on the Supervisor
    for extra in ("uvloop", "httptools", "websockets", "watchfiles", "python-dotenv", "pyyaml"):
        assert extra in pins, extra
    # the direct exact pins are the same version in both files
    for r in lp.parse_requirements(REQS.read_text(encoding="utf-8")):
        if r["spec"].startswith("=="):
            assert pins[lp.norm(r["name"])] == r["spec"][2:].strip(), r["name"]


def test_check_catches_a_drifted_or_incomplete_lock():
    reqs = "fastapi==0.141.1\nuvicorn[standard]==0.53.0\nnumpy>=2.0,<3\ntzdata>=2024.1\n"
    good = "fastapi==0.141.1\nuvicorn==0.53.0\nnumpy==2.5.4\ntzdata==2026.6\n"
    assert lp.check(reqs, good) == []
    assert any("numpy" in p and "not pinned" in p for p in lp.check(reqs, good.replace("numpy==2.5.4\n", "")))
    assert any("numpy==3.0.0" in p for p in lp.check(reqs, good.replace("2.5.4", "3.0.0")))
    assert any("fastapi==0.141.0" in p for p in lp.check(reqs, good.replace("0.141.1", "0.141.0")))
    assert any("duplicate" in p for p in lp.check(reqs, good + "FastAPI==0.141.1\n"))
    for bad in ("numpy>=2\n", "uvicorn[standard]==0.53.0\n", "uvloop==0.22.1; sys_platform != 'win32'\n",
                "idna==3.20 --hash=sha256:" + "a" * 64 + "\n", "-r other.txt\n"):
        assert lp.check(reqs, good + bad), f"accepted a non-plain constraints line: {bad!r}"
    assert lp.check(reqs, "# nothing\n") == ["constraints.txt pins nothing"]


