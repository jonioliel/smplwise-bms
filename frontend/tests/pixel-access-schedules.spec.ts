import { test, expect, type Page } from '@playwright/test';
import fs from 'node:fs';
import { installAccessMock, NOW, SKINS, type MockOptions } from './access-control-mocks';
import { settlePage } from './pixel-settle';
import { pixelTitle, skinCheck } from './helpers/pixel-skins';

// CR-036 S9 pixel baselines: the NEW read-only schedules screen - the door view (week grid, program, library, proposals) in every skin the
// product has, and the table, the phone's door sheet and the states (empty, error, forbidden) in the classic skin - desktop 1440 and phone
// 390, against the mocked backend (deterministic data, fixed clock, performance:full). Baselines are per OS: the Linux ones are generated on
// the runner with `--update-snapshots` (NOT generated by the slice itself); on an OS without a baseline the check is skipped instead of failing
// on a missing file (the design-foundation rule).
//   ~/run_remote.sh spec <branch> tests/pixel-access-schedules.spec.ts --project=desktop --project=mobile [--update-snapshots]
const SCREEN = 'sw-app wiskey-schedules';
const ON = { 'access.ui.schedules': 'smplwise' };

const noBaseline = (info: { snapshotPath: (...name: string[]) => string; config: { updateSnapshots: string } }, name: string) =>
  !['all', 'changed'].includes(info.config.updateSnapshots) && !fs.existsSync(info.snapshotPath(name));

async function open(page: Page, opts: MockOptions, skin: string, ready: string, hash = '/wiskey/schedules', view: 'door' | 'table' = 'door') {
  await page.addInitScript((v) => localStorage.setItem('sw.wiskey.schedules.view', v), view);
  await installAccessMock(page, { ...opts, settings: ON });
  await page.clock.setFixedTime(NOW);
  await page.goto('about:blank');
  await page.goto(`/?design=a&look=performance:full&skin=${skin}&scheme=light#${hash}`);
  await page.waitForSelector('sw-app');
  await page.waitForSelector(ready, { timeout: 30_000 });
  await settlePage(page);
}

async function compare(page: Page, info: Parameters<typeof noBaseline>[0] & { project: { name: string } }, name: string) {
  const file = `${name}-${info.project.name === 'mobile' ? '390' : '1440'}.png`;
  if (noBaseline(info, file)) test.info().annotations.push({ type: 'skipped-pixel', description: `${file}: no baseline on ${process.platform}` });
  else await expect(page).toHaveScreenshot(file, { maxDiffPixels: 40, animations: 'disabled' });
}

test.describe('pixel: the schedules screen', () => {
  test.skip(process.env.SW_LIVE === '1', 'mocked-backend spec');
  test.beforeEach(({}, info) => {
    test.skip(info.project.name === 'tablet', 'desktop and phone only');
  });

  for (const skin of SKINS) {
    // "pixel-stable" in the title: the release gate runs its pixel group with --grep pixel-stable
    // GATELANES-297: pixels for the skins in helpers/pixel-skins.ts (classic, domus), the structural smoke for the others
    test(pixelTitle(skin, 'the door view with the library and the proposals'), async ({ page }, info) => {
      const check = skinCheck(page, skin);
      await open(page, {}, skin, `${SCREEN} [data-sch-lib-row="sch-contractors"]`);
      await check(() => compare(page, info, `schedules-${skin}-door`), SCREEN);
    });
  }

  test('classic is pixel-stable: the table (desktop) or the door sheet (phone)', async ({ page }, info) => {
    if (info.project.name === 'mobile') {
      await open(page, {}, 'classic', `${SCREEN} [data-sch-program]`);
      await page.locator(`${SCREEN} [data-sch-door-chip]`).click();
      await page.waitForSelector(`${SCREEN} sw-drawer[data-sch-sheet][open] button[data-sch-door]`, { timeout: 20_000 });
      await settlePage(page);
      await compare(page, info, 'schedules-classic-sheet');
    } else {
      await open(page, {}, 'classic', `${SCREEN} sw-table tbody tr[data-row-id="entry-c:1"] sw-badge`, '/wiskey/schedules', 'table');
      await compare(page, info, 'schedules-classic-table');
    }
  });

  test('classic is pixel-stable: a paused program, a saved draft and an error at an offline station', async ({ page }, info) => {
    await open(page, {}, 'classic', `${SCREEN} [data-sch-program="paused"]`, '/wiskey/schedules?door=entry-b:1');
    await compare(page, info, 'schedules-classic-paused');
    await page.unrouteAll({ behavior: 'ignoreErrors' });
    await open(page, {}, 'classic', `${SCREEN} [data-sch-program="draft"]`, '/wiskey/schedules?door=entry-b:2');
    await compare(page, info, 'schedules-classic-draft');
    await page.unrouteAll({ behavior: 'ignoreErrors' });
    await open(page, {}, 'classic', `${SCREEN} [data-sch-program="error"]`, '/wiskey/schedules?door=entry-c:1');
    await compare(page, info, 'schedules-classic-error-program');
  });

  test('classic is pixel-stable: the empty, error and forbidden states', async ({ page }, info) => {
    await open(page, { schedules: 'empty' }, 'classic', `${SCREEN} [data-sch-panel="plans-empty"]`);
    await compare(page, info, 'schedules-classic-empty');
    await page.unrouteAll({ behavior: 'ignoreErrors' });
    await open(page, { schedules: 'error' }, 'classic', `${SCREEN} [data-sch-panel="library-error"]`);
    await compare(page, info, 'schedules-classic-error');
    await page.unrouteAll({ behavior: 'ignoreErrors' });
    await open(page, { persona: 'viewer' }, 'classic', `${SCREEN} [data-sch-panel="forbidden"]`);
    await compare(page, info, 'schedules-classic-forbidden');
  });
});
