import { test, expect } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SW_LAYOUTS, SW_TONES, swLogoSvg } from '../src/design/sw-logo-art';

// LOGOKIT-295: the SmplWise logo is the approved developer kit's artwork, drawn inline from ONE generated module (design/sw-logo-art.ts),
// on a light surface in the brand colours and on a dark one in white with no plate, and no surface points at the mint PNG any more.
const SRC = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src');
const ROOT = path.resolve(SRC, '../..');
const read = (rel: string) => fs.readFileSync(path.join(SRC, rel), 'utf-8');
const kit = (tone: string, file: string) => fs.readFileSync(path.join(ROOT, 'docs/brand/logo-kit/svg', tone, file + '.svg'), 'utf-8');

test('the module draws exactly the kit outlines, placements and colours', () => {
  const art = read('design/sw-logo-art.ts');
  expect(art).toContain('GENERATED by scripts/brand/gen_sw_logo_art.py');
  for (const [layout, file] of [['horizontal', 'logo-horizontal'], ['stacked', 'logo-stacked'], ['symbol', 'symbol'], ['wordmark', 'wordmark']] as const) {
    const svg = kit('brand', file);
    const vb = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/)!;
    expect(SW_LAYOUTS[layout].w).toBeCloseTo(Number(vb[1]), 3);
    expect(SW_LAYOUTS[layout].h).toBeCloseTo(Number(vb[2]), 3);
    for (const d of svg.match(/ d="([^"]+)"/g) ?? []) expect(art).toContain(d.slice(4, -1));
  }
  expect(SW_TONES.brand).toEqual({ symbol: '#0062ff', wordmark: '#0e3054' });
  expect(SW_TONES.white).toEqual({ symbol: '#ffffff', wordmark: '#ffffff' });
});

test('light: brand colours, no background; dark (white tone): white and no plate', () => {
  const light = swLogoSvg('horizontal', 'brand');
  expect(light).toContain('viewBox="0 0 1369 217"');
  expect(light).toContain('fill="#0062ff"');
  expect(light).toContain('fill="#0e3054"');
  expect(light).toContain('data-brand-art="kit-horizontal-brand"');
  const dark = swLogoSvg('horizontal', 'white');
  expect(dark).toContain('data-brand-art="kit-horizontal-white"');
  expect(dark.match(/fill="#[0-9a-f]{6}"/g)).toEqual(['fill="#ffffff"', 'fill="#ffffff"']);
  for (const s of [light, dark, swLogoSvg('stacked', 'brand'), swLogoSvg('symbol', 'white')]) expect(s).not.toMatch(/<rect|<circle|background/);
});

test('the layouts: stacked has both parts, symbol and wordmark one each', () => {
  expect(swLogoSvg('stacked', 'brand').match(/<path /g)).toHaveLength(2);
  expect(swLogoSvg('symbol', 'brand').match(/<path /g)).toHaveLength(1);
  expect(swLogoSvg('wordmark', 'navy').match(/<path /g)).toHaveLength(1);
  expect(swLogoSvg('symbol', 'brand')).toContain('viewBox="0 0 484 178"');
});

test('an alt text makes the drawing an image; none makes it decorative', () => {
  expect(swLogoSvg('horizontal', 'brand', 'SmplWise')).toContain('role="img" aria-label="SmplWise"');
  expect(swLogoSvg('horizontal', 'brand')).toContain('aria-hidden="true"');
});

test('sw-brand draws the product logo from the module with no plate; the placements follow the owner choice', () => {
  const brand = read('components/sw-brand.ts');
  expect(brand).toContain("swLogoSvg(layout, dark ? 'white' : 'brand', alt)");
  const productBranch = brand
    .slice(brand.indexOf("if (this.kind === 'product')"), brand.indexOf("const installer = this.kind === 'installer'"))
    .split('\n')
    .filter((l) => !l.trim().startsWith('//'))
    .join('\n');
  expect(productBranch).not.toMatch(/plate|invert/);
  expect(read('arx/arx-login.ts')).toMatch(/<sw-brand kind="product" stacked /);
  expect(read('screens/kiosk-wall.ts')).toMatch(/<sw-brand kind="product" scheme="dark" /);
  expect(read('shell/sw-app.ts')).toMatch(/<sw-brand kind="product" mark decorative /);
  expect(read('notice-tv/main.ts')).toContain("swLogoSvg('horizontal', dark ? 'white' : 'brand', 'SmplWise')");
});

test('no surface points at the mint PNG, and the tab icon is the Arx icon', () => {
  expect(read('notice-tv/main.ts')).not.toMatch(/smplwise-logo\.png|smplwise-mark\.png/);
  expect(read('screens/kiosk-wall.ts')).not.toMatch(/smplwise-logo\.png|smplwise-mark\.png/);
  const index = fs.readFileSync(path.join(SRC, '../index.html'), 'utf-8');
  expect(index).toContain('./icons/arx.svg');
  expect(index).not.toContain('smplwise-mark');
  expect(fs.existsSync(path.join(SRC, '../public/brand/smplwise-logo.png'))).toBe(false);
  expect(fs.existsSync(path.join(SRC, '../public/brand/smplwise-mark.png'))).toBe(false);
  expect(fs.readFileSync(path.join(SRC, '../notice-tv.html'), 'utf-8')).not.toContain('id="sw-word"');
});
