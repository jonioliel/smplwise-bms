// CR-FE-GATES-2436 (review 07:F8 step 1): the client-to-inventory check. REPORT-ONLY - it prints counts and always exits 0;
// CR-FE-GATES-ENFORCE makes "a client route missing from the inventory" a failure.
//
// 1. Every call of the API client in src/ - get / post / put / patch / del / upload / api (and apiUrl / resourceUrl, any method) - in
//    a module that imports that name from api/client. The first argument must be a string or template literal; `${...}` in a whole
//    path segment is a parameter, a trailing `${...}` glued to text (or one holding a '?') is a query suffix and dropped, and a call
//    whose path is a variable or starts with `${...}` is counted as "dynamic" (not checked). Demo modules (`*-mock.ts`, `*-demo.ts`)
//    are skipped: they never reach the server.
// 2. Every route of contracts/API_INVENTORY.md (generated by scripts/api_inventory.py): method + path, `{param}` = any one segment,
//    `{param:path}` = the rest of the path.
// It prints the client calls that match no inventory route (method and path) and the count of inventory routes no client call reaches.
// Usage (from frontend/): node scripts/api-client-check.mjs [--all] [--json]
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const HERE = path.dirname(url.fileURLToPath(import.meta.url));
const SRC = path.resolve(HERE, '..', 'src');
const INVENTORY = path.resolve(HERE, '..', '..', 'contracts', 'API_INVENTORY.md');
const METHOD = { get: 'GET', post: 'POST', put: 'PUT', patch: 'PATCH', del: 'DELETE', upload: 'POST', api: null, apiUrl: '*', resourceUrl: '*' };

function walk(dir, out = []) {
  for (const n of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, n.name);
    if (n.isDirectory()) walk(p, out);
    else if (/\.ts$/.test(n.name) && !/\.d\.ts$/.test(n.name)) out.push(p);
  }
  return out;
}

/** Read a string or template literal starting at s[i] (the quote). Returns { parts: [{lit}|{expr}], end } or null. */
export function readLiteral(s, i) {
  const q = s[i];
  if (q !== "'" && q !== '"' && q !== '`') return null;
  const parts = [];
  let lit = '';
  let j = i + 1;
  while (j < s.length) {
    const c = s[j];
    if (c === '\\') {
      lit += s[j + 1];
      j += 2;
      continue;
    }
    if (c === q) {
      if (lit) parts.push({ lit });
      return { parts, end: j + 1 };
    }
    if (q === '`' && c === '$' && s[j + 1] === '{') {
      if (lit) parts.push({ lit });
      lit = '';
      let depth = 1;
      let k = j + 2;
      while (k < s.length && depth > 0) {
        const d = s[k];
        if (d === "'" || d === '"' || d === '`') {
          const inner = readLiteral(s, k);
          if (!inner) return null;
          k = inner.end;
          continue;
        }
        if (d === '{') depth++;
        else if (d === '}') depth--;
        k++;
      }
      parts.push({ expr: s.slice(j + 2, k - 1) });
      j = k;
      continue;
    }
    if (q !== '`' && c === '\n') return null;
    lit += c;
    j++;
  }
  return null;
}

/** Literal parts -> a normalised client path (segments; '{}' = a parameter, 'a*b' = a segment with a parameter inside), or null (dynamic). */
export function clientPath(parts) {
  const ps = parts.slice();
  if (!ps.length || ps[0].expr !== undefined) return null; // the path itself comes from a variable
  let out = '';
  for (let n = 0; n < ps.length; n++) {
    const p = ps[n];
    if (p.lit !== undefined) {
      const q = p.lit.indexOf('?');
      if (q >= 0) {
        out += p.lit.slice(0, q);
        break;
      }
      out += p.lit;
    } else {
      if (/['"`]\?|[?&][\w-]+=/.test(p.expr)) break; // a query string built in the expression
      const last = n === ps.length - 1 || ps.slice(n + 1).every((x) => x.lit !== undefined && x.lit.startsWith('?'));
      if (last && out && !out.endsWith('/')) break; // `items${suffix}`: an optional query or suffix
      out += '\u0000';
    }
  }
  out = out.replace(/^\/+/, '').replace(/^api\/v1\//, '').replace(/#.*$/, '').replace(/\/+$/, '');
  if (!out) return null;
  return out.split('/').map((seg) => (seg === '\u0000' ? '{}' : seg.replace(/\u0000/g, '*')));
}

export function parseInventory(md) {
  const routes = [];
  for (const line of md.split('\n')) {
    const m = /^\|\s*([^|]+?)\s*\|\s*([A-Z]+)\s*\|\s*`([^`]+)`/.exec(line);
    if (!m || m[2] === 'Method') continue;
    const p = m[3].replace(/^\/api\/v1\/?/, '').replace(/\/+$/, '');
    routes.push({ router: m[1], method: m[2], path: m[3], segs: p ? p.split('/') : [] });
  }
  return routes;
}

function segMatch(c, r) {
  if (/^\{[^}]+:path\}$/.test(r)) return 'rest';
  if (c === '{}' || /^\{[^}]+\}$/.test(r)) return true;
  if (c.includes('*')) return new RegExp(`^${c.split('*').map((x) => x.replace(/[.+^$()|[\]\\{}?]/g, '\\$&')).join('.+')}$`).test(r);
  return c === r;
}

export function routeMatches(call, route) {
  if (call.method !== '*' && call.method !== route.method && !(route.method === 'WS' && call.method === 'GET')) return false;
  const a = call.segs;
  const b = route.segs;
  for (let i = 0; i < b.length; i++) {
    if (i >= a.length) return false;
    const m = segMatch(a[i], b[i]);
    if (m === 'rest') return true;
    if (!m) return false;
  }
  return a.length === b.length;
}

/** Module-level string constants (`const T = 'tickets'`, `const E = \`${BASE}/x/\``) - the usual path prefixes of an API module. */
export function fileConstants(text) {
  const consts = new Map();
  for (const m of text.matchAll(/(?:^|\n)\s*(?:export\s+)?const\s+([A-Za-z_$][\w$]*)\s*(?::\s*string\s*)?=\s*(?=['"`])/g)) {
    const lit = readLiteral(text, m.index + m[0].length);
    if (!lit) continue;
    const parts = substitute(lit.parts, consts);
    if (parts.every((p) => p.lit !== undefined)) consts.set(m[1], parts.map((p) => p.lit).join(''));
  }
  // path helpers: `const base = (rid: string) => \`frigate/${enc(rid)}\`` - a call `${base(x)}` stands for the helper's template
  const helpers = new Map();
  for (const m of text.matchAll(/(?:^|\n)\s*(?:export\s+)?const\s+([A-Za-z_$][\w$]*)\s*=\s*\([^()]*\)\s*(?::\s*string\s*)?=>\s*(?=['"`])/g)) {
    const lit = readLiteral(text, m.index + m[0].length);
    if (lit) helpers.set(m[1], substitute(lit.parts, consts));
  }
  consts.helpers = helpers;
  return consts;
}

/** Replace `${NAME}` of a known constant with its text and merge the neighbouring literal parts. */
export function substitute(parts, consts) {
  const out = [];
  const push = (v) => {
    const prev = out[out.length - 1];
    if (v.lit !== undefined && prev && prev.lit !== undefined) prev.lit += v.lit;
    else out.push({ ...v });
  };
  for (const p of parts) {
    const e = p.expr?.trim();
    const h = e !== undefined ? /^([A-Za-z_$][\w$]*)\(/.exec(e) : null;
    if (e !== undefined && consts.has(e)) push({ lit: consts.get(e) });
    else if (h && consts.helpers?.has(h[1]) && e.endsWith(')')) for (const q of consts.helpers.get(h[1])) push(q);
    else push(p);
  }
  return out.filter((p) => p.lit !== '');
}

export function clientCalls(file, text) {
  const imp = /import\s*\{([^}]*)\}\s*from\s*['"](?:\.\/|(?:\.\.\/)+(?:[\w-]+\/)*)(?:api\/)?client(?:\.js)?['"]/.exec(text);
  if (!imp) return [];
  const names = imp[1].split(',').map((x) => x.trim().replace(/^type\s+/, '')).filter((n) => n in METHOD);
  if (!names.length) return [];
  const consts = fileConstants(text);
  const calls = [];
  const re = new RegExp(`(?<![\\w$.])(${names.join('|')})\\s*(?=[<(])`, 'g');
  for (const m of text.matchAll(re)) {
    let i = m.index + m[0].length;
    if (text[i] === '<') {
      let depth = 0;
      for (; i < text.length; i++) {
        if (text[i] === '<') depth++;
        else if (text[i] === '>' && text[i - 1] !== '=') depth--;
        if (depth === 0) break;
      }
      i++;
      while (/\s/.test(text[i])) i++;
      if (text[i] !== '(') continue;
    }
    i++;
    while (/\s/.test(text[i])) i++;
    const line = text.slice(0, m.index).split('\n').length;
    if (/^[\w$]+\??\s*:/.test(text.slice(i, i + 80)) || /^\)\s*:/.test(text.slice(i, i + 10))) continue; // a signature in a type, not a call
    let lit = readLiteral(text, i);
    if (!lit) {
      const id = /^([A-Za-z_$][\w$]*)\s*[,)]/.exec(text.slice(i, i + 80));
      if (id && consts.has(id[1])) lit = { parts: [{ lit: consts.get(id[1]) }], end: i + id[1].length };
    }
    if (lit) lit = { parts: substitute(lit.parts, consts), end: lit.end };
    let method = METHOD[m[1]];
    if (method === null) {
      const rest = text.slice(i, i + 400);
      method = /method:\s*['"](\w+)['"]/.exec(rest)?.[1] ?? 'GET';
    }
    // `'home/wallpaper/' + id`: a literal ending in '/' and concatenated is a path with one more parameter segment
    const parts = lit ? lit.parts.slice() : null;
    if (parts && /^\s*\+/.test(text.slice(lit.end, lit.end + 20)) && parts.length && parts[parts.length - 1].lit?.endsWith('/')) parts.push({ expr: '+' }, { lit: '' });
    const segs = parts ? clientPath(parts.filter((p) => p.lit !== '')) : null;
    calls.push({ file, line, fn: m[1], method, segs, raw: segs ? null : text.slice(i, i + 60).split('\n')[0] });
  }
  return calls;
}

export function check(srcDir, inventoryText) {
  const routes = parseInventory(inventoryText);
  const calls = [];
  for (const f of walk(srcDir)) {
    if (/-(mock|demo)\.ts$/.test(f) || /[\\/]api[\\/]client\.ts$/.test(f)) continue;
    calls.push(...clientCalls(path.relative(path.dirname(srcDir), f).replace(/\\/g, '/'), fs.readFileSync(f, 'utf8')));
  }
  const used = new Set();
  const missing = [];
  const dynamicCalls = [];
  for (const c of calls) {
    if (!c.segs) {
      dynamicCalls.push({ fn: c.fn, at: `${c.file}:${c.line}`, arg: c.raw });
      continue;
    }
    const hit = routes.filter((r) => routeMatches(c, r));
    if (!hit.length) missing.push({ method: c.method, path: c.segs.join('/'), at: `${c.file}:${c.line}` });
    for (const r of hit) used.add(r);
  }
  const unused = routes.filter((r) => !used.has(r));
  const dynamic = dynamicCalls.length;
  return { calls: calls.length, checked: calls.length - dynamic, dynamic, dynamicCalls, missing, routes: routes.length, routesUsed: used.size, unused: unused.map((r) => ({ router: r.router, method: r.method, path: r.path })), mode: 'report-only' };
}

if (process.argv[1] && path.resolve(process.argv[1]) === url.fileURLToPath(import.meta.url)) {
  const argv = process.argv.slice(2);
  try {
    if (!fs.existsSync(INVENTORY)) {
      console.log(`api-client-check (report-only): no inventory at ${INVENTORY}`);
      process.exit(0);
    }
    const r = check(SRC, fs.readFileSync(INVENTORY, 'utf8'));
    if (argv.includes('--json')) console.log(JSON.stringify(r, null, 2));
    else {
      const all = argv.includes('--all');
      const L = [`api-client-check (report-only, never fails) - ${path.relative(process.cwd(), INVENTORY)}`];
      L.push(`  client calls: ${r.calls} (${r.checked} checked, ${r.dynamic} dynamic paths not checked)`);
      if (argv.includes('--dynamic')) for (const d of r.dynamicCalls) L.push(`    dynamic ${d.fn}(${d.arg}  (${d.at})`);
      L.push(`  client calls with no inventory route: ${r.missing.length}`);
      for (const m of all ? r.missing : r.missing.slice(0, 40)) L.push(`    ${m.method.padEnd(6)} ${m.path}  (${m.at})`);
      if (!all && r.missing.length > 40) L.push(`    ... ${r.missing.length - 40} more (--all)`);
      L.push(`  inventory routes: ${r.routes}, reached by a client call: ${r.routesUsed}, by none: ${r.unused.length}`);
      const byRouter = new Map();
      for (const u of r.unused) byRouter.set(u.router, (byRouter.get(u.router) ?? 0) + 1);
      L.push(`    by router: ${[...byRouter].sort((a, b) => b[1] - a[1]).slice(0, 15).map(([k, v]) => `${k} ${v}`).join(', ')}${byRouter.size > 15 ? ', ...' : ''}`);
      if (all) for (const u of r.unused) L.push(`    ${u.method.padEnd(6)} ${u.path}  [${u.router}]`);
      L.push('  (a heuristic: a path built in a variable or a helper is not seen; verify before acting on any single line)');
      console.log(L.join('\n'));
    }
  } catch (e) {
    console.error(`api-client-check (report-only): ${e instanceof Error ? e.stack : String(e)}`);
  }
  process.exit(0);
}
