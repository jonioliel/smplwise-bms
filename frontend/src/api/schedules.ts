export function resolveDays(tokens: DayToken[]): DayId[] | null {
  if (tokens.includes('daily')) return [...DAY_ORDER];
  if (tokens.includes('workday') || tokens.includes('weekend')) return null;
  return DAY_ORDER.filter((d) => tokens.includes(d));
}

export function daysKind(tokens: DayToken[]): DaysKind {
  if (tokens.includes('daily')) return 'daily';
  const named = tokens.filter((t) => (DAY_ORDER as string[]).includes(t));
  if (tokens.includes('workday')) return named.length ? 'mixed' : 'workday';
  if (tokens.includes('weekend')) return named.length ? 'mixed' : 'weekend';
  return 'days';
}

/** "כל יום", "א׳–ה׳", "א׳, ג׳, ה׳", "ימי עבודה". */
export function daysLabel(tokens: DayToken[]): string {
  if (tokens.includes('daily')) return 'כל יום';
  const parts: string[] = [];
  if (tokens.includes('workday')) parts.push('ימי עבודה');
  if (tokens.includes('weekend')) parts.push('סוף שבוע');
  const days = DAY_ORDER.filter((d) => tokens.includes(d));
  if (days.length === 7) return 'כל יום';
  if (days.length >= 3) {
    const idx = days.map((d) => DAY_ORDER.indexOf(d));
    const contiguous = idx.every((v, i) => i === 0 || v === idx[i - 1] + 1);
    if (contiguous) parts.unshift(`${DAY_SHORT[days[0]]}–${DAY_SHORT[days[days.length - 1]]}`);
    else parts.unshift(days.map((d) => DAY_SHORT[d]).join(', '));
  } else if (days.length) parts.unshift(days.map((d) => DAY_SHORT[d]).join(', '));
  return parts.join(' · ') || '—';
}

