export interface SunTimes {
  /** Minutes from local midnight, today. */
  sunrise: number;
  sunset: number;
}

/** Fallback when no sun entity is known (the UI marks sun times as "משוער" anyway). */
export const SUN_FALLBACK: SunTimes = { sunrise: 6 * 60 + 30, sunset: 18 * 60 + 15 };

const FIXED_RE = /^(\d{1,2}):(\d{2})(?::(\d{2}))?$/;
const SUN_RE = /^(sunrise|sunset)([+-])(\d{1,2}):(\d{2})(?::(\d{2}))?$/;

function pad(n: number): string {
  return String(n).padStart(2, '0');
}

/** A component time string ("07:30:00", "07:30", "sunset+00:30:00") as a TimeSpec; null when not recognised. */
export function parseTime(raw: string | null | undefined): TimeSpec | null {
  const s = (raw ?? '').trim();
  let m = FIXED_RE.exec(s);
  if (m) {
    const h = Number(m[1]);
    const min = Number(m[2]);
    if (h > 23 || min > 59) return null;
    return { kind: 'fixed', time: `${pad(h)}:${pad(min)}`, raw: s };
  }
  m = SUN_RE.exec(s);
  if (m) {
    const off = Number(m[3]) * 60 + Number(m[4]);
    return { kind: 'sun', event: m[1] as 'sunrise' | 'sunset', offset_min: m[2] === '-' ? -off : off, raw: s };
  }
  return null;
}

/** The stored form Arx writes (§2.2): "HH:MM:SS" or "sunset+HH:MM:SS". */
export function timeToRaw(spec: { kind: 'fixed'; time: string } | { kind: 'sun'; event: 'sunrise' | 'sunset'; offset_min: number }): string {
  if (spec.kind === 'fixed') return `${spec.time.slice(0, 5)}:00`;
  const a = Math.abs(spec.offset_min);
  return `${spec.event}${spec.offset_min < 0 ? '-' : '+'}${pad(Math.floor(a / 60))}:${pad(a % 60)}:00`;
}

export function minutesToRaw(minutes: number): string {
  const m = ((Math.round(minutes) % 1440) + 1440) % 1440;
  return `${pad(Math.floor(m / 60))}:${pad(m % 60)}:00`;
}

/** Hebrew display: "07:30", "שקיעה +00:30", "זריחה −00:15", "שקיעה". */
export function formatTime(spec: TimeSpec | null): string {
  if (!spec) return '—';
  if (spec.kind === 'fixed') return spec.time;
  const word = spec.event === 'sunrise' ? 'זריחה' : 'שקיעה';
  if (!spec.offset_min) return word;
  const a = Math.abs(spec.offset_min);
  return `${word} ${spec.offset_min < 0 ? '−' : '+'}${pad(Math.floor(a / 60))}:${pad(a % 60)}`;
}

/** Minutes from midnight (sun times from today's values, clamped like the component to 00:00..23:59). */
export function timeMinutes(spec: TimeSpec, sun: SunTimes | null = null): number {
  if (spec.kind === 'fixed') {
    const [h, m] = spec.time.split(':').map(Number);
    return h * 60 + m;
  }
  const base = (sun ?? SUN_FALLBACK)[spec.event];
  return Math.min(1439, Math.max(0, base + spec.offset_min));
}

/** A slot's span in minutes: a point action occupies one minute; a stop of 00:00 (or before the start) = end of day. */
export function slotSpan(slot: { start: TimeSpec; stop: TimeSpec | null }, sun: SunTimes | null = null): { start: number; end: number } {
  const start = timeMinutes(slot.start, sun);
  if (!slot.stop) return { start, end: Math.min(1440, start + 1) };
  let end = timeMinutes(slot.stop, sun);
  if (end <= start) end = 1440;
  return { start, end };
}

export function draftSlotSpan(slot: DraftSlot, sun: SunTimes | null = null): { start: number; end: number } | null {
  const start = parseTime(slot.start);
  if (!start) return null;
  const stop = slot.stop ? parseTime(slot.stop) : null;
  if (slot.stop && !stop) return null;
  return slotSpan({ start, stop }, sun);
}

/** Index pairs of overlapping slots (half-open intervals; contiguous slots do not overlap). */
export function findOverlaps(slots: DraftSlot[], sun: SunTimes | null = null): [number, number][] {
  const spans = slots.map((s) => draftSlotSpan(s, sun));
  const out: [number, number][] = [];
  for (let i = 0; i < spans.length; i++)
    for (let j = i + 1; j < spans.length; j++) {
      const a = spans[i];
      const b = spans[j];
      if (a && b && a.start < b.end && b.start < a.end) out.push([i, j]);
    }
  return out;
}

/** Snap minutes to the editor's grid (5 / 15 / 30), within the day. */
export function snapMinutes(minutes: number, step: number): number {
  return Math.min(1440, Math.max(0, Math.round(minutes / step) * step));
}

