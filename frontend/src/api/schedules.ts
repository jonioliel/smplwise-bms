export function scheduleSettingsOf(s: Record<string, unknown> | null | undefined): ScheduleSettings {
  const d = SCHEDULE_SETTINGS_DEFAULT;
  let classes: unknown = s?.['schedules.classes'];
  if (typeof classes === 'string') {
    try {
      classes = JSON.parse(classes);
    } catch {
      classes = null;
    }
  }
  const snap = Number(s?.['schedules.snap_minutes']);
  const repeat = s?.['schedules.default_repeat'];
  const days = Number(s?.['schedules.runs_retention_days']);
  const sensor = s?.['schedules.shabbat_sensor'];
  return {
    enabled: String(s?.['schedules.enabled'] ?? 'true') !== 'false',
    classes: Array.isArray(classes) ? ALL_CLASSES.filter((c) => (classes as unknown[]).includes(c)) : d.classes,
    snapMinutes: snap === 5 || snap === 30 ? snap : 15,
    defaultRepeat: repeat === 'pause' || repeat === 'single' ? repeat : 'repeat',
    runsRetentionDays: Number.isFinite(days) && days >= 7 && days <= 365 ? days : d.runsRetentionDays,
    shabbatSensor: typeof sensor === 'string' ? sensor : '',
  };
}

/** The PATCH /settings body for what differs (system.configure; audited by the server). */
export function scheduleSettingsPatch(from: ScheduleSettings, to: ScheduleSettings): Record<string, unknown> {
  const body: Record<string, unknown> = {};
  if (from.enabled !== to.enabled) body['schedules.enabled'] = String(to.enabled);
  if (JSON.stringify(from.classes) !== JSON.stringify(to.classes)) body['schedules.classes'] = to.classes;
  if (from.snapMinutes !== to.snapMinutes) body['schedules.snap_minutes'] = String(to.snapMinutes);
  if (from.defaultRepeat !== to.defaultRepeat) body['schedules.default_repeat'] = to.defaultRepeat;
  if (from.runsRetentionDays !== to.runsRetentionDays) body['schedules.runs_retention_days'] = to.runsRetentionDays;
  if (from.shabbatSensor !== to.shabbatSensor) body['schedules.shabbat_sensor'] = to.shabbatSensor;
  return body;
}

export async function saveScheduleSettings(from: ScheduleSettings, to: ScheduleSettings): Promise<ScheduleSettings> {
  const body = scheduleSettingsPatch(from, to);
  if (!Object.keys(body).length) return to;
  if (!isApi()) return demoStore().saveSettings(to);
  const r = await patch<{ settings: Record<string, unknown> }>('settings', body);
  invalidateSettings();
  return scheduleSettingsOf(r.settings);
}

