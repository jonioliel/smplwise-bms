/**
 * Next occurrence of each slot, soonest first - the shape of the component's `timestamps` / `next_entries` (V-LIVE).
 * Local (browser) time, today's sun times for every day; `workday` / `weekend` are not computed (empty result). For demo
 * mode and a draft's instant feedback only - the server's preview is the answer in API mode.
 */
export function approximateUpcoming(
  draft: Pick<ScheduleDraft, 'weekdays' | 'start_date' | 'end_date' | 'slots'>,
  now: Date = new Date(),
  sun: SunTimes | null = null,
): UpcomingRun[] {
  const days = resolveDays(draft.weekdays);
  if (!days || !days.length) return [];
  const from = draft.start_date ? new Date(`${draft.start_date}T00:00:00`) : null;
  const to = draft.end_date ? new Date(`${draft.end_date}T23:59:59`) : null;
  const out: UpcomingRun[] = [];
  draft.slots.forEach((slot, index) => {
    const spec = parseTime(slot.start);
    if (!spec) return;
    const minutes = timeMinutes(spec, sun);
    for (let k = 0; k < 400; k++) {
      const d = new Date(now.getFullYear(), now.getMonth(), now.getDate() + k, Math.floor(minutes / 60), minutes % 60, 0, 0);
      if (d.getTime() <= now.getTime()) continue;
      if (!days.includes(DAY_ORDER[d.getDay()])) continue;
      if (from && d < from) continue;
      if (to && d > to) break;
      out.push({ at: d.toISOString(), slot_index: index });
      break;
    }
  });
  return out.sort((a, b) => a.at.localeCompare(b.at));
}

/** "היום 18:00", "מחר 07:30", "יום ה׳ 06:00", "12.10 06:00" (local time). */
export function whenLabel(iso: string | null | undefined, now: Date = new Date()): string {
  if (!iso) return '—';
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return '—';
  const hm = `${pad(d.getHours())}:${pad(d.getMinutes())}`;
  const day0 = new Date(now.getFullYear(), now.getMonth(), now.getDate()).getTime();
  const diff = Math.round((new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime() - day0) / 86_400_000);
  if (diff === 0) return `היום ${hm}`;
  if (diff === 1) return `מחר ${hm}`;
  if (diff > 1 && diff < 7) return `יום ${DAY_SHORT[DAY_ORDER[d.getDay()]]} ${hm}`;
  return `${d.getDate()}.${d.getMonth() + 1} ${hm}`;
}

/** The next-run text of a schedule: "היום 18:00" or "היום 18:00 · בתנאי" (§6.5: conditions are never a promise). */
export function nextRunLabel(s: Pick<Schedule, 'next_run' | 'enabled'>, now: Date = new Date()): string {
  if (!s.enabled) return 'מושבת';
  if (!s.next_run) return 'אין הרצה קרובה';
  return s.next_run.conditional ? `${whenLabel(s.next_run.at, now)} · בתנאי` : whenLabel(s.next_run.at, now);
}

