/**
 * Live refresh: calls `onChange` when the server says schedules changed (`schedules_changed`, no ids) or a schedule
 * switch's state changed (`switch.schedule_*`, e.g. `triggered`), throttled to one call per second. It opens its own
 * `/ha/ws` socket (the frames are filtered by the caller's scope on the server). No-op in demo mode; returns a stop
 * function.
 */
export function subscribeSchedules(onChange: () => void, onSocket?: (connected: boolean) => void): () => void {
  if (!isApi()) return () => undefined;
  let ws: WebSocket | null = null;
  let stopped = false;
  let delay = 2000;
  let pending = 0;
  const fire = () => {
    if (pending) return;
    pending = window.setTimeout(() => {
      pending = 0;
      if (!stopped) onChange();
    }, 1000);
  };
  const url = (() => {
    const u = new URL(apiUrl('ha/ws'));
    u.protocol = u.protocol === 'https:' ? 'wss:' : 'ws:';
    return u.toString();
  })();
  const open = () => {
    if (stopped) return;
    try {
      ws = new WebSocket(url);
    } catch {
      return;
    }
    ws.onopen = () => {
      delay = 2000;
      onSocket?.(true);
    };
    ws.onmessage = (m) => {
      try {
        const env = JSON.parse(m.data as string) as { type: string; payload?: { entity?: { entity_id?: string } } };
        if (env.type === 'schedules_changed') fire();
        else if (env.type === 'entity_state_changed' && String(env.payload?.entity?.entity_id ?? '').startsWith('switch.schedule_')) fire();
      } catch {
        /* ignore malformed frames */
      }
    };
    ws.onclose = (ev) => {
      onSocket?.(false);
      if (!stopped && ev.code !== 4403 && ev.code !== 4401) {
        window.setTimeout(open, delay);
        delay = Math.min(30000, delay * 2);
      }
    };
  };
  open();
  return () => {
    stopped = true;
    if (pending) window.clearTimeout(pending);
    ws?.close();
  };
}

