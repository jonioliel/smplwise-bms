// ------------------------------------------------------------------------------------------------ helpers: unread, snooze, acknowledge (state machine)

export const isSnoozed = (n: Pick<Notification, 'me'>, now: number): boolean => !!n.me.snoozed_until && Date.parse(n.me.snoozed_until) > now;
/** Unread = not read by this user and not snoozed; the state of the condition does not matter (a resolved row nobody read is still news). */
export const isUnread = (n: Pick<Notification, 'me'>, now: number): boolean => n.me.read_at === null && !isSnoozed(n, now);
export const unreadCount = (rows: readonly Pick<Notification, 'me'>[], now: number): number => rows.filter((n) => isUnread(n, now)).length;
/** Open and critical: the avatar dot. A snoozed row still counts (snooze hides it from the unread count only). */
export const isOpenCritical = (n: Pick<Notification, 'severity' | 'state'>): boolean => n.severity === 'critical' && n.state === 'open';
export const openCriticalCount = (rows: readonly Pick<Notification, 'severity' | 'state'>[]): number => rows.filter(isOpenCritical).length;
/** The chip / dot numbers computed from rows (the server's `/notifications/summary`; the client's fallback). */
export function summarize(rows: readonly Notification[], now: number): NotifySummary {
  const by: Partial<Record<Category, number>> = {};
  for (const n of rows) if (isUnread(n, now)) by[n.category] = (by[n.category] ?? 0) + 1;
  return { unread: unreadCount(rows, now), open_critical: openCriticalCount(rows), by_category: by };
}

/** Shared state: open -> acknowledged -> resolved. An acknowledge of an acknowledged or resolved row changes nothing; a resolve ends any
 * state; a resolved row is final (a new signal creates a new row: the partial unique index of CR §12 covers unresolved rows only). */
export type StateEvent = 'ack' | 'resolve';
export function nextState(state: NotifyState, event: StateEvent): NotifyState {
  if (state === 'resolved') return 'resolved';
  if (event === 'resolve') return 'resolved';
  return 'acknowledged';
}
const iso = (ms: number) => new Date(ms).toISOString();
/** The instant a snooze ends: `60` = one hour from now; `until_morning` = the next end of the quiet window (`quiet.to`, 07:00 by default) in the
 * installation zone, strictly after now (at 03:00 it is 07:00 the same day, at 08:00 it is 07:00 tomorrow). */
export function snoozeUntil(choice: SnoozeChoice, now: number, quiet: Pick<QuietHours, 'to'> = { to: '07:00' }, tz?: string): string {
  if (choice === 60) return iso(now + 3_600_000);
  const to = hhmmToMin(quiet.to);
  const min = Number.isFinite(to) ? to : 7 * 60;
  const p = zoneParts(now, tz);
  let at = zonedToUtc(p.y, p.m, p.d, Math.floor(min / 60), min % 60, tz);
  if (at <= now) at = zonedToUtc(p.y, p.m, p.d + 1, Math.floor(min / 60), min % 60, tz);
  return iso(at);
}
export const applyRead = (n: Notification, now: number): Notification => (n.me.read_at ? n : { ...n, me: { ...n.me, read_at: iso(now) } });
export const applySnooze = (n: Notification, until: string): Notification => (n.state === 'resolved' ? n : { ...n, me: { ...n.me, snoozed_until: until } });
/** A user's acknowledge: only an open row the caller may acknowledge; also marks it read (the mockup's behaviour). */
export function applyAck(n: Notification, byDisplay: string, now: number): Notification {
  if (!n.can_ack || n.state !== 'open') return n;
  return {
    ...n, state: nextState(n.state, 'ack'), acked_at: iso(now), acked_by_display: byDisplay, me: { ...n.me, read_at: n.me.read_at ?? iso(now) },
    timeline: [...n.timeline, { at: iso(now), kind: 'acknowledged', by_display: byDisplay }],
  };
}
export function applyResolve(n: Notification, now: number): Notification {
  if (n.state === 'resolved') return n;
  return { ...n, state: 'resolved', resolved_at: iso(now), timeline: [...n.timeline, { at: iso(now), kind: 'resolved' }] };
}
/** A repeat folded into the row: `count` and `last_at` move, the timeline gets a `folded` entry whose `count` is the new total. */
export function applyFold(n: Notification, now: number): Notification {
  const count = n.count + 1;
  return { ...n, count, last_at: iso(now), timeline: [...n.timeline, { at: iso(now), kind: 'folded', count }] };
}

