/** Critical rows that are still open stay pinned at the top until acknowledged or resolved (CR §6.1). */
export const isPinned = (n: Pick<Notification, 'severity' | 'state'>): boolean => isOpenCritical(n);
const byLastDesc = (a: Notification, b: Notification) => Date.parse(b.last_at) - Date.parse(a.last_at);

export function dayLabel(at: string | number, now: number, tz?: string): string {
  const t = zoneParts(toMs(at), tz);
  const days = dayNumber(zoneParts(now, tz)) - dayNumber(t);
  if (days === 0) return 'היום';
  if (days === 1) return 'אתמול';
  return `יום ${WEEKDAY_NAME[t.wd]} ${t.d}.${t.m}`;
}
export interface DayGroup { key: string; label: string; rows: Notification[] }
export interface InboxLayout { pinned: Notification[]; days: DayGroup[] }
/** The center's list: the pinned critical rows first, then the rest grouped by the local day of `last_at`, newest first. */
export function layoutInbox(rows: readonly Notification[], now: number, tz?: string): InboxLayout {
  const sorted = [...rows].sort(byLastDesc);
  const pinned = sorted.filter(isPinned);
  const days: DayGroup[] = [];
  for (const n of sorted) {
    if (isPinned(n)) continue;
    const key = dayKey(zoneParts(Date.parse(n.last_at), tz));
    let g = days[days.length - 1];
    if (!g || g.key !== key) {
      g = { key, label: dayLabel(n.last_at, now, tz), rows: [] };
      days.push(g);
    }
    g.rows.push(n);
  }
  return { pinned, days };
}

export interface ConditionGroup {
  key: string;
  source: string;
  subject: Notification['subject'];
  rows: Notification[];
  /** The sum of the rows' `count` (occurrences of this condition). */
  total: number;
  severity: Severity;
  last_at: string;
  open: boolean;
  /** The newest row. */
  latest: Notification;
}
/** Rows of the same condition (source + subject) together: the folded-repeats view. Newest group first. */
export function groupByCondition(rows: readonly Notification[]): ConditionGroup[] {
  const map = new Map<string, Notification[]>();
  for (const n of rows) {
    const k = `${n.source}:${n.subject.kind}:${n.subject.id ?? ''}`;
    map.set(k, [...(map.get(k) ?? []), n]);
  }
  return [...map.entries()].map(([key, list]) => {
    const sorted = [...list].sort(byLastDesc);
    return {
      key, source: sorted[0].source, subject: sorted[0].subject, rows: sorted, total: sorted.reduce((s, n) => s + n.count, 0),
      severity: maxSeverity(sorted.map((n) => n.severity)) as Severity, last_at: sorted[0].last_at, open: sorted.some((n) => n.state === 'open'), latest: sorted[0],
    };
  }).sort((a, b) => Date.parse(b.last_at) - Date.parse(a.last_at));
}
export interface InboxView { filter?: InboxFilter; category?: Category | null; now: number }
/** The center's filters: all / unread / critical, plus the source filter (by category). */
