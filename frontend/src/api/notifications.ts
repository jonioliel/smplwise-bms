/** An ApiError of the notifications API (the mock and the client-side validators raise these). */
export function notifyError(code: string, details: Record<string, unknown> = {}, status: number = NOTIFY_ERROR_STATUS[code] ?? 400): ApiError {
  const body: ApiErrorBody = { code, user_message: NOTIFY_ERROR_LABEL[code] ?? code, retryable: status === 429, correlation_id: '', details };
  return new ApiError(status, body);
}
/** The code of an ApiError, or null. */
export const errorCode = (err: unknown): string | null => (err instanceof ApiError ? err.code : null);
/** Seconds to wait after a 429 (`details.retry_after_s`), or null. */
export function retryAfterS(err: unknown): number | null {
  if (!(err instanceof ApiError)) return null;
  const v = (err.body.details as { retry_after_s?: unknown } | undefined)?.retry_after_s;
  return typeof v === 'number' && Number.isFinite(v) ? v : null;
}
/** The Hebrew line of an error of this API: the table by code (a 429 names the wait), else the server's own message. */
export function notifyErrorText(err: unknown): string {
  if (err instanceof ApiError && NOTIFY_ERROR_LABEL[err.code]) {
    const wait = err.code === 'rate_limited' ? retryAfterS(err) : null;
    return wait !== null ? `יותר מדי נסיונות; נסו שוב בעוד ${Math.max(1, Math.ceil(wait))} שניות` : NOTIFY_ERROR_LABEL[err.code];
  }
  return describeError(err);
}
export type ErrorContext = 'item' | 'ack' | 'action' | 'settings' | 'policy' | 'email' | 'email_test' | 'admin' | 'user';
/** A response without a code of its own (`http_<n>`) gets the contract's code for that status on that kind of route; a coded response is
 * returned untouched. */
export function mapNotifyError(err: unknown, ctx: ErrorContext): unknown {
  if (!(err instanceof ApiError) || !err.code.startsWith('http_')) return err;
  const s = err.status;
  const admin = ctx === 'settings' || ctx === 'policy' || ctx === 'email' || ctx === 'email_test' || ctx === 'admin';
  let code: string | null = null;
  if (s === 429) code = 'rate_limited';
  else if (s === 401 && ctx === 'action') code = 'action_token_invalid';
  else if (s === 403) code = admin ? 'forbidden' : ctx === 'ack' ? 'ack_not_allowed' : 'forbidden';
  else if (s === 404 && (ctx === 'item' || ctx === 'ack')) code = 'notification_not_found';
  else if (s === 412 && (ctx === 'settings' || ctx === 'policy')) code = 'settings_conflict';
  else if (s === 409 && (ctx === 'email' || ctx === 'email_test')) code = 'channel_unavailable';
  if (!code) return err;
  return new ApiError(s, { ...err.body, code, user_message: NOTIFY_ERROR_LABEL[code] ?? err.body.user_message });
}

// ------------------------------------------------------------------------------------------------ time in the installation zone

/** Every time helper takes an explicit IANA zone (the installation's `time.zone`); `undefined` = the runtime's own zone. */
interface ZoneParts { y: number; m: number; d: number; h: number; mi: number; wd: number }
const formatters = new Map<string, Intl.DateTimeFormat>();
function zoneParts(ms: number, tz?: string): ZoneParts {
  const k = tz ?? '';
  let f = formatters.get(k);
  if (!f) {
    f = new Intl.DateTimeFormat('en-US', { timeZone: tz, hourCycle: 'h23', year: 'numeric', month: 'numeric', day: 'numeric', hour: 'numeric', minute: 'numeric', weekday: 'short' });
    formatters.set(k, f);
  }
  const o: Record<string, string> = {};
  for (const p of f.formatToParts(new Date(ms))) o[p.type] = p.value;
  return { y: Number(o.year), m: Number(o.month), d: Number(o.day), h: Number(o.hour) % 24, mi: Number(o.minute), wd: ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'].indexOf(o.weekday) };
}
/** The instant at which the zone's wall clock reads y-m-d h:mi (m 1-12; d / h may overflow and are normalised). */
function zonedToUtc(y: number, m: number, d: number, h: number, mi: number, tz?: string): number {
  const guess = Date.UTC(y, m - 1, d, h, mi);
  const off = (t: number) => {
    const p = zoneParts(t, tz);
    return Date.UTC(p.y, p.m - 1, p.d, p.h, p.mi) - Math.floor(t / 60000) * 60000;
  };
  const t1 = guess - off(guess);
  const t2 = guess - off(t1);
  return t2;
}
const pad2 = (n: number) => String(n).padStart(2, '0');
/** "HH:MM" of an instant in the zone. */
export function clockText(at: number | string, tz?: string): string {
  const p = zoneParts(typeof at === 'number' ? at : Date.parse(at), tz);
  return `${pad2(p.h)}:${pad2(p.mi)}`;
}
const dayNumber = (p: ZoneParts) => Math.floor(Date.UTC(p.y, p.m - 1, p.d) / 86400000);
const dayKey = (p: ZoneParts) => `${p.y}-${pad2(p.m)}-${pad2(p.d)}`;
/** "HH:MM" -> minutes since midnight, NaN when malformed. */
export function hhmmToMin(s: string): number {
  const m = /^(\d{1,2}):(\d{2})$/.exec(s);
  if (!m || Number(m[1]) > 23 || Number(m[2]) > 59) return NaN;
  return Number(m[1]) * 60 + Number(m[2]);
}
const toMs = (at: number | string | Date): number => (typeof at === 'number' ? at : at instanceof Date ? at.getTime() : Date.parse(at));

/** "עכשיו", "לפני 12 דק׳", "14:02" (earlier today), "אתמול 21:15", "לפני 3 ימים". */
export function relativeTime(at: string | number, now: number, tz?: string): string {
  const t = toMs(at);
  const diff = now - t;
  if (diff < 60_000) return 'עכשיו';
  const days = dayNumber(zoneParts(now, tz)) - dayNumber(zoneParts(t, tz));
  if (days === 0) return diff < 3_600_000 ? `לפני ${Math.floor(diff / 60_000)} דק׳` : clockText(t, tz);
  if (days === 1) return `אתמול ${clockText(t, tz)}`;
  return `לפני ${days} ימים`;
}

