export type DoorOpenPhase = 'idle' | 'confirm' | 'sending' | 'step_up' | 'done' | 'failed';
export interface DoorOpenState {
  phase: DoorOpenPhase;
  notification_id: string | null;
  door: { id: string; name: string } | null;
  /** The failure's code, or null. */
  error: string | null;
  /** The line to show after `done` / `failed`. */
  text: string | null;
}
export const DOOR_OPEN_IDLE: DoorOpenState = { phase: 'idle', notification_id: null, door: null, error: null, text: null };
export type DoorOpenEvent =
  | { type: 'press'; notification: Pick<Notification, 'id' | 'state' | 'door'> }
  | { type: 'confirm' }
  | { type: 'cancel' }
  | { type: 'accepted' }
  | { type: 'error'; code: string }
  | { type: 'step_up_done' }
  | { type: 'dismiss' };
/** The button is shown only on a doorbell row that is not resolved, to a caller who may open that door (`door.can_open`, computed by the server). */
export const doorButtonVisible = (n: Pick<Notification, 'door' | 'state'>): boolean => !!n.door && n.door.can_open && n.state !== 'resolved';
export const doorOpenQuestion = (name: string): string => `האם אתה בטוח שברצונך לפתוח את ${name}?`;
export const doorOpenResultText = (name: string): string => `הפקודה נשלחה אל ${name}`;
export const doorOpenBusy = (s: DoorOpenState): boolean => s.phase === 'sending';
const DOOR_ERROR_TEXT: Record<string, string> = { ...NOTIFY_ERROR_LABEL, forbidden: 'אין הרשאה לפתוח את הדלת' };
/** The flow: a press only OPENS the confirmation; nothing is sent until `confirm` follows it (and `step_up_done` after a step-up); the notification
 * never opens a door by itself. A press on a row without `door.can_open` is ignored (no button exists for that user); `cancel` is not possible while a
 * command is in flight. */
export function reduceDoorOpen(s: DoorOpenState, e: DoorOpenEvent): DoorOpenState {
  switch (e.type) {
    case 'press':
      if (s.phase === 'sending' || s.phase === 'confirm' || s.phase === 'step_up') return s;
      if (!doorButtonVisible(e.notification) || !e.notification.door) return s;
      return { phase: 'confirm', notification_id: e.notification.id, door: { id: e.notification.door.id, name: e.notification.door.name }, error: null, text: null };
    case 'confirm': return s.phase === 'confirm' ? { ...s, phase: 'sending' } : s;
    case 'step_up_done': return s.phase === 'step_up' ? { ...s, phase: 'sending', error: null } : s;
    case 'cancel': return s.phase === 'confirm' || s.phase === 'step_up' ? DOOR_OPEN_IDLE : s;
    case 'accepted': return s.phase === 'sending' && s.door ? { ...s, phase: 'done', error: null, text: doorOpenResultText(s.door.name) } : s;
    case 'error':
      if (s.phase !== 'sending') return s;
      return e.code === 'step_up_required' ? { ...s, phase: 'step_up', error: e.code, text: null } : { ...s, phase: 'failed', error: e.code, text: DOOR_ERROR_TEXT[e.code] ?? 'הפתיחה נכשלה' };
    case 'dismiss': return s.phase === 'done' || s.phase === 'failed' ? DOOR_OPEN_IDLE : s;
  }
}
/** Runs the one command of a flow that reached `sending` (through the existing release route, origin `notification:<id>`) and feeds the result back. A state
 * in any other phase sends nothing. Returns the final state. */
export async function runDoorOpen(adapter: Pick<NotifyAdapter, 'openDoor'>, state: DoorOpenState, onState: (s: DoorOpenState) => void = () => undefined): Promise<DoorOpenState> {
  if (state.phase !== 'sending' || !state.door || !state.notification_id) return state;
  let next: DoorOpenState;
  try {
    await adapter.openDoor(state.notification_id, state.door.id);
    next = reduceDoorOpen(state, { type: 'accepted' });
  } catch (err) {
    next = reduceDoorOpen(state, { type: 'error', code: errorCode(err) ?? 'failed' });
  }
  onState(next);
  return next;
}

