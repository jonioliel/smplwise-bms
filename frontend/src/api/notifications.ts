/** One implementation per transport: HTTP (the real backend) or the in-memory mock. Same shapes, same errors. `read`, `readAll`, `snooze` and `ack`
 * answer the updated row when the server sends one, else null (apply `applyRead` / `applySnooze` / `applyAck` and refetch the summary). */
export interface NotifyAdapter {
  // every signed-in user
  list(q?: InboxQuery): Promise<InboxPage>;
  summary(): Promise<NotifySummary>;
  read(id: string): Promise<Notification | null>;
  readAll(): Promise<void>;
  snooze(id: string, choice: SnoozeChoice): Promise<Notification | null>;
  /** 403 `ack_not_allowed` unless the row's `can_ack`. */
  ack(id: string): Promise<Notification | null>;
  /** An <img src> for the row's snapshot (same origin, session cookie); null when the row has none. Fetched only inside Arx. */
  snapshotUrl(id: string): string | null;
  /** A test push to the caller's own devices (3/min). */
  test(): Promise<{ sent: number }>;
  deliveries(notificationId?: string): Promise<Delivery[]>;
  /** The push action endpoint (no session): the one-time token authorises exactly `ack` or `snooze` on one row. */
  action(token: string, action: 'ack' | 'snooze'): Promise<void>;
  /** Runs AFTER the in-app confirmation: the existing door release with the notification as its origin. Never called by a notification surface itself. */
  openDoor(notificationId: string, doorId: string): Promise<void>;
  // notify.manage
  settings(): Promise<NotifySettings>;
  saveSettings(body: SettingsBody, baseRevision: number): Promise<NotifySettings>;
  policies(): Promise<NotifyPolicy[]>;
  savePolicy(source: string, body: PolicyBody, baseRevision: number): Promise<NotifyPolicy>;
  saveEmail(body: EmailBody): Promise<EmailSettings>;
  testEmail(): Promise<EmailTestResult>;
  adminDeliveries(q?: DeliveryQuery): Promise<Delivery[]>;
  stats(): Promise<NotifyStats>;
}

const enc = encodeURIComponent;
const qs = (q: Record<string, string | number | undefined>) => {
  const p = new URLSearchParams();
  for (const [k, v] of Object.entries(q)) if (v !== undefined && v !== '') p.set(k, String(v));
  const s = p.toString();
  return s ? `?${s}` : '';
};
/** Accepts `[...]` or `{ [key]: [...] }`. */
const rows = <T>(r: unknown, key: string): T[] => (Array.isArray(r) ? (r as T[]) : (((r as Record<string, unknown> | null)?.[key] as T[] | undefined) ?? []));
/** The updated row when the reply is one, else null. */
const rowOrNull = (r: unknown): Notification | null => (r && typeof r === 'object' && typeof (r as Notification).id === 'string' && 'state' in (r as object) ? (r as Notification) : null);
async function call<T>(ctx: ErrorContext, fn: () => Promise<T>): Promise<T> {
  try { return await fn(); } catch (err) { throw mapNotifyError(err, ctx); }
}
const DEFAULT_PAGE = 50;
const commandEnvelope = () => ({ client_request_id: commandId(), expires_at: new Date(Date.now() + 15_000).toISOString().replace(/\.\d{3}Z$/, 'Z') });

export const httpNotify: NotifyAdapter = {
  list: (q = {}) => call('user', async () => {
    const limit = q.limit ?? DEFAULT_PAGE;
    const list = rows<Notification>(await get<unknown>(`notifications${qs({ state: q.state, category: q.category, severity_min: q.severity_min, before: q.before, limit })}`), 'notifications');
    return { notifications: list, next_before: list.length >= limit ? list[list.length - 1].last_at : null };
  }),
  summary: () => call('user', () => get<NotifySummary>('notifications/summary')),
  read: (id) => call('item', async () => rowOrNull(await post<unknown>(`notifications/${enc(id)}/read`))),
  readAll: () => call('user', async () => { await post('notifications/read-all'); }),
  snooze: (id, minutes) => call('item', async () => rowOrNull(await post<unknown>(`notifications/${enc(id)}/snooze`, { minutes }))),
  ack: (id) => call('ack', async () => rowOrNull(await post<unknown>(`notifications/${enc(id)}/ack`))),
  snapshotUrl: (id) => apiUrl(`notifications/${enc(id)}/snapshot`),
  test: () => call('user', () => post<{ sent: number }>('notifications/test')),
  deliveries: (id) => call('user', async () => rows<Delivery>(await get<unknown>(`notifications/deliveries${qs({ notification_id: id })}`), 'deliveries')),
  action: (t, a) => call('action', async () => { await post('notifications/action', { t, a }); }),
  // the existing WisKey release route (routers/access_control.py): `confirmed` is sent only after the in-app confirmation; `origin` names the notification
  openDoor: (notificationId, doorId) => call('user', async () => { await post(`intercom/stations/${enc(doorId)}/release`, { confirmed: true, origin: `notification:${notificationId}`, ...commandEnvelope() }); }),
  settings: () => call('settings', () => get<NotifySettings>('notify/settings')),
  saveSettings: (body, base) => call('settings', () => api<NotifySettings>('notify/settings', { method: 'PUT', body: JSON.stringify({ ...body, base_revision: base }), headers: { 'If-Match': String(base) } })),
  policies: () => call('policy', async () => rows<NotifyPolicy>(await get<unknown>('notify/policies'), 'policies')),
  savePolicy: (source, body, base) => call('policy', () => api<NotifyPolicy>(`notify/policies/${enc(source)}`, { method: 'PUT', body: JSON.stringify({ ...body, base_revision: base }), headers: { 'If-Match': String(base) } })),
  saveEmail: (body) => call('email', () => put<EmailSettings>('notify/email', body)),
  testEmail: () => call('email_test', () => post<EmailTestResult>('notify/email/test')),
  adminDeliveries: (q = {}) => call('admin', async () => rows<Delivery>(await get<unknown>(`notify/deliveries${qs({ status: q.status, channel: q.channel, since: q.since, limit: q.limit })}`), 'deliveries')),
  stats: () => call('admin', () => get<NotifyStats>('notify/stats')),
};

/** The mock behind a dynamic import: the two modules never import each other statically (the mock reuses this file's helpers). Same selector as the
 * media clients (`isApi() ? http : mock`). */
const mockAdapter = (): Promise<NotifyAdapter> => import('./notifications-mock').then((m) => m.notifyMock());
function lazyMock(): NotifyAdapter {
  const m = (): Promise<NotifyAdapter> => mockAdapter();
  return {
    list: async (q) => (await m()).list(q), summary: async () => (await m()).summary(), read: async (id) => (await m()).read(id), readAll: async () => (await m()).readAll(),
    snooze: async (id, c) => (await m()).snooze(id, c), ack: async (id) => (await m()).ack(id),
    // the one synchronous method: the mock's snapshot is a data URI built from the id (no store needed)
    snapshotUrl: (id) => `data:image/svg+xml;utf8,${enc(`<svg xmlns="http://www.w3.org/2000/svg" width="320" height="180"><rect width="320" height="180" fill="#cfd8e3"/><text x="160" y="95" text-anchor="middle" font-size="14" fill="#5a6b7d">${id}</text></svg>`)}`,
    test: async () => (await m()).test(), deliveries: async (id) => (await m()).deliveries(id), action: async (t, a) => (await m()).action(t, a),
    openDoor: async (n, d) => (await m()).openDoor(n, d), settings: async () => (await m()).settings(), saveSettings: async (b, r) => (await m()).saveSettings(b, r),
    policies: async () => (await m()).policies(), savePolicy: async (s, b, r) => (await m()).savePolicy(s, b, r), saveEmail: async (b) => (await m()).saveEmail(b),
    testEmail: async () => (await m()).testEmail(), adminDeliveries: async (q) => (await m()).adminDeliveries(q), stats: async () => (await m()).stats(),
  };
}
let lazy: NotifyAdapter | null = null;
/** The adapter in force: HTTP with a backend, the mock otherwise. */
export const notify = (): NotifyAdapter => (isApi() ? httpNotify : (lazy ??= lazyMock()));
