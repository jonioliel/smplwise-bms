export interface DeliveryLine { tone: 'ok' | 'bad' | 'held' | 'pending'; text: string; at: string | null }
/** The detail view's "my delivery" line: "נשלח לטלפון · 14:02" / "לא נשלח · שעות שקט" / "המסירה לטלפון נכשלה · 14:02". Sent wins over a failure on another
 * channel; null when nothing was attempted (a source without push). The inbox itself (the center) is never a delivery line. */
export function deliveryLine(n: Pick<Notification, 'my_deliveries'>, tz?: string): DeliveryLine | null {
  const list = n.my_deliveries.filter((d) => d.channel !== 'inbox');
  if (!list.length) return null;
  const newest = (xs: typeof list) => [...xs].sort((a, b) => Date.parse(b.at) - Date.parse(a.at))[0];
  const sent = list.filter((d) => d.status === 'sent');
  if (sent.length) { const d = newest(sent); return { tone: 'ok', text: `נשלח ${channelTo(d.channel)} · ${clockText(d.at, tz)}`, at: d.at }; }
  const failed = list.filter((d) => isFailed(d.status));
  if (failed.length) { const d = newest(failed); return { tone: 'bad', text: `המסירה ${channelTo(d.channel)} נכשלה · ${clockText(d.at, tz)}`, at: d.at }; }
  const pending = list.filter((d) => d.status === 'queued' || d.status === 'retry');
  if (pending.length) { const d = newest(pending); return { tone: 'pending', text: d.status === 'retry' ? 'ינסה שוב' : 'ממתין לשליחה', at: d.at }; }
  const d = newest(list);
  return { tone: 'held', text: d.reason === 'quiet_hours' ? 'לא נשלח · שעות שקט' : `לא נשלח${d.reason ? ` · ${deliveryReasonText(d.reason)}` : ''}`, at: d.at };
}
/** The small chip on a row: a failed delivery or a held one (quiet hours); null otherwise. */
