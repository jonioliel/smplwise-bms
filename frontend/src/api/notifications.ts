export interface TimelineLine {
  kind: TimelineEntry['kind'] | 'pending' | 'now';
  /** The instant (ISO), or null for the "waiting for acknowledge" line. */
  at: string | null;
  /** "14:07" in the zone ('' when there is no instant). */
  clock: string;
  title: string;
  sub: string;
  pending: boolean;
}
/** The detail view's timeline ("ציר ההסלמה" for a critical row): what the server recorded (created, folded, escalated, delivery failed,
 * acknowledged, resolved), then, while a critical row is open and escalation is on, one pending line per step still to come at
 * `first_at + step * after_min`, then "ממתין לאישור" when nothing is pending. Rows below critical never escalate. */
export function escalationTimeline(n: Notification, esc: EscalationSettings | null, now: number, tz?: string): TimelineLine[] {
  const out: TimelineLine[] = [];
  const line = (kind: TimelineLine['kind'], at: string | null, title: string, sub = '', pending = false): void => {
    out.push({ kind, at, clock: at ? clockText(at, tz) : '', title, sub, pending });
  };
  const critical = n.severity === 'critical';
  for (const e of [...n.timeline].sort((a, b) => Date.parse(a.at) - Date.parse(b.at))) {
    switch (e.kind) {
      case 'created': line('created', e.at, 'נוצרה'); break;
      case 'folded': line('folded', e.at, `חזרה ${e.count ? `×${e.count}` : ''}`.trim()); break;
      case 'escalated': line('escalated', e.at, `הסלמה ${e.step ?? ''} · נשלח שוב ל־${e.count ?? 0} מנהלים`.replace('  ', ' '), esc && e.step ? `${esc.after_min * e.step} דק׳ בלי אישור · דחיפה דחופה` : ''); break;
      case 'delivery_failed': line('delivery_failed', e.at, e.channel ? `המסירה ${channelTo(e.channel)} נכשלה` : 'המסירה נכשלה', 'ההתראה במרכז'); break;
      case 'acknowledged': line('acknowledged', e.at, `אושר · ${e.by_display ?? ''}`.replace(/ · $/, ''), critical ? 'ההסלמה נעצרה' : ''); break;
      case 'resolved': line('resolved', e.at, 'נפתר'); break;
    }
  }
  let pendingShown = false;
  if (n.state === 'open' && critical && esc?.enabled) {
    const done = n.timeline.filter((e) => e.kind === 'escalated').length;
    const first = Date.parse(n.first_at);
    for (let step = done + 1; step <= esc.steps; step++) {
      const at = first + step * esc.after_min * 60_000;
      const mins = Math.ceil((at - now) / 60_000);
      line('pending', iso(at), mins > 0 ? `הסלמה ${step} בעוד ${mins} דק׳` : `הסלמה ${step} ממתינה`, step === esc.steps ? 'השלב האחרון' : '', true);
      pendingShown = true;
    }
  }
  if (n.state === 'open' && !pendingShown) line('now', null, 'ממתין לאישור');
  return out;
}
