// ------------------------------------------------------------------------------------------------ helpers: quiet hours and the pass-through matrix (CR §8.1)

export interface QuietWindow { active: boolean; /** The instant the active window ends (ISO), else null. */ until: string | null }
/** Whether `now` is inside the installation's quiet window. A window that crosses midnight belongs to the day it STARTS on (22:00-07:00 with
 * "fri" ticked is quiet from Friday 22:00 to Saturday 07:00); from == to is empty; an empty day list never goes quiet. */
export function quietWindow(q: QuietHours, now: number, tz?: string): QuietWindow {
  const from = hhmmToMin(q.from);
  const to = hhmmToMin(q.to);
  if (!q.enabled || !Number.isFinite(from) || !Number.isFinite(to) || from === to || !q.days.length) return { active: false, until: null };
  const p = zoneParts(now, tz);
  const t = p.h * 60 + p.mi;
  const today = WEEKDAYS[p.wd];
  const yesterday = WEEKDAYS[(p.wd + 6) % 7];
  const endAt = (dayOffset: number) => iso(zonedToUtc(p.y, p.m, p.d + dayOffset, Math.floor(to / 60), to % 60, tz));
  if (from < to) return t >= from && t < to && q.days.includes(today) ? { active: true, until: endAt(0) } : { active: false, until: null };
  if (t >= from) return q.days.includes(today) ? { active: true, until: endAt(1) } : { active: false, until: null };
  if (t < to) return q.days.includes(yesterday) ? { active: true, until: endAt(0) } : { active: false, until: null };
  return { active: false, until: null };
}
export const isQuietNow = (q: QuietHours, now: number, tz?: string): boolean => quietWindow(q, now, tz).active;
export interface PassDecision { send: boolean; reason: 'quiet_hours' | null }
/** The pass-through matrix: outside quiet hours everything is sent; inside, the center always receives, push / email / Companion follow the severity x
 * channel matrix, a reserved channel without a matrix column (whatsapp, app) is held, and an ESCALATION step bypasses quiet hours (CR §8.3). */
export function passThrough(settings: Pick<NotifySettings, 'quiet' | 'pass_through'>, severity: Severity, channel: Channel, now: number, tz?: string, opts: { escalation?: boolean } = {}): PassDecision {
  if (channel === 'inbox' || opts.escalation || !isQuietNow(settings.quiet, now, tz)) return { send: true, reason: null };
  const col = settings.pass_through[severity] as Record<string, boolean | undefined>;
  return col[channel] === true ? { send: true, reason: null } : { send: false, reason: 'quiet_hours' };
}
export interface ChannelDecision { channel: Channel; send: boolean; reason: string | null }
/** What a notification of `severity` would do on each channel of its policy now (the settings preview and the specs): `category_off` for a channel the
 * policy has off, `channel_unavailable` for email that is not configured, `quiet_hours` from the matrix. The center is always `send`. */
export function planChannels(settings: Pick<NotifySettings, 'quiet' | 'pass_through' | 'email'>, policy: Pick<NotifyPolicy, 'channels'>, severity: Severity, now: number, tz?: string, opts: { escalation?: boolean } = {}): ChannelDecision[] {
  const out: ChannelDecision[] = [{ channel: 'inbox', send: true, reason: null }];
  for (const channel of EDITABLE_CHANNELS) {
    if (!policy.channels[channel as 'webpush' | 'email']) { out.push({ channel, send: false, reason: 'category_off' }); continue; }
    if (channel === 'email' && !settings.email.configured) { out.push({ channel, send: false, reason: 'channel_unavailable' }); continue; }
    const d = passThrough(settings, severity, channel, now, tz, opts);
    out.push({ channel, send: d.send, reason: d.reason });
  }
  return out;
}
/** "שעות שקט עד 07:00 · נשלח רק קריטי" while the window is active, else null. */
export function quietBannerText(settings: Pick<NotifySettings, 'quiet' | 'pass_through'>, now: number, tz?: string): string | null {
  const w = quietWindow(settings.quiet, now, tz);
  if (!w.active || !w.until) return null;
  const passing = SEVERITIES.filter((s) => Object.values(settings.pass_through[s]).some(Boolean));
  const what = passing.length === 0 ? 'לא נשלח דבר' : passing.length === SEVERITIES.length ? 'נשלח הכול' : `נשלח רק ${passing.slice().reverse().map((s) => SEVERITY_LABEL[s]).join(', ')}`;
  return `שעות שקט עד ${clockText(w.until, tz)} · ${what}`;
}

