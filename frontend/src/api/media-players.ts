export interface JoinDiff { join: string[]; leave: string[]; stay: string[] }
/** Current members vs. the wanted ones (the leader is never in either; duplicates dropped): who joins, who leaves, who stays.
 * The same diff serves the ticked rooms of the panel and a saved group's "הפעל" (unjoin the extras, join the missing). */
export function joinDiff(current: readonly string[], desired: readonly string[], leaderKey?: string): JoinDiff {
  const clean = (l: readonly string[]) => [...new Set(l)].filter((k) => k !== leaderKey);
  const cur = clean(current);
  const want = clean(desired);
  return { join: want.filter((k) => !cur.includes(k)), leave: cur.filter((k) => !want.includes(k)), stay: cur.filter((k) => want.includes(k)) };
}

/** The ticks of the group section between two sends (`JOIN_BATCH_MS` of quiet, then one request): a second tick of the
 * same room cancels the first. `isMember` = whether the room is in the group right now. */
export class JoinDraft {
  private add = new Set<string>();
  private remove = new Set<string>();
  toggle(key: string, isMember: boolean): void {
    const set = isMember ? this.remove : this.add;
    if (!set.delete(key)) set.add(key);
  }
  /** The room has an unsent change (spinner). */
  has(key: string): boolean {
    return this.add.has(key) || this.remove.has(key);
  }
  get size(): number {
    return this.add.size + this.remove.size;
  }
  get additions(): number {
    return this.add.size;
  }
  /** The members after the draft is applied to `current`. */
  desired(current: readonly string[]): string[] {
    return [...new Set([...current.filter((k) => !this.remove.has(k)), ...this.add])];
  }
  diff(current: readonly string[], leaderKey?: string): JoinDiff {
    return joinDiff(current, this.desired(current), leaderKey);
  }
  clear(): void {
    this.add.clear();
    this.remove.clear();
  }
}

