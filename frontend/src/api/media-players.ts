export function playerSections(devices: readonly PlayerDevice[], opts: { floors: boolean; order?: readonly string[]; floorOrder?: readonly string[] }): PlayerSection[] {
  const rank = new Map((opts.order ?? []).map((k, i) => [k, i]));
  const byOrder = (a: PlayerDevice, b: PlayerDevice) => (rank.get(a.key) ?? 1e6) - (rank.get(b.key) ?? 1e6) || a.name.localeCompare(b.name, 'he');
  const { placed, unplaced } = unplacedBucket(devices);
  const out: PlayerSection[] = [];
  if (opts.floors) {
    const ids = [...new Set(placed.map((d) => d.floor_id ?? 'none'))];
    const fr = new Map((opts.floorOrder ?? []).map((f, i) => [f, i]));
    ids.sort((a, b) => (fr.get(a) ?? 1e6) - (fr.get(b) ?? 1e6));
    for (const id of ids) {
      const ds = placed.filter((d) => (d.floor_id ?? 'none') === id).sort(byOrder);
      out.push({ id, label: ds[0].floor_name ?? ds[0].area_name ?? UNPLACED_LABEL, devices: ds });
    }
  } else if (placed.length) {
    out.push({ id: 'all', label: ALL_ROOMS_LABEL, devices: [...placed].sort(byOrder) });
  }
  if (unplaced.length) out.push({ id: 'none', label: UNPLACED_LABEL, devices: [...unplaced].sort(byOrder) });
  return out;
}

/** The room chips (the area filter): one per area with its count, "ללא חדר" last when something is unplaced. */
export function roomChips(devices: readonly Pick<PlayerDevice, 'area_id' | 'area_name'>[]): { id: string; name: string; count: number }[] {
  const by = new Map<string, { id: string; name: string; count: number }>();
  for (const d of devices) {
    if (d.area_id === null) continue;
    const c = by.get(d.area_id) ?? { id: d.area_id, name: d.area_name ?? d.area_id, count: 0 };
    c.count += 1;
    by.set(d.area_id, c);
  }
  const chips = [...by.values()].sort((a, b) => a.name.localeCompare(b.name, 'he'));
  const none = devices.filter((d) => d.area_id === null).length;
  return none ? [...chips, { id: 'none', name: NO_ROOM_LABEL, count: none }] : chips;
}

