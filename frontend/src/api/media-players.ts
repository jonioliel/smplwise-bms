/** Whether the UI should offer a command at all (the server re-checks everything). Greyed, never guessed, without `caps_known`. */
export function playerCommandOffered(d: Pick<PlayerDevice, 'live' | 'caps' | 'can' | 'zones'>, c: PlayerCommand): boolean {
  const { live, caps, can } = d;
  if (!live.caps_known || isDead(live)) return false;
  const power = c.command === 'power_on' || c.command === 'power_off' || c.command === 'source' || c.command === 'sound_output';
  if (power ? !can.power : !can.control) return false;
  // a second zone: its own state, and only the commands it accepts
  const zone = c.zone && d.zones && c.zone !== d.zones[0]?.id ? d.zones.find((z) => z.id === c.zone) ?? null : null;
  if (c.zone && d.zones && c.zone !== d.zones[0]?.id) {
    if (!zone || !ZONE2_COMMANDS.includes(c.command)) return false;
    if (c.command === 'power_on') return caps.power_on && zone.power !== 'on';
    if (c.command === 'power_off') return caps.power_off && zone.power === 'on';
    if (zone.power !== 'on') return false;
  } else {
    if (c.command === 'power_on') return caps.power_on && live.power !== 'on';
    if (c.command === 'power_off') return caps.power_off && isOn(live);
    if (!isOn(live)) return false;
  }
  switch (c.command) {
    case 'volume_set': return caps.volume_set && c.level >= 0 && c.level <= 100;
    case 'volume_step': return caps.volume_step;
    case 'mute': return caps.mute;
    case 'source': return caps.sources;
    case 'sound_output': return caps.sound_outputs.includes(c.output);
    case 'transport': return c.action === 'play_pause' ? caps.transport.play || caps.transport.pause : c.action === 'previous' ? caps.transport.previous : caps.transport[c.action];
    case 'seek': return caps.transport.seek && live.now.duration_s !== null && c.position_s >= 0 && c.position_s <= live.now.duration_s;
    case 'shuffle': return caps.shuffle;
    case 'repeat': return caps.repeat;
    case 'play_item': return (caps.favourites || caps.stations || caps.playlists) && ITEM_REF_RE.test(c.item_ref);
    case 'transfer': return caps.transfer && c.from_key.length > 0;
    default: return false; // keys / text / app: not a player thing
  }
}

/** The library tabs the panel shows, in order: per the device's caps, the provider (Sonos has no playlists) and the
 * administrator's `kinds_on`. Empty = no library at all (the panel has no tabs, "הבא בתור" reads "לא זמין"). */
export function libraryTabs(d: Pick<PlayerDevice, 'caps' | 'music_provider'>, kindsOn: readonly LibraryKind[] | null = null): LibraryKind[] {
  if (d.music_provider === 'none') return [];
  const tabs: LibraryKind[] = [];
  if (d.caps.favourites) tabs.push('favourites');
  if (d.caps.stations) tabs.push('stations');
  if (d.caps.playlists && d.music_provider !== 'sonos') tabs.push('playlists');
  return kindsOn ? tabs.filter((k) => kindsOn.includes(k)) : tabs;
}
export const LIBRARY_TAB_LABEL: Record<LibraryKind, string> = { favourites: 'מועדפים', stations: 'תחנות', playlists: 'פלייליסטים' };

/** The curation applied to a page (hidden items out, the administrator's order first, the rest in the server's order). */
export function applyCuration(items: readonly LibraryItem[], c: Pick<FavouritesCuration, 'items'> | null): LibraryItem[] {
  if (!c || !c.items.length) return [...items];
  const by = new Map(c.items.map((i) => [i.item_ref, i]));
  const rank = (i: LibraryItem) => by.get(i.item_ref)?.order ?? 1e6;
  return items.filter((i) => !by.get(i.item_ref)?.hidden).map((i, n) => ({ i, n })).sort((a, b) => rank(a.i) - rank(b.i) || a.n - b.n).map((x) => x.i);
}
