/** The Hebrew line of an error of the players API: the table above by code, else the server's own message. */
export function playerErrorText(err: unknown): string {
  if (err instanceof ApiError) {
    const reason = (err.body.details as { reason?: unknown } | undefined)?.reason;
    const byReason = typeof reason === 'string' ? REASON_LABEL[`${err.code}:${reason}`] : undefined;
    if (byReason) return byReason;
  }
  if (err instanceof ApiError && PLAYER_ERROR_LABEL[err.code]) return PLAYER_ERROR_LABEL[err.code];
  return describeError(err);
}
/** The code of an ApiError, or null. */
export const errorCode = (err: unknown): string | null => (err instanceof ApiError ? err.code : null);
/** 409 `confirm_required` -> the preview to show in the confirmation dialog (from `details.preview`, or the body itself); else null. */
export function confirmPreview(err: unknown): GroupPreview | null {
  if (!(err instanceof ApiError) || err.code !== 'confirm_required') return null;
  const body = err.body as unknown as { details?: { preview?: GroupPreview }; preview?: GroupPreview };
  return body.details?.preview ?? body.preview ?? null;
}

/** 409 `confirm_required` of a queue `clear` -> how many rows it would remove (`details.count`); else null. */
export function confirmCount(err: unknown): number | null {
  if (!(err instanceof ApiError) || err.code !== 'confirm_required') return null;
  const c = (err.body.details as { count?: unknown } | undefined)?.count;
  return typeof c === 'number' ? c : null;
}

