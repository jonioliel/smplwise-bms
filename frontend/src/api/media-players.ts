const hhmm = (s: string): number => {
  const m = /^(\d{1,2}):(\d{2})$/.exec(s);
  return m ? Number(m[1]) * 60 + Number(m[2]) : NaN;
};
/** Whether `now` (local time) is inside the night window; a window that crosses midnight (22:00 - 07:00) works; from == to is empty. */
export function inNightWindow(night: VolumeNight | null, now: Date = new Date()): boolean {
  if (!night) return false;
  const from = hhmm(night.from);
  const to = hhmm(night.to);
  if (!Number.isFinite(from) || !Number.isFinite(to) || from === to) return false;
  const t = now.getHours() * 60 + now.getMinutes();
  return from < to ? t >= from && t < to : t >= from || t < to;
}
/** Unmuting reveals the level the device was muted at: when a ceiling (or a night window) set LATER is below it the server refuses (422 `not_supported`, reason
 * `ceiling`). Returns the ceiling the level must be lowered to first, else null (the unmute can go as it is). */
export function unmuteCeiling(d: Pick<PlayerDevice, 'volume_max' | 'volume_night' | 'live'>, now: Date = new Date()): number | null {
  const c = effectiveCeiling(d, now);
  const level = d.live.volume.level;
  return c !== null && (level === null || level > c) ? c : null;
}

/** The ceiling in force right now: the lower of `volume_max` and the night window's max inside the window - only where an
 * administrator set them (decision 7ב: no default, so null = no ceiling and nothing is clamped). */
export function effectiveCeiling(d: Pick<PlayerDevice, 'volume_max' | 'volume_night'>, now: Date = new Date()): number | null {
  const caps = [d.volume_max, inNightWindow(d.volume_night, now) ? d.volume_night!.max : null].filter((c): c is number => c !== null);
  return caps.length ? Math.min(...caps) : null;
}
/** `level` (0-100 integer) limited to the ceiling in force. */
export function clampVolume(d: Pick<PlayerDevice, 'volume_max' | 'volume_night'>, level: number, now: Date = new Date()): number {
  const c = effectiveCeiling(d, now);
  return Math.max(0, Math.min(c === null ? 100 : c, Math.round(level)));
}

/** What the group-volume plan reads of a member (a `PlayerDevice` fits). */
export interface PlanMember {
  key: string;
  volume_max: number | null;
  volume_night: VolumeNight | null;
  can: { control: boolean };
  live: { power: PowerState; volume: { level: number | null; muted: boolean | null } };
}
export interface VolumeStep {
  key: string;
  from: number | null;
  /** The level to write; null when the member is skipped (or unknown). */
  to: number | null;
  outcome: MemberOutcome;
}
const powered = (m: PlanMember): boolean => m.live.power === 'on' || m.live.power === 'art';

/** The group's volume: the max of the powered members (like MA); null when none is powered or none reports a level. */
export function groupLevel(members: readonly PlanMember[]): number | null {
  const levels = members.filter(powered).map((m) => m.live.volume.level).filter((v): v is number => v !== null);
  return levels.length ? Math.max(...levels) : null;
}

/**
 * The per-member plan of a group volume change (CR §6.2; the server does the same and reports the same outcomes).
 * - `relative` (default): every member is scaled by the same factor from its current level (balance kept), the factor being
 *   `level / group level` so the loudest member lands on `level`; when the group level is 0 / unknown there is no balance to
 *   keep and every member goes to `level`. A member without a reported level is `unknown` (nothing to scale).
 * - `absolute`: one level on all.
 * - A member is skipped, never raised: not in the caller's scope (`not_allowed`), unavailable, off, muted.
 * - Each written level is limited to the member's ceiling in force (`volume_max`, the night window) ONLY where one is set;
 *   a member that hit it is `clamped`.
 * `level` (the result) is what the slider should show afterwards: the max of the powered members.
 */
export function groupVolumePlan(members: readonly PlanMember[], level: number, mode: 'relative' | 'absolute' = 'relative', now: Date = new Date()): { steps: VolumeStep[]; level: number | null } {
  const target = Math.max(0, Math.min(100, Math.round(level)));
  const base = groupLevel(members);
  const factor = mode === 'relative' && base !== null && base > 0 ? target / base : null;
  const steps: VolumeStep[] = members.map((m) => {
    const from = m.live.volume.level;
    const skip = (outcome: MemberOutcome): VolumeStep => ({ key: m.key, from, to: null, outcome });
    if (!m.can.control) return skip('not_allowed');
    if (m.live.power === 'unavailable' || m.live.power === 'unknown') return skip('skipped_unavailable');
    if (!powered(m)) return skip('skipped_off');
    if (m.live.volume.muted) return skip('skipped_muted');
    let want = target;
    if (factor !== null) {
      if (from === null) return skip('unknown');
      want = Math.max(0, Math.min(100, Math.round(from * factor)));
    }
    const ceiling = effectiveCeiling(m, now);
    const to = ceiling === null ? want : Math.min(want, ceiling);
    return { key: m.key, from, to, outcome: to < want ? 'clamped' : 'set' };
  });
  const after = members.filter(powered).map((m) => steps.find((s) => s.key === m.key)!.to ?? m.live.volume.level).filter((v): v is number => v !== null);
  return { steps, level: after.length ? Math.max(...after) : null };
}

