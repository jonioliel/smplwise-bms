/** Entity ids the typed action blocks drive (services, scenes, scripts), recursively; locked blocks contribute their statically known effects. */
export function draftTargets(draft: AnyDraft): string[] {
  const out = new Set<string>();
  for (const w of walkDraft(draft)) {
    if (w.section !== 'action') continue;
    const b = w.block;
    if (b.kind === 'typed' && (b as { type: string }).type === 'service') (b as Extract<ActionBlock, { type: 'service' }>).entity_ids.forEach((e) => out.add(e));
    else if (b.kind === 'locked' && Array.isArray(b.effects)) b.effects.forEach((e) => out.add(e));
  }
  if ('members' in draft) draft.members.forEach((m) => out.add(m.entity_id));
  return [...out];
}
/** Entity ids the triggers watch (state / numeric_state). */
export function triggerEntities(draft: AnyDraft): string[] {
  const out = new Set<string>();
  if ('triggers' in draft) for (const t of draft.triggers) if (t.kind === 'typed' && 'entity_ids' in t) t.entity_ids.forEach((e) => out.add(e));
  return [...out];
}
/** Any locked ACTION with unknown effects (CR §9.6: needs `confirm: true`, and installation-wide manage to run). */
export const hasUnknownEffects = (draft: AnyDraft): boolean => walkDraft(draft).some((w) => w.section === 'action' && w.block.kind === 'locked' && w.block.effects === 'unknown');
export const lockedCount = (draft: AnyDraft): number => lockedBlocks(draft).length;
/** The number of action steps of a draft, nested ones included (the cap of §2.2 is 60). */
export const stepsOfDraft = (_kind: ItemKind, draft: AnyDraft): number => walkDraft(draft).filter((w) => w.section === 'action').length;
/** The sensitive calls of a draft with the grant each needs (the preview's `sensitive_steps`). `classOf` = the catalogue's entity class. */
export function sensitiveSteps(draft: AnyDraft, classOf: (entityId: string) => string | null = () => null, hasGrant: (grant: string) => boolean = () => true): PreviewResult['sensitive_steps'] {
  const out: PreviewResult['sensitive_steps'] = [];
  for (const w of walkDraft(draft)) {
    if (w.section !== 'action' || w.block.kind !== 'typed' || (w.block as { type: string }).type !== 'service') continue;
    const b = w.block as Extract<ActionBlock, { type: 'service' }>;
    if (b.role !== 'device') continue;
    const ids = b.entity_ids.length ? b.entity_ids : [''];
    for (const id of ids) {
      const cls = sensitiveClassOf(b.action, id ? classOf(id) : null);
      if (cls) out.push({ path: w.path, entity_id: id, action: b.action, grant: GRANT_OF_CLASS[cls], granted: hasGrant(GRANT_OF_CLASS[cls]) });
    }
  }
  return out;
}
/** A locked block that controls schedules (`scheduler.*`): the builder shows the chip "שולט בתזמונים" (CR §5). */
export const controlsSchedules = (b: Block): boolean => b.kind === 'locked' && b.reason === 'custom_service' && /^scheduler\./.test(String((b.raw as Raw | null)?.action ?? (b.raw as Raw | null)?.service ?? ''));
export const blockIsSensitive = (b: Block, classOf: (e: string) => string | null = () => null): boolean => {
  if (b.kind === 'locked') return b.sensitive;
  const s = b as Extract<ActionBlock, { type: 'service' }>;
  return s.type === 'service' && s.role === 'device' && (s.entity_ids.length ? s.entity_ids : ['']).some((id) => sensitiveClassOf(s.action, id ? classOf(id) : null) !== null);
};

