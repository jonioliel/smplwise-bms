/** How a service is handled: typed with a role, or locked with the reason (CR §9.1). */
export function classifyAction(action: string, ctx: ModelContext = {}): { ok: true; role: 'device' | 'scene' | 'script' | 'notify' | 'automation' } | { ok: false; reason: LockedReason } {
  if (NEVER_TYPED_RE.test(action)) return { ok: false, reason: 'service_not_allowed' };
  if (!SERVICE_RE.test(action)) return { ok: false, reason: 'unknown' };
  const [domain, svc] = action.split('.');
  const allowed = allowedOf(ctx);
  if (action === 'scene.turn_on') return { ok: true, role: 'scene' };
  if (domain === 'script') return svc === 'toggle' ? { ok: false, reason: 'service_not_allowed' } : { ok: true, role: 'script' };
  if (domain === 'automation') return ['turn_on', 'turn_off', 'trigger'].includes(svc) ? { ok: true, role: 'automation' } : { ok: false, reason: 'service_not_allowed' };
  if (domain === 'notify') return !ctx.allowedActions || allowed.has(action) ? { ok: true, role: 'notify' } : { ok: false, reason: 'service_not_allowed' };
  if (allowed.has(action)) return { ok: true, role: 'device' };
  return { ok: false, reason: CORE_DOMAINS.has(domain) ? 'service_not_allowed' : 'custom_service' };
}

export function parseAction(raw: unknown, ctx: ModelContext = {}): ActionBlock | LockedBlock {
  if (!isObj(raw)) return preflight(raw, 'action', ctx, true)!;
  const container = 'choose' in raw || 'if' in raw || 'repeat' in raw;
  const pre = preflight(raw, 'action', ctx, !container);
  if (pre) return pre;
  const r = raw;
  const bad = (hint: LockedReason = 'unsupported_step') => lockedFor(raw, 'action', ctx, hint);
  const mk = <T extends ActionBlock>(b: unknown): T => finish<T>({ ...(b as object), uid: (ctx.uid ?? newUid)() }, 'action', ctx);
  if ('choose' in r) {
    if (!onlyKeys(r, ['choose', 'default']) || !Array.isArray(r.choose)) return bad();
    const opts: Array<{ conditions: Array<ConditionBlock | LockedBlock>; sequence: Block[] }> = [];
    for (const o of r.choose) {
      if (!isObj(o) || !Object.keys(o).every((k) => k === 'conditions' || k === 'sequence')) return bad();
      opts.push({ conditions: parseConditions(o.conditions, ctx), sequence: parseActions(o.sequence, ctx) });
    }
    return mk<ActionBlock>({ kind: 'typed', raw, type: 'choose', options: opts, default: 'default' in r ? parseActions(r.default, ctx) : null });
  }
  if ('if' in r) {
    if (!onlyKeys(r, ['if', 'then', 'else']) || !('then' in r)) return bad();
    return mk<ActionBlock>({ kind: 'typed', raw, type: 'if', conditions: parseConditions(r.if, ctx), then: parseActions(r.then, ctx), else: 'else' in r ? parseActions(r.else, ctx) : null });
  }
  if ('repeat' in r) {
    const rp = r.repeat;
    if (!onlyKeys(r, ['repeat']) || !isObj(rp) || !Object.keys(rp).every((k) => k === 'count' || k === 'sequence') || typeof rp.count !== 'number' || !Number.isInteger(rp.count) || rp.count < 1) return bad();
    return mk<ActionBlock>({ kind: 'typed', raw, type: 'repeat_count', count: rp.count, sequence: parseActions(rp.sequence, ctx) });
  }
  if ('delay' in r) {
    if (!onlyKeys(r, ['delay'])) return bad();
    const d = parseDuration(r.delay);
    if (d === undefined || d === 'invalid') return bad();
    return mk<ActionBlock>({ kind: 'typed', raw, type: 'delay', delay: d });
  }
  if ('stop' in r) {
    if (!onlyKeys(r, ['stop']) || typeof r.stop !== 'string') return bad();
    return mk<ActionBlock>({ kind: 'typed', raw, type: 'stop', message: r.stop });
  }
  if (typeof r.condition === 'string' && !('action' in r) && !('service' in r)) {
    const c = parseCondition(raw, ctx);
    if (c.kind === 'locked') return { ...c, effects: 'none' };
    return mk<ActionBlock>({ kind: 'typed', raw, type: 'condition', condition: c });
  }
  if ('type' in r && 'device_id' in r && 'domain' in r) return mkLocked(raw, 'device', 'action', ctx);
  const svc = r.action ?? r.service;
  if (svc === undefined) return bad(); // variables, wait_*, parallel, sequence, event, scene ... : known, not typed
  if (typeof svc !== 'string') return lockedFor(raw, 'action', ctx, 'unknown');
  if (hasTemplate(raw)) return mkLocked(raw, 'template', 'action', ctx);
  if (!onlyKeys(r, ['action', 'service', 'target', 'data', 'entity_id'])) return bad();
  const cls = classifyAction(svc, ctx);
  if (!cls.ok) return mkLocked(raw, cls.reason, 'action', ctx);
  let ids: string[] | null = [];
  if (r.target !== undefined) {
    if (!isObj(r.target) || Object.keys(r.target).some((k) => k !== 'entity_id')) return bad();
    ids = entityList(r.target.entity_id);
  } else if (r.entity_id !== undefined) ids = entityList(r.entity_id);
  if (!ids) return bad();
  if (r.data !== undefined && !isObj(r.data)) return bad();
  const data = isObj(r.data) ? clone(r.data) : {};
  if ('entity_id' in data) return bad();
  const scriptCall = cls.role === 'script' && svc.split('.')[1] !== 'turn_on' && svc.split('.')[1] !== 'turn_off';
  return mk<ActionBlock>({ kind: 'typed', raw, type: 'service', action: svc, entity_ids: scriptCall ? [svc] : ids, data, role: cls.role });
}
export const parseActions = (v: unknown, ctx: ModelContext = {}): Array<ActionBlock | LockedBlock> => toList(v).map((a) => parseAction(a, ctx));

