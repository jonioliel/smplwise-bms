const AUTOMATION_MANAGED = ['id', 'alias', 'description', 'triggers', 'trigger', 'conditions', 'condition', 'actions', 'action', 'mode', 'max'];
const SCRIPT_MANAGED = ['alias', 'description', 'icon', 'mode', 'max', 'fields', 'sequence'];
const SCENE_MANAGED = ['id', 'name', 'icon', 'entities'];

export interface ReadResult<D> { draft: D; /** top-level keys the draft does not model (carried unchanged by the writer). */ extras: string[]; /** the item uses the pre-2024.10 keys (rewritten in the new schema only when someone saves it). */ legacy: boolean }

const modeOf = (v: unknown): Mode => ((MODES as readonly string[]).includes(v as string) ? (v as Mode) : 'single');
const maxOf = (v: unknown): number | null => (typeof v === 'number' && Number.isFinite(v) ? v : null);
const extrasOf = (c: Raw, managed: string[]): string[] => Object.keys(c).filter((k) => !managed.includes(k));

export function parseSelector(raw: unknown): ScriptField['selector'] {
  if (!isObj(raw) || Object.keys(raw).length !== 1) return { kind: 'locked', raw };
  const [kind, cfgRaw] = Object.entries(raw)[0];
  const cfg = isObj(cfgRaw) ? cfgRaw : cfgRaw === null || cfgRaw === undefined ? {} : null;
  if (!cfg) return { kind: 'locked', raw };
  switch (kind) {
    case 'number':
      return typeof cfg.min === 'number' && typeof cfg.max === 'number'
        ? { kind: 'number', min: cfg.min, max: cfg.max, ...(typeof cfg.step === 'number' ? { step: cfg.step } : {}), ...(typeof cfg.unit_of_measurement === 'string' ? { unit: cfg.unit_of_measurement } : {}) }
        : { kind: 'locked', raw };
    case 'boolean': return { kind: 'boolean' };
    case 'select': return Array.isArray(cfg.options) && cfg.options.every((o) => typeof o === 'string') && !cfg.multiple ? { kind: 'select', options: cfg.options as string[] } : { kind: 'locked', raw };
    case 'text': return { kind: 'text', ...(typeof cfg.maxlength === 'number' ? { max: cfg.maxlength } : {}) };
    case 'entity': {
      const d = cfg.domain === undefined ? [] : toList(cfg.domain);
      return d.every((x) => typeof x === 'string') && !cfg.multiple && !cfg.integration ? { kind: 'entity', domains: d as string[] } : { kind: 'locked', raw };
    }
    default: return { kind: 'locked', raw };
  }
}
/** The HA selector for a typed one; `base` (the stored selector) keeps the keys the draft does not model (`mode`, `translation_key` ...). */
export function selectorOut(sel: ScriptField['selector'], base?: unknown): unknown {
  if (sel.kind === 'locked') return sel.raw;
  const inner: Raw = isObj(base) && isObj(Object.values(base)[0]) && Object.keys(base)[0] === sel.kind ? { ...(Object.values(base)[0] as Raw) } : {};
  switch (sel.kind) {
    case 'number': return { number: { ...inner, min: sel.min, max: sel.max, ...(sel.step !== undefined ? { step: sel.step } : {}), ...(sel.unit !== undefined ? { unit_of_measurement: sel.unit } : {}) } };
    case 'boolean': return { boolean: inner };
    case 'select': return { select: { ...inner, options: [...sel.options] } };
    case 'text': return { text: { ...inner, ...(sel.max !== undefined ? { maxlength: sel.max } : {}) } };
    case 'entity': return { entity: { ...inner, ...(sel.domains.length ? { domain: sel.domains.length === 1 ? sel.domains[0] : [...sel.domains] } : {}) } };
  }
}
function parseFields(v: unknown): ScriptField[] {
  if (!isObj(v)) return [];
  return Object.entries(v).map(([key, f]) => {
    const o = isObj(f) ? f : {};
    return { key, name: typeof o.name === 'string' ? o.name : key, required: o.required === true, default: o.default, selector: parseSelector(o.selector) };
  });
}
function parseMembers(v: unknown): SceneMember[] {
  if (!isObj(v)) return [];
  return Object.entries(v).map(([entity_id, val]) => {
    if (isObj(val)) { const { state, ...attrs } = val; return { entity_id, state: state === undefined ? '' : String(state), attributes: attrs as SceneMember['attributes'] }; }
    return { entity_id, state: val === undefined || val === null ? '' : String(val), attributes: {} };
  });
}

