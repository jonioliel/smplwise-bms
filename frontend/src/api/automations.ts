/** "לפני 12 דק׳", "לפני שעה", "אתמול", "לפני 3 ימים"; "רץ עכשיו" while running; '' when never run. */
export function lastRunText(last: Item['last_run'], now: Date = new Date()): string {
  if (!last) return '';
  if (last.result === 'running') return 'רץ עכשיו';
  const min = Math.floor((now.getTime() - Date.parse(last.at)) / 60000);
  if (!Number.isFinite(min)) return '';
  if (min < 1) return 'עכשיו';
  if (min < 60) return `לפני ${min} דק׳`;
  const h = Math.floor(min / 60);
  if (h < 24) return h === 1 ? 'לפני שעה' : `לפני ${h} שע׳`;
  const days = Math.floor(h / 24);
  return days === 1 ? 'אתמול' : `לפני ${days} ימים`;
}
const norm = (s: string): string => s.normalize('NFC').toLocaleLowerCase('he');
/** The list's filters applied client-side (the server applies the same to `GET /automations`): name, description, sentence and target names. */
export function filterItems(items: readonly Item[], q: ListQuery = {}, opts: { me?: string | null } = {}): Item[] {
  const needle = q.q ? norm(q.q.trim()) : '';
  const out = items.filter((i) => {
    if (q.kind && i.kind !== q.kind) return false;
    if (needle && !norm([i.name, i.description, i.sentence, ...i.targets.map((t) => t.name)].join(' ')).includes(needle)) return false;
    if (q.floor && !i.floors.some((f) => f.id === q.floor)) return false;
    if (q.area && !i.areas.some((a) => a.id === q.area)) return false;
    if (q.state && i.state !== q.state) return false;
    if (q.sensitive !== undefined && i.sensitive !== q.sensitive) return false;
    if (q.source && i.source !== q.source) return false;
    if (q.mine && opts.me !== undefined && i.owner?.display_name !== opts.me) return false;
    if (q.label && !i.labels.includes(q.label)) return false;
    if (q.category && i.category !== q.category) return false;
    return true;
  });
  return sortItems(out, q.sort ?? 'last_run').slice(0, q.limit ?? 500);
}
export function sortItems(items: readonly Item[], sort: NonNullable<ListQuery['sort']> = 'last_run'): Item[] {
  const t = (s: string | null | undefined) => (s ? Date.parse(s) : -Infinity);
  const by: Record<typeof sort, (a: Item, b: Item) => number> = {
    last_run: (a, b) => t(b.last_run?.at) - t(a.last_run?.at) || a.name.localeCompare(b.name, 'he'),
    name: (a, b) => a.name.localeCompare(b.name, 'he'),
    updated: (a, b) => t(b.updated_at) - t(a.updated_at) || a.name.localeCompare(b.name, 'he'),
  };
  return [...items].sort(by[sort]);
}
