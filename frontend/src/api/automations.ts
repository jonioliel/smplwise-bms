/** The text of the code view's JSON mode (the item as it is stored). S4 renders YAML on top of the same object. */
export const codeFromConfig = (config: unknown): string => JSON.stringify(config, null, 2);
/** Parses the code view's text. Only a JSON object is accepted here; YAML is the editor's own parser (S4). */
export function parseCode(text: string): { ok: true; config: Raw } | { ok: false; message: string } {
  try {
    const v = JSON.parse(text) as unknown;
    return isObj(v) ? { ok: true, config: v } : { ok: false, message: 'התוכן צריך להיות אובייקט' };
  } catch (e) {
    return { ok: false, message: e instanceof Error ? e.message : 'קוד לא תקין' };
  }
}
