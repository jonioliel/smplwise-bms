function finish<T extends Block>(b: unknown, section: Section, ctx: ModelContext): T {
  const blk = { ...(b as object), sentence: '' } as unknown as T;
  blk.sentence = blockSentence(blk, section, ctx);
  return blk;
}

export function parseTrigger(raw: unknown, ctx: ModelContext = {}): TriggerBlock | LockedBlock {
  const pre = preflight(raw, 'trigger', ctx, true);
  if (pre) return pre;
  const r = raw as Raw;
  const type = r.trigger ?? r.platform;
  if (typeof type !== 'string') return lockedFor(raw, 'trigger', ctx, 'unknown');
  if (type === 'device') return mkLocked(raw, 'device', 'trigger', ctx);
  if (type === 'template') return mkLocked(raw, 'template', 'trigger', ctx);
  if (type.includes('.')) return mkLocked(raw, 'purpose_trigger', 'trigger', ctx);
  if (hasTemplate(raw)) return mkLocked(raw, 'template', 'trigger', ctx);
  const idv = r.id;
  if (idv !== undefined && typeof idv !== 'string') return mkLocked(raw, 'unsupported_step', 'trigger', ctx);
  const common = { uid: (ctx.uid ?? newUid)(), kind: 'typed' as const, raw, ...(typeof idv === 'string' ? { id: idv } : {}) };
  const head = ['trigger', 'platform', 'id'];
  const bad = (hint: LockedReason = 'unsupported_step') => mkLocked(raw, hint, 'trigger', ctx);
  switch (type) {
    case 'state': {
      if (!onlyKeys(r, [...head, 'entity_id', 'from', 'to', 'for'])) return bad();
      const ids = entityList(r.entity_id); const from = strOrNull(r.from); const to = strOrNull(r.to); const f = parseDuration(r.for);
      if (!ids || from === 'bad' || to === 'bad' || f === 'invalid') return bad();
      return finish<TriggerBlock>({ ...common, type: 'state', entity_ids: ids, ...(from !== undefined ? { from } : {}), ...(to !== undefined ? { to } : {}), ...(f ? { for: f } : {}) }, 'trigger', ctx);
    }
    case 'numeric_state': {
      if (!onlyKeys(r, [...head, 'entity_id', 'above', 'below', 'for'])) return bad();
      const ids = entityList(r.entity_id); const above = num(r.above); const below = num(r.below); const f = parseDuration(r.for);
      if (!ids || above === 'bad' || below === 'bad' || f === 'invalid') return bad();
      return finish<TriggerBlock>({ ...common, type: 'numeric_state', entity_ids: ids, ...(above !== null ? { above } : {}), ...(below !== null ? { below } : {}), ...(f ? { for: f } : {}) }, 'trigger', ctx);
    }
    case 'time': {
      if (!onlyKeys(r, [...head, 'at']) || typeof r.at !== 'string' || !TIME_RE.test(r.at)) return bad();
      return finish<TriggerBlock>({ ...common, type: 'time', at: r.at }, 'trigger', ctx);
    }
    case 'time_pattern': {
      if (!onlyKeys(r, [...head, 'hours', 'minutes', 'seconds'])) return bad();
      const pat = (v: unknown): string | null | 'bad' => (v === undefined || v === null ? null : typeof v === 'string' || typeof v === 'number' ? String(v) : 'bad');
      const h = pat(r.hours); const m = pat(r.minutes); const s = pat(r.seconds);
      if (h === 'bad' || m === 'bad' || s === 'bad') return bad();
      return finish<TriggerBlock>({ ...common, type: 'time_pattern', hours: h, minutes: m, seconds: s }, 'trigger', ctx);
    }
    case 'sun': {
      if (!onlyKeys(r, [...head, 'event', 'offset']) || (r.event !== 'sunrise' && r.event !== 'sunset')) return bad();
      const off = offsetMin(r.offset);
      if (off === 'bad') return bad();
      return finish<TriggerBlock>({ ...common, type: 'sun', event: r.event, offset_min: off }, 'trigger', ctx);
    }
    case 'homeassistant': {
      if (!onlyKeys(r, [...head, 'event']) || r.event !== 'start') return bad();
      return finish<TriggerBlock>({ ...common, type: 'homeassistant', event: 'start' }, 'trigger', ctx);
    }
    default:
      // event, zone, mqtt, webhook, calendar, tag ...: known to HA, not typed in v1
      return /^[a-z_]+$/.test(type) ? bad() : bad('unknown');
  }
}

// ---- parse: conditions

export function parseCondition(raw: unknown, ctx: ModelContext = {}, inGroup = false): ConditionBlock | LockedBlock {
  if (typeof raw === 'string') return mkLocked(raw, hasTemplate(raw) ? 'template' : 'unknown', 'condition', ctx);
  const type = isObj(raw) ? raw.condition : undefined;
  const container = type === 'and' || type === 'or' || type === 'not';
  const pre = preflight(raw, 'condition', ctx, !container);
  if (pre) return pre;
  const r = raw as Raw;
  if (typeof type !== 'string') return lockedFor(raw, 'condition', ctx, 'unknown');
  if (type === 'device') return mkLocked(raw, 'device', 'condition', ctx);
  if (type === 'template') return mkLocked(raw, 'template', 'condition', ctx);
  const bad = (hint: LockedReason = 'unsupported_step') => lockedFor(raw, 'condition', ctx, hint);
  if (!container && hasTemplate(raw)) return mkLocked(raw, 'template', 'condition', ctx);
  const common = { uid: (ctx.uid ?? newUid)(), kind: 'typed' as const, raw };
  const head = ['condition'];
  switch (type) {
    case 'state': {
      if (!onlyKeys(r, [...head, 'entity_id', 'state', 'for'])) return bad();
      const ids = entityList(r.entity_id); const f = parseDuration(r.for);
      const st = Array.isArray(r.state) ? r.state : [r.state];
      if (!ids || f === 'invalid' || !st.length || !st.every((s) => typeof s === 'string')) return bad();
      const state = Array.isArray(r.state) ? (r.state as string[]) : (r.state as string);
      const sensor = ctx.shabbatSensor;
      if (sensor && ids.length === 1 && ids[0] === sensor && !f && (state === 'on' || state === 'off')) {
        return finish<ConditionBlock>({ ...common, type: 'shabbat', mode: state === 'on' ? 'only_holy_days' : 'not_holy_days' }, 'condition', ctx);
      }
      return finish<ConditionBlock>({ ...common, type: 'state', entity_ids: ids, state, ...(f ? { for: f } : {}) }, 'condition', ctx);
    }
    case 'numeric_state': {
      if (!onlyKeys(r, [...head, 'entity_id', 'above', 'below'])) return bad();
      const ids = entityList(r.entity_id); const above = num(r.above); const below = num(r.below);
      if (!ids || above === 'bad' || below === 'bad') return bad();
      return finish<ConditionBlock>({ ...common, type: 'numeric_state', entity_ids: ids, ...(above !== null ? { above } : {}), ...(below !== null ? { below } : {}) }, 'condition', ctx);
    }
    case 'time': {
      if (!onlyKeys(r, [...head, 'after', 'before', 'weekday'])) return bad();
      const okT = (v: unknown) => v === undefined || (typeof v === 'string' && TIME_RE.test(v));
      const wd = r.weekday === undefined ? undefined : toList(r.weekday);
      if (!okT(r.after) || !okT(r.before) || (wd && !wd.every((d) => typeof d === 'string' && (WEEKDAYS as readonly string[]).includes(d)))) return bad();
      return finish<ConditionBlock>({ ...common, type: 'time', ...(r.after !== undefined ? { after: r.after as string } : {}), ...(r.before !== undefined ? { before: r.before as string } : {}), ...(wd ? { weekday: wd as Weekday[] } : {}) }, 'condition', ctx);
    }
    case 'sun': {
      if (!onlyKeys(r, [...head, 'after', 'before'])) return bad();
      const okS = (v: unknown) => v === undefined || v === 'sunrise' || v === 'sunset';
      if (!okS(r.after) || !okS(r.before)) return bad();
      return finish<ConditionBlock>({ ...common, type: 'sun', ...(r.after !== undefined ? { after: r.after as SunRef } : {}), ...(r.before !== undefined ? { before: r.before as SunRef } : {}) }, 'condition', ctx);
    }
    case 'trigger': {
      const ids = toList(r.id);
      if (!onlyKeys(r, [...head, 'id']) || !ids.length || !ids.every((i) => typeof i === 'string')) return bad();
      return finish<ConditionBlock>({ ...common, type: 'trigger', ids: ids as string[] }, 'condition', ctx);
    }
    case 'and': case 'or': case 'not': {
      if (inGroup || !onlyKeys(r, [...head, 'conditions']) || !Array.isArray(r.conditions)) return bad();
      const kids = r.conditions.map((c) => parseCondition(c, ctx, true));
      return finish<ConditionBlock>({ ...common, type, conditions: kids }, 'condition', ctx);
    }
    default: return bad('unknown');
  }
}
const parseConditions = (v: unknown, ctx: ModelContext): Array<ConditionBlock | LockedBlock> => toList(v).map((c) => parseCondition(c, ctx));

