export function configToDraft(kind: 'script', config: unknown, ctx?: ModelContext): ReadResult<ScriptDraft>;
export function configToDraft(kind: 'scene', config: unknown, ctx?: ModelContext): ReadResult<SceneDraft>;
export function configToDraft(kind: ItemKind, config: unknown, ctx?: ModelContext): ReadResult<AnyDraft>;
/** Reads a stored item (JSON) into the draft model. Legacy keys (`trigger`, `platform`, `service`) are normalised in memory only. */
export function configToDraft(kind: ItemKind, config: unknown, ctx: ModelContext = {}): ReadResult<AnyDraft> {
  const c: Raw = isObj(config) ? config : {};
  if (kind === 'automation') {
    const legacy = 'trigger' in c || 'condition' in c || 'action' in c || JSON.stringify(c).includes('"platform"') || JSON.stringify(c).includes('"service"');
    const draft: AutomationDraft = {
      alias: typeof c.alias === 'string' ? c.alias : '', description: typeof c.description === 'string' ? c.description : '', mode: modeOf(c.mode), max: maxOf(c.max),
      triggers: toList(c.triggers ?? c.trigger).map((t) => parseTrigger(t, ctx)), conditions: parseConditions(c.conditions ?? c.condition, ctx), actions: parseActions(c.actions ?? c.action, ctx),
    };
    return { draft, extras: extrasOf(c, AUTOMATION_MANAGED), legacy };
  }
  if (kind === 'script') {
    const legacy = JSON.stringify(c).includes('"service"');
    const draft: ScriptDraft = {
      alias: typeof c.alias === 'string' ? c.alias : '', description: typeof c.description === 'string' ? c.description : '', icon: typeof c.icon === 'string' ? c.icon : null,
      mode: modeOf(c.mode), max: maxOf(c.max), fields: parseFields(c.fields), sequence: parseActions(c.sequence, ctx),
    };
    return { draft, extras: extrasOf(c, SCRIPT_MANAGED), legacy };
  }
  const draft: SceneDraft = { name: typeof c.name === 'string' ? c.name : '', icon: typeof c.icon === 'string' ? c.icon : null, members: parseMembers(c.entities) };
  return { draft, extras: extrasOf(c, SCENE_MANAGED), legacy: false };
}

