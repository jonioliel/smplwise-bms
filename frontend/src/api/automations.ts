const fill = (tpl: string, d: Record<string, unknown>): string =>
  tpl.replace(/\{(\w+)\}/g, (_m, k: string) => (typeof d[k] === 'string' || typeof d[k] === 'number' ? String(d[k]) : '…'));

/** The Hebrew line of an error of this API: the §3.3 table by code (placeholders from `details`), else the server's own message. */
export function automationErrorText(err: unknown): string {
  if (err instanceof ApiError) {
    const tpl = (AUTOMATION_ERROR_LABEL as Record<string, string>)[err.code];
    if (tpl) {
      if (err.code === 'bridge_not_paired' && err.body.user_message) return err.body.user_message; // contract §3.3: the existing message
      const d = err.body.details ?? {};
      // validation: `details.errors[0]` carries the field and what is wrong
      const first = Array.isArray(d.errors) ? (d.errors[0] as Partial<Issue> | undefined) : undefined;
      const merged: Record<string, unknown> = { ...d, ...(first ? { field: first.path, what: first.message } : {}) };
      const text = fill(tpl, merged);
      return /…/.test(text) && err.body.user_message ? err.body.user_message : text;
    }
  }
  return describeError(err);
}

/** Maps any thrown value to the structure screens branch on. */
export function mapAutomationError(err: unknown): AutomationFailure {
  if (!(err instanceof ApiError)) {
    return { code: 'network', status: 0, kind: 'unavailable', message: describeError(err), retryable: true, details: {}, current: null, issues: [], grant: null, maybe_saved: false };
  }
  const d = (err.body.details ?? {}) as Record<string, unknown>;
  const issues = Array.isArray(d.errors) ? (d.errors as Issue[]) : [];
  return {
    code: err.code, status: err.status, kind: KIND_OF[err.code] ?? 'unknown', message: automationErrorText(err), retryable: !!err.body.retryable, details: d,
    current: d.current && typeof d.current === 'object' ? (d.current as ItemDetail) : null,
    issues,
    grant: err.code === 'grant_required' ? { grant: typeof d.grant === 'string' ? d.grant : null, path: typeof d.path === 'string' ? d.path : null } : null,
    maybe_saved: err.code === 'config_timeout',
  };
}
