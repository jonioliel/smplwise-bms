/** The caller's floors / areas (a binding's scope). `null` = installation-wide. HA areas on their own are never a scope (CR §7). */
export interface UserScope { floors: readonly string[] | null; areas: readonly string[] | null }
export const INSTALLATION_WIDE: UserScope = { floors: null, areas: null };
export const isInstallationWide = (s: UserScope): boolean => s.floors === null && s.areas === null;
type Placed = { floor: { id: string } | null; area: { id: string } | null };
/** Whether an entity is inside the scope. An unplaced entity (no floor, no area: a person, a zone, a bare sensor) is never a CONTROL target for a scoped
 * caller (`purpose: 'target'`) but may be watched (`'watch'`: triggers and conditions), like the approved mockup. */
export function entityInScope(e: Placed, scope: UserScope, purpose: 'target' | 'watch' = 'target'): boolean {
  if (isInstallationWide(scope)) return true;
  if (!e.floor && !e.area) return purpose === 'watch';
  return (!!e.area && !!scope.areas?.includes(e.area.id)) || (!!e.floor && !!scope.floors?.includes(e.floor.id));
}
export interface PickerFilter { purpose?: 'target' | 'watch'; q?: string; domains?: readonly string[]; sensitive?: boolean; onlyTriggerable?: boolean; /** only entities that have a typed action (a control target) */ controllable?: boolean; actionId?: string }
/** The entities a picker offers: in scope, matching the search (name, id, area), the domains and (for a typed action) the entities that action may drive. */
export function pickerEntities(entities: readonly CatalogEntity[], scope: UserScope, f: PickerFilter = {}): CatalogEntity[] {
  const q = f.q ? norm(f.q.trim()) : '';
  return entities.filter((e) => {
    if (!entityInScope(e, scope, f.purpose ?? 'target')) return false;
    if (f.domains && !f.domains.includes(e.domain)) return false;
    if (f.sensitive !== undefined && (e.class !== null) !== f.sensitive) return false;
    if (f.onlyTriggerable && !e.triggers.length) return false;
    if (f.controllable && !e.actions.length) return false;
    if (f.actionId && !e.actions.includes(f.actionId)) return false;
    return !q || norm(`${e.name} ${e.entity_id} ${e.area?.name ?? ''} ${e.floor?.name ?? ''}`).includes(q);
  }).sort((a, b) => a.name.localeCompare(b.name, 'he'));
}
export interface PickerGroup { floor: { id: string; name: string } | null; areas: Array<{ area: { id: string; name: string } | null; entities: CatalogEntity[] }> }
/** Floor -> area -> entities; entities with no placement are one last group ("כל הבית" in the UI: floor null, area null). */
export function groupPicker(entities: readonly CatalogEntity[]): PickerGroup[] {
  const floors = new Map<string, PickerGroup>();
  const none: PickerGroup = { floor: null, areas: [{ area: null, entities: [] }] };
  for (const e of entities) {
    if (!e.floor && !e.area) { none.areas[0].entities.push(e); continue; }
    const fk = e.floor?.id ?? '';
    const g = floors.get(fk) ?? { floor: e.floor, areas: [] };
    floors.set(fk, g);
    let a = g.areas.find((x) => (x.area?.id ?? null) === (e.area?.id ?? null));
    if (!a) { a = { area: e.area, entities: [] }; g.areas.push(a); }
    a.entities.push(e);
  }
  const groups = [...floors.values()].sort((a, b) => (a.floor?.name ?? '￿').localeCompare(b.floor?.name ?? '￿', 'he'));
  for (const g of groups) g.areas.sort((a, b) => (a.area?.name ?? '').localeCompare(b.area?.name ?? '', 'he'));
  return none.areas[0].entities.length ? [...groups, none] : groups;
}
/** CR §7 visibility: an item is visible iff every ACTION target is in scope; with no typed target, by its trigger entities; with neither only installation-wide viewers.
 * (Trigger / condition entities outside the scope never hide an item that has targets.) `place` looks an entity up (null = unplaced). */
export function itemVisibleTo(draft: AnyDraft, scope: UserScope, place: (entityId: string) => Placed | null): boolean {
  if (isInstallationWide(scope)) return true;
  const targets = draftTargets(draft);
  const ids = targets.length ? targets : triggerEntities(draft);
  if (!ids.length) return false;
  // trigger entities count only when they are PLACED inside the scope: a person or a zone belongs to no floor, so an item that only watches them stays installation-wide
  return ids.every((id) => entityInScope(place(id) ?? { floor: null, area: null }, scope, 'target'));
}

