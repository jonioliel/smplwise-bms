export const extraKeys = (kind: ItemKind, config: unknown): string[] => (isObj(config) ? extrasOf(config, kind === 'automation' ? AUTOMATION_MANAGED : kind === 'script' ? SCRIPT_MANAGED : SCENE_MANAGED) : []);

