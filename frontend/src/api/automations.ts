/** Reads the `automations.*` keys of the settings map (the server's values, defaults for what is missing or out of range). */
export function automationSettingsOf(s: Record<string, unknown> | null | undefined): AutomationSettings {
  const d = AUTOMATION_SETTINGS_DEFAULT;
  const json = (v: unknown): unknown => { if (typeof v !== 'string') return v; try { return JSON.parse(v); } catch { return v; } };
  const bool = (v: unknown, def: boolean) => (v === undefined || v === null ? def : String(v) !== 'false');
  const num = (v: unknown, def: number, [lo, hi]: readonly [number, number]) => { const n = Number(v); return Number.isFinite(n) && n >= lo && n <= hi ? Math.round(n) : def; };
  const list = (v: unknown, def: string[]) => { const j = json(v); return Array.isArray(j) ? j.map(String) : def; };
  const lim = (json(s?.['automations.limits']) ?? {}) as Partial<AutomationLimits>;
  const pos = (v: unknown, def: number) => { const n = Number(v); return Number.isFinite(n) && n > 0 ? Math.round(n) : def; };
  return {
    enabled: bool(s?.['automations.enabled'], d.enabled),
    code_view_roles: list(s?.['automations.code_view_roles'], d.code_view_roles),
    trash_days: num(s?.['automations.trash_days'], d.trash_days, AUTOMATION_SETTING_RANGES.trash_days),
    versions_keep: num(s?.['automations.versions_keep'], d.versions_keep, AUTOMATION_SETTING_RANGES.versions_keep),
    limits: {
      writes_per_min: pos(lim.writes_per_min, d.limits.writes_per_min), preview_per_min: pos(lim.preview_per_min, d.limits.preview_per_min),
      run_interval_s: pos(lim.run_interval_s, d.limits.run_interval_s), scene_apply_interval_s: pos(lim.scene_apply_interval_s, d.limits.scene_apply_interval_s),
      storm_item_per_min: pos(lim.storm_item_per_min, d.limits.storm_item_per_min), storm_total_per_min: pos(lim.storm_total_per_min, d.limits.storm_total_per_min),
    },
    storm_auto_disable: bool(s?.['automations.storm_auto_disable'], d.storm_auto_disable),
    sensitive_warning: bool(s?.['automations.sensitive_warning'], d.sensitive_warning),
    templates_enabled: bool(s?.['automations.templates_enabled'], d.templates_enabled),
    templates_hidden: list(s?.['automations.templates_hidden'], d.templates_hidden),
    templates_order: list(s?.['automations.templates_order'], d.templates_order),
    notify_targets: list(s?.['automations.notify_targets'], d.notify_targets),
    ask_when_on_new: bool(s?.['automations.ask_when_on_new'], d.ask_when_on_new),
    phone_filter: s?.['automations.phone_filter'] === 'rows' ? 'rows' : 'fold',
    sensitive_chip: s?.['automations.sensitive_chip'] === 'red' ? 'red' : 'amber',
  };
}
/** The PATCH /settings body for what differs (system.configure; audited by the server). Booleans travel as in the other tabs. */
export function automationSettingsPatch(from: AutomationSettings, to: AutomationSettings): Record<string, unknown> {
  const body: Record<string, unknown> = {};
  const j = JSON.stringify;
  if (from.enabled !== to.enabled) body['automations.enabled'] = String(to.enabled);
  if (j(from.code_view_roles) !== j(to.code_view_roles)) body['automations.code_view_roles'] = to.code_view_roles;
  if (from.trash_days !== to.trash_days) body['automations.trash_days'] = to.trash_days;
  if (from.versions_keep !== to.versions_keep) body['automations.versions_keep'] = to.versions_keep;
  if (j(from.limits) !== j(to.limits)) body['automations.limits'] = to.limits;
  if (from.storm_auto_disable !== to.storm_auto_disable) body['automations.storm_auto_disable'] = String(to.storm_auto_disable);
  if (from.sensitive_warning !== to.sensitive_warning) body['automations.sensitive_warning'] = String(to.sensitive_warning);
  if (from.templates_enabled !== to.templates_enabled) body['automations.templates_enabled'] = String(to.templates_enabled);
  if (j(from.templates_hidden) !== j(to.templates_hidden)) body['automations.templates_hidden'] = to.templates_hidden;
  if (j(from.templates_order) !== j(to.templates_order)) body['automations.templates_order'] = to.templates_order;
  if (j(from.notify_targets) !== j(to.notify_targets)) body['automations.notify_targets'] = to.notify_targets;
  if (from.ask_when_on_new !== to.ask_when_on_new) body['automations.ask_when_on_new'] = String(to.ask_when_on_new);
  if (from.phone_filter !== to.phone_filter) body['automations.phone_filter'] = to.phone_filter;
  if (from.sensitive_chip !== to.sensitive_chip) body['automations.sensitive_chip'] = to.sensitive_chip;
  return body;
}

