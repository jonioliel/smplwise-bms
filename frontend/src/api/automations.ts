/** The mask the server puts in place of a secret-like value. */
export const MASK = '••••';
const SECRET_WORDS = new Set(['password', 'passwd', 'token', 'secret', 'code', 'pin', 'apikey']);
/** CR §9.3: `password|passwd|token|api_key|apikey|secret|code|pin`, matched as whole words of the key (snake, kebab or camel case), so
 * `shipping` or `unicode` are not secrets while `access_token`, `alarm_code` and `apiKey` are. */
export function isSecretKey(key: string): boolean {
  const parts = key.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase().split(/[^a-z0-9]+/).filter(Boolean);
  if (parts.some((p) => SECRET_WORDS.has(p))) return true;
  return parts.some((p, i) => p === 'api' && parts[i + 1] === 'key');
}
/** `'code'` when a key is exactly the alarm-code word, `'secret'` for any other secret-like key, else null (any depth). */
export function secretKind(v: unknown): 'code' | 'secret' | null {
  let found: 'code' | 'secret' | null = null;
  const walk = (x: unknown): void => {
    if (found === 'code') return;
    if (Array.isArray(x)) x.forEach(walk);
    else if (isObj(x)) for (const [k, val] of Object.entries(x)) {
      if (isSecretKey(k)) found = k.toLowerCase() === 'code' || k.toLowerCase().split(/[^a-z0-9]+/).includes('code') ? 'code' : (found ?? 'secret');
      walk(val);
    }
  };
  walk(v);
  return found;
}
/** Replaces the value under every secret-like key (any depth) with the mask (traces and every API answer, CR §9.3). */
export function maskSecrets<T>(v: T): T {
  if (Array.isArray(v)) return v.map(maskSecrets) as unknown as T;
  if (isObj(v)) return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, isSecretKey(k) ? MASK : maskSecrets(x)])) as T;
  return v;
}
