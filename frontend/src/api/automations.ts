export function codeToDraft(kind: ItemKind, text: string, ctx?: ModelContext): { ok: true; draft: AnyDraft; extras: string[] } | { ok: false; message: string } {
  const p = parseCode(text);
  if (!p.ok) return p;
  const r = configToDraft(kind, p.config, ctx);
  return { ok: true, draft: r.draft, extras: r.extras };
}

// ---- walking blocks

export interface BlockLists { name: string; blocks: Block[]; section: Section }
/** The child lists of a block with their path segment (`choose.0.conditions`, `then` ...). */
export function childLists(b: Block): BlockLists[] {
  if (b.kind !== 'typed') return [];
  const t = b as Block & { type: string };
  switch (t.type) {
    case 'and': case 'or': case 'not': return [{ name: 'conditions', blocks: (b as Extract<ConditionBlock, { type: 'and' | 'or' | 'not' }>).conditions, section: 'condition' }];
    case 'choose': {
      const c = b as Extract<ActionBlock, { type: 'choose' }>;
      return [...c.options.flatMap((o, i): BlockLists[] => [{ name: `choose.${i}.conditions`, blocks: o.conditions, section: 'condition' }, { name: `choose.${i}.sequence`, blocks: o.sequence, section: 'action' }]),
        ...(c.default ? [{ name: 'default', blocks: c.default, section: 'action' as Section }] : [])];
    }
    case 'if': {
      const c = b as Extract<ActionBlock, { type: 'if' }>;
      return [{ name: 'if', blocks: c.conditions, section: 'condition' }, { name: 'then', blocks: c.then, section: 'action' }, ...(c.else ? [{ name: 'else', blocks: c.else, section: 'action' as Section }] : [])];
    }
    case 'repeat_count': return [{ name: 'repeat.sequence', blocks: (b as Extract<ActionBlock, { type: 'repeat_count' }>).sequence, section: 'action' }];
    default: return [];
  }
}
export interface Walked { block: Block; section: Section; path: string; depth: number }
/** Every block of a draft (containers before their children) with its dotted path (`actions.1.choose.0.sequence.2`) and nesting depth. */
export function walkDraft(draft: AnyDraft): Walked[] {
  const out: Walked[] = [];
  const visit = (blocks: Block[], section: Section, prefix: string, depth: number) => {
    blocks.forEach((b, i) => {
      const path = `${prefix}.${i}`;
      out.push({ block: b, section, path, depth });
      for (const l of childLists(b)) visit(l.blocks, l.section, `${path}.${l.name}`, depth + 1);
      if (b.kind === 'typed' && (b as { type?: string }).type === 'condition') out.push({ block: (b as Extract<ActionBlock, { type: 'condition' }>).condition, section: 'condition', path: `${path}.condition`, depth: depth + 1 });
    });
  };
  if ('triggers' in draft) {
    visit(draft.triggers, 'trigger', 'triggers', 0); visit(draft.conditions, 'condition', 'conditions', 0); visit(draft.actions, 'action', 'actions', 0);
  } else if ('sequence' in draft) visit(draft.sequence, 'action', 'sequence', 0);
  return out;
}
/** The dotted path of a block, or null. */
export const blockPathOf = (draft: AnyDraft, uid: string): string | null => walkDraft(draft).find((w) => w.block.uid === uid)?.path ?? null;
const SINGULAR: Record<string, string> = { trigger: 'triggers', condition: 'conditions', action: 'actions' };
/** Normalises a server issue path (`actions[1]`, `action/1/choose/0`, `actions.1`) to the dotted form of `walkDraft`. */
export const normalisePath = (p: string): string => {
  const t = p.split(/[./[\]]+/).filter(Boolean);
  if (t.length && SINGULAR[t[0]]) t[0] = SINGULAR[t[0]];
  return t.join('.');
};
/** The block an issue path points at: the deepest block whose path is a prefix of the issue's. */
export function blockAtPath(draft: AnyDraft, path: string): Block | null {
  const want = normalisePath(path);
  let best: Walked | null = null;
  for (const w of walkDraft(draft)) if ((want === w.path || want.startsWith(`${w.path}.`)) && (!best || w.path.length > best.path.length)) best = w;
  return best?.block ?? null;
}
export const findBlock = (draft: AnyDraft, uid: string): Block | null => walkDraft(draft).find((w) => w.block.uid === uid)?.block ?? null;
export const lockedBlocks = (draft: AnyDraft): LockedBlock[] => walkDraft(draft).map((w) => w.block).filter((b): b is LockedBlock => b.kind === 'locked');
/** The fingerprints the bridge's `preserved` list carries (CR §8.2): every locked block of the draft. */
export const preservedFingerprints = (draft: AnyDraft): string[] => [...new Set(lockedBlocks(draft).map((b) => b.fingerprint))];

/** Locked blocks of `draft` that are not (by fingerprint) a locked block of the stored item: the server answers 403 `locked_block_changed` unless the save goes through the code view. */
export function changedLockedBlocks(draft: AnyDraft, stored: AnyDraft | null): LockedBlock[] {
  const known = new Set(stored ? lockedBlocks(stored).map((b) => b.fingerprint) : []);
  return lockedBlocks(draft).filter((b) => !known.has(b.fingerprint));
}
/** The write profile derived from the CONTENT (CR §4.5): every locked block is one of the stored item's -> `builder` (delegation applies); else `code` (HA admin). */
