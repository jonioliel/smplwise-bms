/** Capture domains v1. Alarm panels are not one (reproducing their state needs a code and codes are never stored, CR §4.3). */
export const SCENE_CAPTURE_DOMAINS = ['light', 'switch', 'fan', 'cover', 'climate', 'media_player', 'lock'] as const;
/** The attributes kept per domain (HA attribute names). Lights: by color mode, see `captureMember`. */
export const CAPTURE_ATTRS: Record<string, readonly string[]> = {
  switch: [], lock: [], fan: ['percentage', 'preset_mode'], cover: ['current_position', 'current_tilt_position'],
  climate: ['temperature', 'target_temp_high', 'target_temp_low', 'fan_mode', 'preset_mode', 'swing_mode'], media_player: ['volume_level', 'source'], light: ['brightness'],
};
type Attrs = Record<string, unknown>;
const LIGHT_COLOR: Record<string, string> = { color_temp: 'color_temp_kelvin', hs: 'hs_color', xy: 'hs_color', rgb: 'rgb_color', rgbw: 'rgb_color', rgbww: 'rgb_color' };
/** One entity state (HA shape: `{entity_id, state, attributes}`) -> a scene member with the domain's attributes only, or null when the domain is not a capture domain. */
export function captureMember(e: { entity_id: string; state: string; attributes?: Attrs }): SceneMember | null {
  const domain = e.entity_id.split('.')[0];
  if (!(SCENE_CAPTURE_DOMAINS as readonly string[]).includes(domain)) return null;
  const a = e.attributes ?? {};
  const keys = [...(CAPTURE_ATTRS[domain] ?? [])];
  const on = e.state !== 'off' && e.state !== 'unavailable' && e.state !== 'unknown';
  if (domain === 'light' && on) { const ck = typeof a.color_mode === 'string' ? LIGHT_COLOR[a.color_mode] : undefined; if (ck) keys.push(ck); }
  if (domain === 'light' && !on) keys.length = 0;
  if ((domain === 'fan' || domain === 'media_player') && !on) keys.length = 0;
  const attributes: SceneMember['attributes'] = {};
  for (const k of keys) {
    const v = a[k];
    if (typeof v === 'number' || typeof v === 'string' || typeof v === 'boolean' || (Array.isArray(v) && v.every((x) => typeof x === 'number'))) attributes[k] = v as never;
  }
  return { entity_id: e.entity_id, state: e.state, attributes };
}
export function captureMembers(entities: ReadonlyArray<{ entity_id: string; state: string; attributes?: Attrs }>): { members: SceneMember[]; skipped: Array<{ entity_id: string; reason: 'alarm_not_capturable' | 'domain_not_supported' | 'unavailable' }> } {
  const members: SceneMember[] = []; const skipped: Array<{ entity_id: string; reason: 'alarm_not_capturable' | 'domain_not_supported' | 'unavailable' }> = [];
  for (const e of entities) {
    const dom = e.entity_id.split('.')[0];
    if (dom === 'alarm_control_panel') { skipped.push({ entity_id: e.entity_id, reason: 'alarm_not_capturable' }); continue; }
    if (e.state === 'unavailable' || e.state === 'unknown') { skipped.push({ entity_id: e.entity_id, reason: 'unavailable' }); continue; }
    const m = captureMember(e);
    if (m) members.push(m); else skipped.push({ entity_id: e.entity_id, reason: 'domain_not_supported' });
  }
  return { members, skipped };
}
const STATE_WORD: Record<string, string> = {
  on: 'דלוק', off: 'כבוי', open: 'פתוח', closed: 'סגור', opening: 'נפתח', closing: 'נסגר', locked: 'נעול', unlocked: 'פתוח', cool: 'קירור', heat: 'חימום', heat_cool: 'חימום/קירור',
  auto: 'אוטומטי', dry: 'ייבוש', fan_only: 'מאוורר', playing: 'מנגן', paused: 'מושהה', idle: 'לא מנגן', standby: 'המתנה',
};
/** A member as one short line: "דלוק · בהירות 80% · 3000K", "קירור 23°", "פתוח 100%". */
export function memberSummary(m: SceneMember): string {
  const dom = m.entity_id.split('.')[0];
  const a = m.attributes;
  const parts: string[] = [STATE_WORD[m.state] ?? m.state];
  if (typeof a.brightness === 'number') parts.push(`בהירות ${Math.round((a.brightness / 255) * 100)}%`);
  if (typeof a.color_temp_kelvin === 'number') parts.push(`${a.color_temp_kelvin}K`);
  if (Array.isArray(a.hs_color)) parts.push('צבע');
  if (Array.isArray(a.rgb_color)) parts.push('צבע');
  if (typeof a.current_position === 'number') parts.push(`${a.current_position}%`);
  if (typeof a.temperature === 'number') parts.push(`${a.temperature}°`);
  if (typeof a.percentage === 'number') parts.push(`${a.percentage}%`);
  if (typeof a.volume_level === 'number') parts.push(`עוצמה ${Math.round(a.volume_level * 100)}%`);
  if (typeof a.source === 'string') parts.push(a.source);
  if (typeof a.fan_mode === 'string') parts.push(`מאוורר ${a.fan_mode}`);
  void dom;
  return parts.join(' · ');
}
export interface MemberDiff { entity_id: string; change: 'added' | 'removed' | 'changed' | 'same'; fields: Array<{ key: string; from: unknown; to: unknown }>; from: string | null; to: string | null }
/** The diff between two member lists (a fresh capture vs the saved scene, or the edited table vs the stored one): per entity added / removed / changed / same,
 * with the changed fields (`state` and attributes) and the one-line summaries. Order: `to` first, then removed. */
export function sceneCaptureDiff(from: readonly SceneMember[], to: readonly SceneMember[]): MemberDiff[] {
  const f = new Map(from.map((m) => [m.entity_id, m]));
  const t = new Map(to.map((m) => [m.entity_id, m]));
  const out: MemberDiff[] = [];
  for (const m of to) {
    const old = f.get(m.entity_id);
    if (!old) { out.push({ entity_id: m.entity_id, change: 'added', fields: [], from: null, to: memberSummary(m) }); continue; }
    const fields: MemberDiff['fields'] = [];
    if (old.state !== m.state) fields.push({ key: 'state', from: old.state, to: m.state });
    for (const k of new Set([...Object.keys(old.attributes), ...Object.keys(m.attributes)])) {
      if (JSON.stringify(old.attributes[k]) !== JSON.stringify(m.attributes[k])) fields.push({ key: k, from: old.attributes[k] ?? null, to: m.attributes[k] ?? null });
    }
    out.push({ entity_id: m.entity_id, change: fields.length ? 'changed' : 'same', fields, from: memberSummary(old), to: memberSummary(m) });
  }
  for (const m of from) if (!t.has(m.entity_id)) out.push({ entity_id: m.entity_id, change: 'removed', fields: [], from: memberSummary(m), to: null });
  return out;
}

// ------------------------------------------------------------------------------------------------ the schedule suggestion (CR §5)

const SCHEDULE_DOMAINS = new Set(['light', 'switch', 'climate', 'fan', 'cover']);
export interface SuggestOptions { schedulerPresent: boolean; shabbatSensor?: string | null; classOf?: (entityId: string) => string | null }
/** "צור כתזמון": when a draft has only `time` / `sun` triggers and only device control (lights, switches, climate, fans, covers; nothing sensitive) and the
 * scheduler is present, the pre-filled CR-014 draft; else null. A suggestion, never a refusal. Time -> slot start (one slot per trigger), weekdays -> days,
 * the Shabbat condition -> a condition on CR-014's sensor. Anything else (other conditions, choose, delay, notify ...) -> no suggestion. */
export function suggestSchedule(draft: AutomationDraft, opts: SuggestOptions): { schedule_draft: ScheduleDraft } | null {
  if (!opts.schedulerPresent || !draft.triggers.length || !draft.actions.length) return null;
  if (!draft.triggers.every((t) => t.kind === 'typed' && (t.type === 'time' || t.type === 'sun'))) return null;
  let weekdays: Weekday[] = [];
  let shabbat: 'on' | 'off' | null = null;
  for (const c of draft.conditions) {
    if (c.kind !== 'typed') return null;
    if (c.type === 'time' && !c.after && !c.before) weekdays = c.weekday ?? [];
    else if (c.type === 'shabbat' && opts.shabbatSensor) shabbat = c.mode === 'only_holy_days' ? 'on' : 'off';
    else return null;
  }
  const acts: ScheduleDraft['slots'][number]['actions'] = [];
  for (const a of draft.actions) {
    if (a.kind !== 'typed' || a.type !== 'service' || a.role !== 'device' || !a.entity_ids.length) return null;
    if (!SCHEDULE_DOMAINS.has(a.action.split('.')[0])) return null;
    for (const id of a.entity_ids) {
      if (sensitiveClassOf(a.action, opts.classOf?.(id) ?? null)) return null;
      acts.push({ service: a.action, entity_id: id, data: clone(a.data) });
    }
  }
  const slots: ScheduleDraft['slots'] = draft.triggers.map((t) => {
    const x = t as Extract<TriggerBlock, { type: 'time' | 'sun' }>;
    const start = x.type === 'time' ? hms(x.at) : `${x.event}${x.offset_min < 0 ? '-' : '+'}${fmtOffset(Math.abs(x.offset_min))}`;
    return { start, stop: null, actions: clone(acts) };
  });
  const tokens: DayToken[] = weekdays.length && weekdays.length < 7 ? WEEKDAYS.filter((d) => weekdays.includes(d)) : ['daily'];
  return {
    schedule_draft: {
      name: draft.alias.trim() || null, weekdays: tokens, start_date: null, end_date: null, repeat: 'repeat', tags: [],
      conditions: shabbat && opts.shabbatSensor ? { items: [{ entity_id: opts.shabbatSensor, attribute: 'state', match_type: 'is', value: shabbat }], type: null, track: false } : { items: [], type: null, track: false },
      slots,
    },
  };
}
