/** Canonical JSON: keys sorted at every depth, compact, non-ASCII kept (the server's `sort_keys, separators, ensure_ascii=False`). */
export function canonicalJson(v: unknown): string {
  const sort = (x: unknown): unknown => (Array.isArray(x) ? x.map(sort) : isObj(x) ? Object.fromEntries(Object.keys(x).sort().map((k) => [k, sort(x[k])])) : x);
  return JSON.stringify(sort(v));
}

const SHA_K = (() => {
  const primes: number[] = [];
  for (let n = 2; primes.length < 64; n++) if (primes.every((p) => n % p)) primes.push(n);
  const frac32 = (x: number) => Math.floor((x - Math.floor(x)) * 4294967296) >>> 0;
  return { k: primes.map((p) => frac32(Math.cbrt(p))), h: primes.slice(0, 8).map((p) => frac32(Math.sqrt(p))) };
})();
/** SHA-256 of the UTF-8 text, lowercase hex (synchronous: the block fingerprints are needed while parsing). */
export function sha256Hex(text: string): string {
  const bytes = new TextEncoder().encode(text);
  const total = (((bytes.length + 9 + 63) >> 6) << 6);
  const buf = new Uint8Array(total);
  buf.set(bytes);
  buf[bytes.length] = 0x80;
  const dv = new DataView(buf.buffer);
  dv.setUint32(total - 8, Math.floor((bytes.length * 8) / 4294967296));
  dv.setUint32(total - 4, (bytes.length * 8) >>> 0);
  const h = Uint32Array.from(SHA_K.h);
  const w = new Uint32Array(64);
  const rotr = (x: number, n: number) => (x >>> n) | (x << (32 - n));
  for (let off = 0; off < total; off += 64) {
    for (let i = 0; i < 16; i++) w[i] = dv.getUint32(off + i * 4);
    for (let i = 16; i < 64; i++) {
      const s0 = rotr(w[i - 15], 7) ^ rotr(w[i - 15], 18) ^ (w[i - 15] >>> 3);
      const s1 = rotr(w[i - 2], 17) ^ rotr(w[i - 2], 19) ^ (w[i - 2] >>> 10);
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) >>> 0;
    }
    let [a, b, c, d, e, f, g, hh] = h;
    for (let i = 0; i < 64; i++) {
      const S1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
      const ch = (e & f) ^ (~e & g);
      const t1 = (hh + S1 + ch + SHA_K.k[i] + w[i]) >>> 0;
      const S0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
      const mj = (a & b) ^ (a & c) ^ (b & c);
      const t2 = (S0 + mj) >>> 0;
      hh = g; g = f; f = e; e = (d + t1) >>> 0; d = c; c = b; b = a; a = (t1 + t2) >>> 0;
    }
    h[0] = (h[0] + a) >>> 0; h[1] = (h[1] + b) >>> 0; h[2] = (h[2] + c) >>> 0; h[3] = (h[3] + d) >>> 0;
    h[4] = (h[4] + e) >>> 0; h[5] = (h[5] + f) >>> 0; h[6] = (h[6] + g) >>> 0; h[7] = (h[7] + hh) >>> 0;
  }
  return Array.from(h, (x) => x.toString(16).padStart(8, '0')).join('');
}
/** sha256/16 of the canonical raw: a locked block's identity (CR §6.2). Advisory on the client: the server's value wins (Python
 * prints `1.0` where JS prints `1`, so a float written that way can differ). */
export const fingerprintOf = (raw: unknown): string => sha256Hex(canonicalJson(raw)).slice(0, 16);
/** First 16 hex of SHA-256 over the canonical JSON of a stored config (CR §6.1): the item's revision. */
export const revisionOf = (config: unknown): string => fingerprintOf(config);

