function buildTrigger(b: TriggerBlock): Raw {
  const out: Raw = {};
  switch (b.type) {
    case 'state': out.trigger = 'state'; out.entity_id = [...b.entity_ids]; if (b.from !== undefined) out.from = b.from; if (b.to !== undefined) out.to = b.to; if (b.for) out.for = durOut(b.for); break;
    case 'numeric_state': out.trigger = 'numeric_state'; out.entity_id = [...b.entity_ids]; if (b.above != null) out.above = b.above; if (b.below != null) out.below = b.below; if (b.for) out.for = durOut(b.for); break;
    case 'time': out.trigger = 'time'; out.at = hms(b.at); break;
    case 'time_pattern': out.trigger = 'time_pattern'; if (b.hours != null) out.hours = b.hours; if (b.minutes != null) out.minutes = b.minutes; if (b.seconds != null) out.seconds = b.seconds; break;
    case 'sun': out.trigger = 'sun'; out.event = b.event; if (b.offset_min) out.offset = fmtOffset(b.offset_min); break;
    case 'homeassistant': out.trigger = 'homeassistant'; out.event = 'start'; break;
  }
  if (b.id) out.id = b.id;
  return out;
}
function buildCondition(b: ConditionBlock, ctx: ModelContext): Raw {
  switch (b.type) {
    case 'state': return { condition: 'state', entity_id: [...b.entity_ids], state: b.state, ...(b.for ? { for: durOut(b.for) } : {}) };
    case 'numeric_state': return { condition: 'numeric_state', entity_id: [...b.entity_ids], ...(b.above != null ? { above: b.above } : {}), ...(b.below != null ? { below: b.below } : {}) };
    case 'time': return { condition: 'time', ...(b.after ? { after: hms(b.after) } : {}), ...(b.before ? { before: hms(b.before) } : {}), ...(b.weekday && b.weekday.length ? { weekday: [...b.weekday] } : {}) };
    case 'sun': return { condition: 'sun', ...(b.after ? { after: b.after } : {}), ...(b.before ? { before: b.before } : {}) };
    case 'trigger': return { condition: 'trigger', id: [...b.ids] };
    case 'and': case 'or': case 'not': return { condition: b.type, conditions: b.conditions.map((c) => emitBlock(c, 'condition', ctx)) };
    case 'shabbat': {
      if (!ctx.shabbatSensor) throw new ModelError('shabbat_sensor_missing', 'no Shabbat sensor is configured');
      return { condition: 'state', entity_id: [ctx.shabbatSensor], state: b.mode === 'only_holy_days' ? 'on' : 'off' };
    }
  }
}
function buildAction(b: ActionBlock, ctx: ModelContext): Raw {
  const seq = (l: Block[]) => l.map((x) => emitBlock(x, 'action', ctx));
  switch (b.type) {
    case 'service': {
      const out: Raw = { action: b.action };
      const scriptCall = b.role === 'script' && b.action === b.entity_ids[0];
      if (b.entity_ids.length && !scriptCall) out.target = { entity_id: [...b.entity_ids] };
      if (Object.keys(b.data).length) out.data = clone(b.data);
      return out;
    }
    case 'delay': return { delay: durOut(b.delay) };
    case 'choose': return { choose: b.options.map((o) => ({ conditions: o.conditions.map((c) => emitBlock(c, 'condition', ctx)), sequence: seq(o.sequence) })), ...(b.default ? { default: seq(b.default) } : {}) };
    case 'if': return { if: b.conditions.map((c) => emitBlock(c, 'condition', ctx)), then: seq(b.then), ...(b.else ? { else: seq(b.else) } : {}) };
    case 'repeat_count': return { repeat: { count: b.count, sequence: seq(b.sequence) } };
    case 'condition': return emitBlock(b.condition, 'condition', ctx) as Raw;
    case 'stop': return { stop: b.message };
  }
}
function reparse(raw: unknown, section: Section, ctx: ModelContext): Block {
  return section === 'trigger' ? parseTrigger(raw, ctx) : section === 'condition' ? parseCondition(raw, ctx) : parseAction(raw, ctx);
}
/** The pre-2024.10 keys anywhere inside a raw (`platform` for `trigger`, `service` for `action`, `data_template`): such a raw is rewritten in the new schema when its item is saved. */
function hasLegacyKeys(v: unknown): boolean {
  if (Array.isArray(v)) return v.some(hasLegacyKeys);
  if (!isObj(v)) return false;
  if (('platform' in v && !('trigger' in v)) || ('service' in v && !('action' in v)) || 'data_template' in v) return true;
  return Object.values(v).some(hasLegacyKeys);
}
/** One block as the stored form (CR §6.2): a locked block is its `raw` untouched; a typed block whose fields still equal the ones parsed
 * from its `raw` is that `raw` untouched; a changed or new typed block is rebuilt in the new schema (the stored `alias`/`metadata` carried). */
export function emitBlock(block: Block, section: Section, ctx: ModelContext = {}): unknown {
  if (block.kind === 'locked') return block.raw;
  const build = (b: Block): Raw => (section === 'trigger' ? buildTrigger(b as TriggerBlock) : section === 'condition' ? buildCondition(b as ConditionBlock, ctx) : buildAction(b as ActionBlock, ctx));
  const built = build(block);
  if (block.raw === null || block.raw === undefined) return built;
  const orig = reparse(block.raw, section, ctx);
  if (orig.kind === 'typed' && !hasLegacyKeys(block.raw) && canonicalJson(build(orig)) === canonicalJson(built)) return block.raw;
  const out: Raw = isObj(block.raw) && block.raw.alias !== undefined ? { alias: block.raw.alias, ...built } : built;
  if (isObj(block.raw)) for (const k of ['metadata']) if (k in block.raw && !(k in out)) out[k] = block.raw[k];
  return out;
}

const NEW_KEY: Record<string, string> = { trigger: 'triggers', condition: 'conditions', action: 'actions' };

/** Orders `managed` like the stored item when there is one (so an untouched item is byte-identical), else HA's order. */
function orderLike(stored: Raw | null, managed: Array<[string, unknown]>, hasKey: (k: string) => boolean): Raw {
  const out: Raw = {};
  const map = new Map(managed);
  if (stored) {
    for (const k of Object.keys(stored)) {
      const nk = NEW_KEY[k] ?? k;
      if (map.has(nk) && !(nk in out)) { if (hasKey(nk)) out[nk] = map.get(nk); continue; }
      if (!map.has(nk) && !(k in out)) out[k] = clone(stored[k]);
    }
  }
  for (const [k, v] of managed) if (!(k in out) && hasKey(k)) out[k] = v;
  return out;
}

/** Writes a draft back as the stored item. `stored` (the item as it is stored, if any) supplies the key order, the unknown top-level keys
 * (carried unchanged: `variables`, `trigger_variables`, `initial_state`, `note`, `use_blueprint` ...) and the fields the draft does not model. */
export function draftToConfig(kind: 'automation', draft: AutomationDraft, stored?: unknown, ctx?: ModelContext, opts?: { id?: string | null }): Raw;
export function draftToConfig(kind: 'script', draft: ScriptDraft, stored?: unknown, ctx?: ModelContext, opts?: { id?: string | null }): Raw;
export function draftToConfig(kind: 'scene', draft: SceneDraft, stored?: unknown, ctx?: ModelContext, opts?: { id?: string | null }): Raw;
export function draftToConfig(kind: ItemKind, draft: AnyDraft, stored?: unknown, ctx?: ModelContext, opts?: { id?: string | null }): Raw;
export function draftToConfig(kind: ItemKind, draft: AnyDraft, stored: unknown = null, ctx: ModelContext = {}, opts: { id?: string | null } = {}): Raw {
  const st = isObj(stored) ? stored : null;
  const has = (k: string) => !!st && (k in st || (k === 'triggers' && 'trigger' in st) || (k === 'conditions' && 'condition' in st) || (k === 'actions' && 'action' in st));
  const id = opts.id ?? (st && typeof st.id === 'string' ? st.id : null);
  if (kind === 'automation') {
    const d = draft as AutomationDraft;
    const managed: Array<[string, unknown]> = [
      ['id', id], ['alias', d.alias], ['description', d.description], ['triggers', d.triggers.map((t) => emitBlock(t, 'trigger', ctx))],
      ['conditions', d.conditions.map((c) => emitBlock(c, 'condition', ctx))], ['actions', d.actions.map((a) => emitBlock(a, 'action', ctx))], ['mode', d.mode], ['max', d.max],
    ];
    return orderLike(st, managed, (k) => (k === 'id' ? id !== null : k === 'description' ? d.description !== '' || !st || has(k) : k === 'conditions' ? d.conditions.length > 0 || !st || has(k) : k === 'mode' ? d.mode !== 'single' || !st || has(k) : k === 'max' ? d.max !== null : true));
  }
  if (kind === 'script') {
    const d = draft as ScriptDraft;
    const storedFields = st && isObj(st.fields) ? st.fields : {};
    const fields: Raw = {};
    for (const f of d.fields) {
      const base = isObj(storedFields[f.key]) ? (storedFields[f.key] as Raw) : {};
      const keep = base.selector !== undefined && canonicalJson(parseSelector(base.selector)) === canonicalJson(f.selector);
      fields[f.key] = { ...base, name: f.name, ...(f.required || 'required' in base ? { required: f.required } : {}), ...(f.default !== undefined ? { default: f.default } : {}), selector: keep ? base.selector : selectorOut(f.selector, base.selector) };
    }
    const managed: Array<[string, unknown]> = [['alias', d.alias], ['description', d.description], ['icon', d.icon], ['mode', d.mode], ['max', d.max], ['fields', fields], ['sequence', d.sequence.map((a) => emitBlock(a, 'action', ctx))]];
    return orderLike(st, managed, (k) => (k === 'description' ? d.description !== '' || !st || has(k) : k === 'icon' ? d.icon !== null : k === 'mode' ? d.mode !== 'single' || !st || has(k) : k === 'max' ? d.max !== null : k === 'fields' ? d.fields.length > 0 || has(k) : true));
  }
  const d = draft as SceneDraft;
  const storedEnt = st && isObj(st.entities) ? st.entities : {};
  const entities: Raw = {};
  for (const m of d.members) {
    const prev = storedEnt[m.entity_id];
    entities[m.entity_id] = typeof prev === 'string' && !Object.keys(m.attributes).length && prev === m.state ? prev : { state: m.state, ...clone(m.attributes) };
  }
  const managed: Array<[string, unknown]> = [['id', id], ['name', d.name], ['icon', d.icon], ['entities', entities]];
  return orderLike(st, managed, (k) => (k === 'id' ? id !== null : k === 'icon' ? d.icon !== null : true));
}

