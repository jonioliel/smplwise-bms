/** The sections the remote draws for this screen: switched on in the config AND backed by a capability; split into the
 * always-visible ones and the ones behind "עוד מקשים". Recent is shown only when there is something to repeat. */
export function remoteSections(d: Pick<MediaDeviceDetail, 'caps' | 'remote' | 'recent'>): { main: RemoteSection[]; more: RemoteSection[] } {
  const { caps } = d;
  const has = (s: RemoteSection): boolean => {
    if (s === 'recent') return d.recent.length > 0 && (caps.sources || caps.apps);
    if (s === 'vol') return caps.volume_set || caps.volume_step || caps.mute;
    if (s === 'pbk') return caps.transport.play || caps.transport.pause;
    if (s === 'text') return caps.text;
    if (s === 'touch') return caps.touchpad;
    return (SECTION_KEYS[s] ?? []).some((k) => caps.keys.includes(k));
  };
  const main: RemoteSection[] = [];
  const more: RemoteSection[] = [];
  for (const { id, on } of d.remote.sections) {
    if (!on || !has(id)) continue;
    (d.remote.more.includes(id) ? more : main).push(id);
  }
  return { main, more };
}

/** The layout the page draws: the installation's, with the personal override on top (only when the server sent one). */
export function effectiveLayout(installation: MediaLayout, personal: MediaPersonal | null): MediaLayout {
  if (!personal) return installation;
  const cards: Record<string, CardCfg> = { ...installation.cards };
  for (const [k, v] of Object.entries(personal.cards)) cards[k] = { ...(cards[k] ?? DEFAULT_CARD), ...v };
  return { ...installation, group_by: personal.group_by ?? installation.group_by, order: personal.order ?? installation.order, cards };
}

export interface CardGroup {
  id: string;
  label: string;
  items: { device: MediaDevice; size: Size }[];
}

/** Orders and groups the visible cards: "מועדפים" first, then by floor / area / one group; hidden cards dropped; devices
 * the layout does not know yet go last in their group at the default size. */
export function resolveCards(devices: MediaDevice[], layout: MediaLayout, phone: boolean): CardGroup[] {
  const cfg = (k: string): CardCfg => layout.cards[k] ?? DEFAULT_CARD;
  const shown = devices.filter((d) => {
    const c = cfg(d.key);
    return phone ? c.phone_on ?? c.on : c.on;
  });
  const rank = new Map(layout.order.map((k, i) => [k, i]));
  const byOrder = (a: MediaDevice, b: MediaDevice) => (rank.get(a.key) ?? 1e6) - (rank.get(b.key) ?? 1e6) || a.name.localeCompare(b.name, 'he');
  const size = (d: MediaDevice): Size => {
    const c = cfg(d.key);
    return phone ? c.phone_size ?? (c.size === 'l' ? 'm' : c.size) : c.size;
  };
  const item = (d: MediaDevice) => ({ device: d, size: size(d) });
  const groups: CardGroup[] = [];
  const pinned = layout.pinned.map((k) => shown.find((d) => d.key === k)).filter((d): d is MediaDevice => !!d);
  if (pinned.length) groups.push({ id: 'pinned', label: 'מועדפים', items: pinned.map(item) });
  const rest = shown.filter((d) => !layout.pinned.includes(d.key)).sort(byOrder);
  if (layout.group_by === 'none') {
    if (rest.length) groups.push({ id: 'all', label: 'כל המסכים', items: rest.map(item) });
    return groups;
  }
  const idOf = (d: MediaDevice) => (layout.group_by === 'floor' ? d.floor_id : d.area_id) ?? 'none';
  const nameOf = (d: MediaDevice) => (layout.group_by === 'floor' ? d.floor_name : d.area_name) ?? 'ללא שיוך';
  const ids = [...new Set(rest.map(idOf))];
  const floorRank = new Map(layout.floor_order.map((f, i) => [f, i]));
  if (layout.group_by === 'floor') ids.sort((a, b) => (floorRank.get(a) ?? 1e6) - (floorRank.get(b) ?? 1e6));
  for (const id of ids) {
    const members = rest.filter((d) => idOf(d) === id);
    groups.push({ id, label: nameOf(members[0]), items: members.map(item) });
  }
  return groups;
}

/** Moves one key inside an order list (the editor's up / down and drop target). */
export function moveKey(order: string[], key: string, to: number): string[] {
  const from = order.indexOf(key);
  if (from < 0) return order;
  const out = [...order];
  out.splice(from, 1);
  out.splice(Math.max(0, Math.min(out.length, to)), 0, key);
  return out;
}

/** The screens a floor / area "כבה מסכים" would send (the preview's `send` count; the server decides). */
export function bulkCandidates(devices: MediaDevice[]): MediaDevice[] {
  return devices.filter((d) => d.can.bulk && d.caps.power_off && ((isOn(d.live) && d.live.confirmed) || d.live.power === 'art'));
}

/** Client mirror of the server's key limit: a token bucket of `burst` presses refilled at `perSecond` (5/s, burst 8, the
 * same rule as services/media_commands.py). A press over it is dropped - never queued. */
export class KeyThrottle {
  private tokens: number;
  private last: number | null = null;
  constructor(private readonly perSecond = KEY_RATE_PER_S, private readonly burst = KEY_BURST) {
    this.tokens = burst;
  }
  /** true = send now; false = drop this press. */
  take(now: number = Date.now()): boolean {
    if (this.last !== null) this.tokens = Math.min(this.burst, this.tokens + (Math.max(0, now - this.last) / 1000) * this.perSecond);
    this.last = now;
    if (this.tokens < 1) return false;
    this.tokens -= 1;
    return true;
  }
}
