// ------------------------------------------------------------------------------------------------ pure helpers

export const isOn = (l: Pick<MediaLive, 'power'>): boolean => l.power === 'on';
/** Lit on the card (glow): on, or showing art. */
export const isLit = (l: Pick<MediaLive, 'power'>): boolean => l.power === 'on' || l.power === 'art';
export const isDead = (l: Pick<MediaLive, 'power'>): boolean => l.power === 'unavailable' || l.power === 'unknown';

/** The card's state line (clean operator wording, no hints). */
export function stateText(d: Pick<MediaDevice, 'live'>): string {
  const l = d.live;
  if (l.power === 'unavailable') return 'לא זמין';
  if (l.power === 'unknown') return 'מצב לא ידוע';
  if (l.power === 'art') return 'מצב אמנות';
  if (l.power === 'off' || l.power === 'standby') return 'כבוי';
  if (l.play === 'playing') return l.now.label ? `מנגן · ${l.now.label}` : 'מנגן';
  if (l.play === 'paused') return l.now.label ? `מושהה · ${l.now.label}` : 'מושהה';
  return l.now.label || 'דולק';
}

/** Whether the UI should offer a command at all (the server re-checks everything). */
export function commandOffered(d: Pick<MediaDevice, 'live' | 'caps' | 'can' | 'public'>, c: MediaCommand): boolean {
  const { live, caps, can } = d;
  if (POWER_COMMANDS.includes(c.command) ? !can.power : !can.control) return false;
  if (PUBLIC_COMMANDS.includes(c.command) && !can.public_ok) return false;
  if (isDead(live)) return false;
  if (c.command === 'power_on') return caps.power_on && live.power !== 'on';
  if (c.command === 'power_off') return caps.power_off && isLit(live);
  if (!isOn(live)) return false; // off, standby, art: only power
  switch (c.command) {
    case 'volume_set': return caps.volume_set && c.level >= 0 && c.level <= 100;
    case 'volume_step': return caps.volume_step || caps.keys.includes(c.direction === 'up' ? 'volup' : 'voldown');
    case 'mute': return caps.mute;
    case 'source': return caps.sources;
    case 'app': return caps.apps;
    case 'sound_output': return caps.sound_outputs.includes(c.output);
    case 'transport': return c.action === 'play_pause' ? caps.transport.play || caps.transport.pause : c.action === 'previous' ? caps.transport.previous : caps.transport[c.action];
    case 'key': return caps.keys.includes(c.key);
    case 'text': return caps.text && c.text.length > 0 && c.text.length <= TEXT_MAX;
  }
  return false;
}

