export function tableTemplate(key: TableTextKey, lang: 'he' | 'en' = ticketsLang()): string {
  return (lang === 'en' ? en[key] : undefined) ?? he[key];
}

/** A text of the table: the template in the document's language, the module's name rendered (D33), then `{var}`s. */
export function tbt(key: TableTextKey, vars?: Record<string, string | number>): string {
  const lang = ticketsLang();
  const named = tn(tableTemplate(key, lang), lang as TicketLang);
  return vars ? named.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : named;
}

