export type WaTextKey = keyof typeof he;

function lang(): 'he' | 'en' {
  return docLang(['en']);
}

export function wt(key: WaTextKey, vars?: Record<string, string | number>): string {
  const raw = (lang() === 'en' ? en[key] : undefined) ?? he[key] ?? key;
  return fill(raw, vars);
}

