export function sedLang(): 'he' | 'en' {
  return docLang(['en']);
}

export function sed(key: Key, vars?: Record<string, string | number>): string {
  const raw = (sedLang() === 'en' ? en[key] : undefined) ?? he[key];
  return fill(raw, vars);
}

