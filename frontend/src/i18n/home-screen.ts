export type HsLang = 'he' | 'en' | 'ar' | 'ru';

export function hsLang(): HsLang {
  const l = typeof document !== 'undefined' ? (document.documentElement.lang || '').toLowerCase() : '';
  return l.startsWith('en') ? 'en' : l.startsWith('ar') ? 'ar' : l.startsWith('ru') ? 'ru' : 'he';
}

const TABLES: Record<HsLang, Partial<Record<HsKey, string>>> = { he, en, ar: {}, ru: {} };
/** The columns that are not translated yet (they show Hebrew). */
export const HS_UNTRANSLATED: readonly HsLang[] = ['ar', 'ru'];

/** One phrase; `{n}`-style holes are filled from `vars`. */
export function hs(key: HsKey, vars: Record<string, string | number> = {}, lang: HsLang = hsLang()): string {
  let s = TABLES[lang][key] ?? he[key];
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export const HS_KEYS = Object.keys(he) as HsKey[];
export const HS_TABLES = TABLES;
