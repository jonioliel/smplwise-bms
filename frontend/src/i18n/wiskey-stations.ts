type Widen<T> = T extends string ? string : T extends readonly (infer U)[] ? readonly Widen<U>[] : { [K in keyof T]: Widen<T[K]> };
export type StationsText = Widen<typeof he>;

const en: StationsText = packTable<typeof import('./lang/en/i18n/wiskey-stations').en>('en', 'i18n/wiskey-stations', 'en');

/** The catalogue in force when a screen renders. */
export function ws(): StationsText {
  return docLang(['en']) === 'en' ? en : he;
}

/** Fills `{name}` placeholders. A missing variable keeps its placeholder (visible in review, never blank). */
export function fill(template: string, vars: Record<string, string | number> = {}): string {
  return coreFill(template, vars);
}

