const en: Partial<Record<Key, string>> = withEntries(packTable<typeof import('./lang/en/i18n/incidents').en>('en', 'i18n/incidents', 'en'), {
  tab: NAV_IT.en.tab,
});

export type ItKey = Key;
export type ItLang = 'he' | 'en';

export function itLang(): ItLang {
  return docLang(['en']);
}

const TABLES: Record<ItLang, Partial<Record<Key, string>>> = { he, en };

export function it(key: Key, vars?: Record<string, string | number>, lang: ItLang = itLang()): string {
  const raw = TABLES[lang][key] ?? he[key] ?? key;
  return fill(raw, vars);
}

export const IT_KEYS = Object.keys(he) as Key[];
export const IT_TABLES = TABLES;

registerCatalogue('i18n/incidents', { he, en });
