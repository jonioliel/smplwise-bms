export type ItKey = Key;
export type ItLang = 'he' | 'en';

export function itLang(): ItLang {
  const l = typeof document !== 'undefined' ? (document.documentElement.lang || '').toLowerCase() : '';
  return l.startsWith('en') ? 'en' : 'he';
}

const TABLES: Record<ItLang, Partial<Record<Key, string>>> = { he, en };

export function it(key: Key, vars?: Record<string, string | number>, lang: ItLang = itLang()): string {
  const raw = TABLES[lang][key] ?? he[key] ?? key;
  return vars ? raw.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : raw;
}

