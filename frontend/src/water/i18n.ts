export type WtKey = Key;
export type WtLang = 'he' | 'en';

export function wtLang(): WtLang {
  const l = typeof document !== 'undefined' ? (document.documentElement.lang || '').toLowerCase() : '';
  return l.startsWith('en') ? 'en' : 'he';
}

const TABLES: Record<WtLang, Partial<Record<Key, string>>> = { he, en };

export function wt(key: Key, vars?: Record<string, string | number>, lang: WtLang = wtLang()): string {
  const raw = TABLES[lang][key] ?? he[key] ?? key;
  return vars ? raw.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : raw;
}

export const WT_KEYS = Object.keys(he) as Key[];
export const WT_TABLES = TABLES;
