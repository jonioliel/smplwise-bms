export const RFQ_TEXT: Readonly<Record<Lang, Record<RfqKey, string>>> = { he, en, ar, ru };

/** One string of the RFQ mode: the language's text (Hebrew when missing), then the `{name}` variables (a typed value is never read as a placeholder). */
export function rfqText(lang: Lang, key: RfqKey, vars: Record<string, string | number> = {}): string {
  const raw = RFQ_TEXT[lang]?.[key] ?? he[key] ?? key;
  return raw.replace(/\{([a-z_]+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

export function isRfqKey(key: string): key is RfqKey {
  return key in he;
}
