export const PORTAL_TEXT: Readonly<Record<Lang, Record<PortalKey, string>>> = { he, en, ar, ru };

/** One string of the portal: the language's text (Hebrew when missing), then the `{name}` variables (a value is never read as a token). */
export function pt(lang: Lang, key: PortalKey, vars: Record<string, string | number> = {}): string {
  const raw = PORTAL_TEXT[lang]?.[key] ?? he[key] ?? key;
  return raw.replace(/\{([a-z_]+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

export function isPortalKey(key: string): key is PortalKey {
  return key in he;
}
