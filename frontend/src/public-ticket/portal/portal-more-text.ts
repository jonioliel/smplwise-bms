export const MORE_TEXT: Readonly<Record<Lang, Record<MoreKey, string>>> = { he, en, ar, ru };

/** One string: the language's text (Hebrew when missing), then the `{name}` variables (a value is never read as a token). */
export function mt(lang: Lang, key: MoreKey, vars: Record<string, string | number> = {}): string {
  const raw = MORE_TEXT[lang]?.[key] ?? he[key] ?? key;
  return raw.replace(/\{([a-z_]+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}
