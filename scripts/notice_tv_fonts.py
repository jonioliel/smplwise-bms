#!/usr/bin/env python3
"""LOBBY-STYLES-2300: build frontend/src/notice-tv/tv-fonts.css from the OFL woff2 files in frontend/public/fonts/lobby.

The TV board page is served on its own (the LAN listener serves only the files the page's script reaches), so the fonts are inlined as
data: URLs, exactly as Heebo is in tv.css. Re-run after adding a font file:  py -3.12 scripts/notice_tv_fonts.py
Sources, licences and sha256 of every file: docs/fonts/LOBBY_FONTS.md."""
from __future__ import annotations

import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "frontend" / "public" / "fonts" / "lobby"
OUT = ROOT / "frontend" / "src" / "notice-tv" / "tv-fonts.css"
RANGE = {
    "hebrew": "U+0307-0308, U+0590-05FF, U+200C-2010, U+20AA, U+25CC, U+FB1D-FB4F",
    "latin": "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD",
}
# (file stem, css family, weight)
FACES = [
    *[(f"plex-sans-hebrew-{s}-{w}", "LobbySans", str(w)) for w in (200, 300, 400, 500, 600) for s in ("hebrew", "latin")],
    *[(f"plex-mono-latin-{w}", "LobbyMono", str(w)) for w in (400, 500)],
    ("frank-ruhl-libre-hebrew-300-700", "LobbyFrank", "300 700"), ("frank-ruhl-libre-latin-300-700", "LobbyFrank", "300 700"),
    *[(f"david-libre-{s}-{w}", "LobbyDavid", str(w)) for w in (400, 500, 700) for s in ("hebrew", "latin")],
    ("bodoni-moda-latin-400-700", "LobbyBodoni", "400 700"),
]


def main() -> None:
    out = ["/* LOBBY-STYLES-2300 - GENERATED by scripts/notice_tv_fonts.py from frontend/public/fonts/lobby (SIL Open Font License; see docs/fonts/LOBBY_FONTS.md).",
           "   IBM Plex Sans Hebrew + IBM Plex Mono (hi-tech styles), Frank Ruhl Libre + David Libre + Bodoni Moda (luxury styles), inlined: the TV page reaches no other file. */"]
    for stem, fam, wt in FACES:
        data = base64.b64encode((SRC / f"{stem}.woff2").read_bytes()).decode("ascii")
        sub = "hebrew" if "-hebrew-" in stem else "latin"
        out.append(f"@font-face {{ font-family: \"{fam}\"; font-style: normal; font-weight: {wt}; font-display: block; src: url(data:font/woff2;base64,{data}) format(\"woff2\"); unicode-range: {RANGE[sub]}; }}")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(OUT, OUT.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
