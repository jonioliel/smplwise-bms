#!/usr/bin/env python3
"""LOBBY-STYLES-2300 / CR-TV-FONTS-ESCAPE-2443: build the TV board's lobby font style sheets from the OFL woff2 files in frontend/fonts-src/lobby.

One style sheet per style family (review 08:F04): frontend/src/notice-tv/tv-fonts-hitech.css (Lumen, Axis, Prism) and tv-fonts-luxury.css
(Gallery, Concierge, Stone). main.ts loads only the active family's sheet, with a dynamic import() before it draws that style, so a board
on another style downloads none of them. The fonts stay inlined as data: URLs: the LAN listener serves only the files the page's script
reaches (smplwise_vms/backend/smplwise/services/notices/page.py follows the built JS chunks: "./x.js" imports and "assets/x.css" names, which
is how Vite names a dynamically imported style sheet), never a font file by its own URL.

The woff2 sources live outside frontend/public on purpose (Vite copies public/ into www, and nothing reads them there at run time). The
OFL texts stay in frontend/public/fonts/lobby as well, so the licences still travel with the add-on.
Re-run after adding a font file:  py -3.12 scripts/notice_tv_fonts.py      Check only (CI):  py -3.12 scripts/notice_tv_fonts.py --check
Sources, licences and sha256 of every file: docs/fonts/LOBBY_FONTS.md."""
from __future__ import annotations

import base64
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "frontend" / "fonts-src" / "lobby"
OUT_DIR = ROOT / "frontend" / "src" / "notice-tv"
RANGE = {
    "hebrew": "U+0307-0308, U+0590-05FF, U+200C-2010, U+20AA, U+25CC, U+FB1D-FB4F",
    "latin": "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD",
}
# style family -> (file stem, css family, weight); the order inside a family is the order of the former single tv-fonts.css
FAMILIES: dict[str, list[tuple[str, str, str]]] = {
    "hitech": [
        *[(f"plex-sans-hebrew-{s}-{w}", "LobbySans", str(w)) for w in (200, 300, 400, 500, 600) for s in ("hebrew", "latin")],
        *[(f"plex-mono-latin-{w}", "LobbyMono", str(w)) for w in (400, 500)],
    ],
    "luxury": [
        ("frank-ruhl-libre-hebrew-300-700", "LobbyFrank", "300 700"), ("frank-ruhl-libre-latin-300-700", "LobbyFrank", "300 700"),
        *[(f"david-libre-{s}-{w}", "LobbyDavid", str(w)) for w in (400, 500, 700) for s in ("hebrew", "latin")],
        ("bodoni-moda-latin-400-700", "LobbyBodoni", "400 700"),
    ],
}
HEAD = {
    "hitech": "IBM Plex Sans Hebrew (\"LobbySans\") + IBM Plex Mono (\"LobbyMono\"): the hi-tech styles Lumen, Axis, Prism",
    "luxury": "Frank Ruhl Libre (\"LobbyFrank\") + David Libre (\"LobbyDavid\") + Bodoni Moda (\"LobbyBodoni\"): the luxury styles Gallery, Concierge, Stone",
}


def render(family: str) -> str:
    out = [f"/* LOBBY-STYLES-2300 / CR-TV-FONTS-ESCAPE-2443 - GENERATED by scripts/notice_tv_fonts.py from frontend/fonts-src/lobby (SIL Open Font License 1.1;",
           f"   see docs/fonts/LOBBY_FONTS.md). {HEAD[family]}. Loaded by main.ts only while a style of this family is shown; inlined: the TV page reaches no other file. */"]
    for stem, fam, wt in FAMILIES[family]:
        data = base64.b64encode((SRC / f"{stem}.woff2").read_bytes()).decode("ascii")
        sub = "hebrew" if "-hebrew-" in stem else "latin"
        out.append(f"@font-face {{ font-family: \"{fam}\"; font-style: normal; font-weight: {wt}; font-display: block; src: url(data:font/woff2;base64,{data}) format(\"woff2\"); unicode-range: {RANGE[sub]}; }}")
    return "\n".join(out) + "\n"


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for family in FAMILIES:
        path = OUT_DIR / f"tv-fonts-{family}.css"
        text = render(family)
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(ROOT)))
            continue
        path.write_text(text, encoding="utf-8", newline="\n")
        print(path, path.stat().st_size, "bytes")
    if stale:
        print("stale (re-run scripts/notice_tv_fonts.py):", ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
