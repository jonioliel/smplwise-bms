#!/usr/bin/env python3
"""PY-CONSTRAINTS-LOCK-2407: the full Python constraints lock of the add-on image.

`smplwise_vms/backend/requirements.txt` keeps the direct requirements (exact pins and a few bounded ranges);
`smplwise_vms/backend/constraints.txt` pins EVERY package of the resolved set exactly, and the Dockerfile installs with
`pip install -r requirements.txt -c constraints.txt`, so the Supervisor's install-time resolution cannot move a transitive
package (or a range pin) to whatever was released the day before.

The resolution targets the image, not the machine running this script: CPython 3.12 on Alpine 3.22 (musl), once per arch of
build.yaml (amd64 = x86_64-unknown-linux-musl, aarch64 = aarch64-unknown-linux-musl). It uses uv (`uv pip compile
--python-platform`), because pip evaluates environment markers against the interpreter that runs it (on the Windows
workstation it would drop uvloop and add colorama). The two arch resolutions must be identical; the file then needs no markers.

Modes (one per call; default --write):
  --write           regenerate constraints.txt (needs uv: on PATH, `python -m uv`, or LOCK_PYTHON_UV=<path>)
  --diff            regenerate into memory and compare with the committed file (exit 1 when the resolution moved)
  --check           offline: requirements and constraints agree (every direct requirement pinned in constraints at a version
                    that satisfies it, exact pins only, no extras, no duplicates). Exit 1 on a mismatch.
  --verify-wheels   online (PyPI JSON API, read-only): every pinned version has a wheel for CPython 3.12 musllinux on each
                    arch; prints wheel / sdist-only / missing per arch. Exit 1 when a version has neither for an arch
                    (with --strict also when it is sdist-only). Exit 3 when PyPI cannot be reached.
  --pip-resolve     online: a clean `pip install --dry-run --report` of -r requirements.txt -c constraints.txt for the
                    image's platform (musllinux_1_2_<arch>, CPython 3.12, binary only) with the pip of THIS interpreter, and
                    the report compared with constraints.txt. pip evaluates markers on the host, so the result is exact only
                    on a Linux host of the same arch (the runner: amd64); elsewhere it is skipped (exit 3) unless --force.
Options: --root <checkout> (default: this script's repository), --json <out.json>, --arch amd64|aarch64 (repeatable).
"""
from __future__ import annotations

import argparse
import json
import os
import platform
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.error
import urllib.request
from pathlib import Path

PYTHON_VERSION = "3.12"
ARCHES = {"amd64": ("x86_64-unknown-linux-musl", "x86_64"), "aarch64": ("aarch64-unknown-linux-musl", "aarch64")}
MUSL_MINOR_MAX = 2          # Alpine 3.22 ships musl 1.2.x: musllinux_1_0 .. musllinux_1_2 wheels install
HEADER = """\
# GENERATED by scripts/lock_python.py (PY-CONSTRAINTS-LOCK-2407) - do not edit by hand; regenerate with
#   python scripts/lock_python.py --write        (needs uv; then: python scripts/lock_python.py --check --verify-wheels)
# The full resolved set of smplwise_vms/backend/requirements.txt for the add-on image: CPython {py} on Alpine 3.22 (musl),
# resolved separately for {targets} - the two resolutions are identical, so no line needs a marker.
# The Dockerfile installs `pip install -r requirements.txt -c constraints.txt`: requirements.txt says WHAT is installed,
# this file fixes the exact version of every package, direct or transitive. No hashes: pip turns hash-checking mode on for
# the whole install as soon as a constraints line carries --hash, and that mode rejects the range pins of requirements.txt
# (docs/changes/PY-CONSTRAINTS-LOCK-2407.md section 3).
# Resolver: {uv}.
"""


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


# ---------------------------------------------------------------- parsing (no third-party import: the runner's python3 too)

REQ_RE = re.compile(r"^([A-Za-z0-9][A-Za-z0-9_.\-]*)\s*(\[[^\]]*\])?\s*(.*)$")


def parse_requirements(text: str) -> list[dict]:
    """[{name, extras, spec, marker, line}] of a requirements file (comments and blank lines skipped)."""
    out = []
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if line.startswith("-"):
            raise ValueError(f"line {n}: options are not allowed here: {raw!r}")
        spec, _, marker = line.partition(";")
        m = REQ_RE.match(spec.strip())
        if not m:
            raise ValueError(f"line {n}: unparsed requirement: {raw!r}")
        out.append({"name": m.group(1), "extras": (m.group(2) or "").strip("[]"), "spec": m.group(3).strip(),
                    "marker": marker.strip(), "line": n})
    return out


def parse_constraints(text: str) -> dict[str, str]:
    """{normalized name: version}; raises on anything but `name==version` lines or a duplicate."""
    pins: dict[str, str] = {}
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        m = re.match(r"^([A-Za-z0-9][A-Za-z0-9_.\-]*)==([A-Za-z0-9_.+!\-]+)$", line)
        if not m:
            raise ValueError(f"constraints line {n} is not `name==version` (no extras, markers, ranges or hashes): {raw!r}")
        key = norm(m.group(1))
        if key in pins:
            raise ValueError(f"constraints line {n}: duplicate {m.group(1)}")
        pins[key] = m.group(2)
    return pins


def _vkey(v: str) -> tuple:
    """A comparison key for the plain release versions used here (N(.N)* with an optional pre/post suffix)."""
    m = re.match(r"^(\d+(?:\.\d+)*)(.*)$", v)
    if not m:
        return ((), v)
    nums = tuple(int(x) for x in m.group(1).split("."))
    while len(nums) > 1 and nums[-1] == 0:
        nums = nums[:-1]
    rest = m.group(2)
    # a pre-release (a/b/rc/dev) sorts before the release, a post-release after it
    rank = 1 if not rest else (2 if rest.lstrip(".").startswith("post") else 0)
    return (nums, rank, rest)


def satisfies(version: str, spec: str) -> bool:
    """Does `version` satisfy a comma-separated specifier (==, !=, >=, <=, >, <, ~=; `==X.*` prefix)? Empty spec: yes."""
    try:
        from packaging.specifiers import SpecifierSet  # exact semantics when packaging is present
        return SpecifierSet(spec).contains(version, prereleases=True)
    except ImportError:
        return satisfies_simple(version, spec)


def satisfies_simple(version: str, spec: str) -> bool:
    """The fallback of satisfies() for an interpreter without `packaging` (the runner's system python3)."""
    for part in filter(None, (p.strip() for p in spec.split(","))):
        m = re.match(r"^(===|==|!=|>=|<=|~=|>|<)\s*(\S+)$", part)
        if not m:
            raise ValueError(f"unsupported specifier {part!r}")
        op, want = m.groups()
        if op in ("==", "===", "!=") and want.endswith(".*"):
            hit = (version + ".").startswith(want[:-1])
            ok = hit if op != "!=" else not hit
        else:
            a, b = _vkey(version), _vkey(want)
            ok = {"==": a == b, "===": version == want, "!=": a != b, ">=": a >= b, "<=": a <= b, ">": a > b,
                  "<": a < b}.get(op)
            if op == "~=":
                base = want.split(".")[:-1]
                ok = a >= b and version.split(".")[:len(base)] == base
        if not ok:
            return False
    return True


def check(requirements: str, constraints: str) -> list[str]:
    """Problems of the pair (empty list = they agree)."""
    problems = []
    try:
        reqs = parse_requirements(requirements)
        pins = parse_constraints(constraints)
    except ValueError as exc:
        return [str(exc)]
    if not pins:
        return ["constraints.txt pins nothing"]
    for r in reqs:
        key = norm(r["name"])
        if key not in pins:
            problems.append(f"{r['name']} (requirements.txt line {r['line']}) is not pinned in constraints.txt")
            continue
        if not satisfies(pins[key], r["spec"]):
            problems.append(f"{r['name']}=={pins[key]} in constraints.txt does not satisfy {r['name']}{r['spec']} "
                            f"(requirements.txt line {r['line']})")
    return problems


# ---------------------------------------------------------------- uv resolution

def find_uv() -> list[str] | None:
    env = os.environ.get("LOCK_PYTHON_UV")
    if env:
        return [env]
    exe = shutil.which("uv")
    if exe:
        return [exe]
    try:
        subprocess.run([sys.executable, "-m", "uv", "--version"], capture_output=True, check=True)
        return [sys.executable, "-m", "uv"]
    except (OSError, subprocess.CalledProcessError):
        return None


def resolve(root: Path, uv: list[str]) -> tuple[dict[str, str], str]:
    """Resolve requirements.txt for each arch; returns ({name: version} in file spelling order, uv version)."""
    req = root / "smplwise_vms" / "backend" / "requirements.txt"
    ver = subprocess.run(uv + ["--version"], capture_output=True, text=True, check=True).stdout.strip().split(" (")[0]
    sets = {}
    with tempfile.TemporaryDirectory() as td:
        for arch, (target, _) in ARCHES.items():
            out = Path(td) / f"{arch}.txt"
            cmd = uv + ["pip", "compile", str(req), "--python-version", PYTHON_VERSION, "--python-platform", target,
                        "--no-header", "--no-annotate", "--quiet", "--no-config", "-o", str(out)]
            # an index other than PyPI (a developer's uv.toml / UV_INDEX_URL) would change the lock silently
            env = {k: v for k, v in os.environ.items() if not k.startswith(("UV_INDEX", "UV_EXTRA_INDEX", "UV_DEFAULT_INDEX"))}
            subprocess.run(cmd, check=True, env=env)
            text = out.read_text(encoding="utf-8")
            lines = [ln.strip() for ln in text.splitlines() if ln.strip() and not ln.lstrip().startswith("#")]
            sets[arch] = lines
    first, *rest = sets.values()
    for arch, lines in sets.items():
        if lines != first:
            a, b = set(first), set(lines)
            raise SystemExit(f"the resolutions differ per arch ({arch}): only amd64 {sorted(a - b)}, only {arch} {sorted(b - a)} - "
                             "constraints.txt would need markers; resolve this by hand (see the change note)")
    pins = {}
    for ln in first:
        name, _, version = ln.partition("==")
        if ";" in version or not version:
            raise SystemExit(f"unexpected uv output line: {ln!r}")
        pins[name] = version
    return pins, ver


def render(pins: dict[str, str], uv_version: str) -> str:
    targets = " and ".join(f"{a} ({t})" for a, (t, _) in ARCHES.items())
    body = "".join(f"{n}=={v}\n" for n, v in sorted(pins.items(), key=lambda kv: norm(kv[0])))
    return HEADER.format(py=PYTHON_VERSION, targets=targets, uv=uv_version) + body


# ---------------------------------------------------------------- wheel availability (PyPI JSON, read-only)

def _wheel_ok(filename: str, arch: str) -> bool:
    """Would pip on CPython 3.12 / musllinux_1_2_<arch> install this wheel file?"""
    if not filename.endswith(".whl"):
        return False
    parts = filename[:-4].split("-")
    if len(parts) < 5:
        return False
    pys, abis, plats = parts[-3].split("."), parts[-2].split("."), parts[-1].split(".")
    machine = ARCHES[arch][1]
    plat_ok = any(p == "any" or re.fullmatch(rf"musllinux_1_([0-{MUSL_MINOR_MAX}])_{machine}", p) for p in plats)
    if not plat_ok:
        return False
    for py in pys:
        for abi in abis:
            if abi == "none" and py in ("py3", "py312", "cp312"):
                return True
            if abi == "cp312" and py == "cp312":
                return True
            if abi == "abi3" and re.fullmatch(r"cp3(\d+)", py) and int(py[3:]) <= 12:
                return True
    return False


def pypi_files(name: str, version: str, timeout: float = 20.0) -> list[str]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=timeout) as resp:  # noqa: S310 - fixed https host
        data = json.load(resp)
    return [u["filename"] for u in data.get("urls", []) if not u.get("yanked")]


def verify_wheels(pins: dict[str, str], arches: list[str]) -> dict:
    rows = []
    for name, version in sorted(pins.items()):
        files = pypi_files(name, version)
        row = {"name": name, "version": version}
        for arch in arches:
            if any(_wheel_ok(f, arch) for f in files):
                row[arch] = "wheel"
            elif any(f.endswith((".tar.gz", ".zip")) for f in files):
                row[arch] = "sdist-only"
            else:
                row[arch] = "missing"
        row["arch_specific"] = any("musllinux" in f for f in files)   # pip picks a binary musllinux wheel per arch
        rows.append(row)
    return {"rows": rows}


# ---------------------------------------------------------------- pip dry-run in a clean venv

def pip_resolve(root: Path, arch: str) -> dict:
    backend = root / "smplwise_vms" / "backend"
    with tempfile.TemporaryDirectory() as td:
        venv = Path(td) / "venv"
        try:
            subprocess.run([sys.executable, "-m", "venv", str(venv)], check=True, capture_output=True, timeout=300)
        except (OSError, subprocess.SubprocessError) as exc:   # e.g. Ubuntu without python3-venv
            return {"ok": None, "error": f"no clean venv: {exc}", "installed": {}}
        py = venv / ("Scripts/python.exe" if os.name == "nt" else "bin/python")
        report = Path(td) / "report.json"
        cmd = [str(py), "-m", "pip", "install", "--dry-run", "--quiet", "--ignore-installed", "--no-cache-dir",
               "--disable-pip-version-check", "--isolated",
               "--only-binary=:all:", "--python-version", PYTHON_VERSION,
               # pip does not expand a custom musllinux tag to the older ones (it does for manylinux): list them all,
               # or e.g. pydantic-core (musllinux_1_1 wheels only) looks uninstallable
               *[x for k in range(MUSL_MINOR_MAX, -1, -1) for x in ("--platform", f"musllinux_1_{k}_{ARCHES[arch][1]}")],
               "--implementation", "cp", "--abi", "cp312", "--target", str(Path(td) / "target"),
               "-r", str(backend / "requirements.txt"), "-c", str(backend / "constraints.txt"), "--report", str(report)]
        p = subprocess.run(cmd, capture_output=True, text=True)
        if p.returncode != 0:
            return {"ok": False, "error": (p.stdout + p.stderr)[-3000:], "installed": {}}
        data = json.loads(report.read_text(encoding="utf-8"))
    installed = {norm(i["metadata"]["name"]): i["metadata"]["version"] for i in data.get("install", [])}
    return {"ok": True, "installed": installed}


def compare_installed(installed: dict[str, str], pins: dict[str, str]) -> list[str]:
    pins_n = {norm(k): v for k, v in pins.items()}
    out = [f"{n}: installed {v}, pinned {pins_n[n]}" for n, v in sorted(installed.items()) if n in pins_n and pins_n[n] != v]
    out += [f"{n} {v}: installed but not in constraints.txt" for n, v in sorted(installed.items()) if n not in pins_n]
    out += [f"{n}=={v}: pinned but not installed" for n, v in sorted(pins_n.items()) if n not in installed]
    return out


# ---------------------------------------------------------------- main

def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(Path(__file__).resolve().parents[1]))
    g = ap.add_mutually_exclusive_group()
    for flag in ("--write", "--diff", "--check", "--verify-wheels", "--pip-resolve"):
        g.add_argument(flag, action="store_true")
    ap.add_argument("--arch", action="append", choices=sorted(ARCHES))
    ap.add_argument("--strict", action="store_true", help="--verify-wheels: sdist-only also fails")
    ap.add_argument("--force", action="store_true", help="--pip-resolve: run on a host whose markers differ from the image")
    ap.add_argument("--json")
    a = ap.parse_args(argv)
    root = Path(a.root).resolve()
    backend = root / "smplwise_vms" / "backend"
    cons_path = backend / "constraints.txt"
    arches = a.arch or list(ARCHES)
    result: dict = {"mode": "", "result": "PASS", "details": []}

    def done(res: str, code: int, msg: str) -> int:
        result["result"] = res
        result["reason"] = msg
        if a.json:
            Path(a.json).write_text(json.dumps(result, indent=1), encoding="utf-8")
        print(f"LOCK_PYTHON {result['mode']}: {res} - {msg}")
        return code

    if a.check:
        result["mode"] = "check"
        if not cons_path.is_file():
            return done("FAIL", 1, f"no {cons_path.relative_to(root)}")
        problems = check((backend / "requirements.txt").read_text(encoding="utf-8"), cons_path.read_text(encoding="utf-8"))
        result["details"] = problems
        for p in problems:
            print("  -", p)
        n = len(parse_constraints(cons_path.read_text(encoding="utf-8"))) if not problems else 0
        return done("FAIL", 1, f"{len(problems)} problem(s)") if problems else done("PASS", 0, f"{n} pinned packages agree with requirements.txt")

    if a.verify_wheels:
        result["mode"] = "verify-wheels"
        pins = parse_constraints(cons_path.read_text(encoding="utf-8"))
        try:
            res = verify_wheels(pins, arches)
        except (urllib.error.URLError, TimeoutError, OSError) as exc:
            return done("NOT_RUN", 3, f"PyPI not reachable: {exc}")
        result["details"] = res["rows"]
        bad, soft = [], []
        for r in res["rows"]:
            tag = "" if not r["arch_specific"] else "  (binary wheel per arch)"
            print(f"  {r['name']}=={r['version']}: " + ", ".join(f"{x} {r[x]}" for x in arches) + tag)
            for x in arches:
                if r[x] == "missing":
                    bad.append(f"{r['name']} {x}")
                elif r[x] == "sdist-only":
                    soft.append(f"{r['name']} {x}")
        native = sum(1 for r in res["rows"] if r["arch_specific"])
        if bad or (a.strict and soft):
            return done("FAIL", 1, f"no installable file: {bad}; sdist-only: {soft}")
        return done("PASS", 0, f"{len(pins)} pins, wheels for {', '.join(arches)}; {native} with per-arch binary wheels; "
                    f"sdist-only: {soft or 'none'}")

    if a.pip_resolve:
        result["mode"] = "pip-resolve"
        host = {"x86_64": "amd64", "amd64": "amd64", "aarch64": "aarch64", "arm64": "aarch64"}.get(platform.machine().lower())
        pins = parse_constraints(cons_path.read_text(encoding="utf-8"))
        outs = []
        for arch in arches:
            exact = sys.platform.startswith("linux") and host == arch
            if not exact and not a.force:
                outs.append(f"{arch}: SKIPPED (host {sys.platform}/{platform.machine()} evaluates markers differently)")
                continue
            try:
                urllib.request.urlopen("https://pypi.org/simple/pip/", timeout=15).close()  # noqa: S310 - fixed https host
            except (urllib.error.URLError, TimeoutError, OSError) as exc:
                return done("NOT_RUN", 3, f"PyPI not reachable: {exc}")
            r = pip_resolve(root, arch)
            if r["ok"] is None:
                return done("NOT_RUN", 3, f"{arch}: {r['error'][:300]}")
            if not r["ok"]:
                if "NewConnectionError" in r["error"] or "Temporary failure in name resolution" in r["error"]:
                    return done("NOT_RUN", 3, f"{arch}: PyPI not reachable")
                print(r["error"])
                return done("FAIL", 1, f"{arch}: pip could not resolve -r requirements.txt -c constraints.txt")
            diff = compare_installed(r["installed"], pins)
            result["details"].append({"arch": arch, "exact": exact, "diff": diff, "count": len(r["installed"])})
            for d in diff:
                print(f"  {arch}: {d}")
            if diff and exact:
                return done("FAIL", 1, f"{arch}: pip's resolution differs from constraints.txt ({len(diff)} line(s))")
            outs.append(f"{arch}: {len(r['installed'])} packages" + ("" if exact else f", host markers ({len(diff)} expected diff line(s))"))
        if all("SKIPPED" in o for o in outs):
            return done("NOT_RUN", 3, "; ".join(outs))
        return done("PASS", 0, "; ".join(outs))

    # --write / --diff
    result["mode"] = "diff" if a.diff else "write"
    uv = find_uv()
    if not uv:
        return done("NOT_RUN", 3, "uv not found (pip install uv, or LOCK_PYTHON_UV=<path to uv>)")
    pins, uv_version = resolve(root, uv)
    text = render(pins, uv_version)
    if a.diff:
        old = parse_constraints(cons_path.read_text(encoding="utf-8")) if cons_path.is_file() else {}
        new = {norm(k): v for k, v in pins.items()}
        diff = [f"{n}: {old.get(n, '-')} -> {new.get(n, '-')}" for n in sorted(set(old) | set(new)) if old.get(n) != new.get(n)]
        result["details"] = diff
        for d in diff:
            print("  ", d)
        return done("FAIL", 1, f"the resolution moved: {len(diff)} package(s)") if diff else done("PASS", 0, f"{len(new)} pins unchanged")
    cons_path.write_text(text, encoding="utf-8", newline="\n")
    problems = check((backend / "requirements.txt").read_text(encoding="utf-8"), text)
    if problems:
        for p in problems:
            print("  -", p)
        return done("FAIL", 1, "the new lock does not satisfy requirements.txt")
    return done("PASS", 0, f"wrote {cons_path.relative_to(root)}: {len(pins)} pins ({uv_version})")


if __name__ == "__main__":
    sys.exit(main())
