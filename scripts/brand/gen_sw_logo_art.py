"""LOGOKIT-295: generate frontend/src/design/sw-logo-art.ts from the approved SmplWise developer kit (docs/brand/logo-kit/svg).

The kit draws every logo from two outlines (the "SW" symbol and the "smplwise" wordmark) placed by a transform per layout; only the fill
colours differ per tone. This script reads the outlines, the per-layout viewBox and transforms, and the per-tone fills straight from the kit
files, so the TypeScript module is a pure function of the kit (nothing is typed in by hand).

Usage:  python scripts/brand/gen_sw_logo_art.py [kit_svg_dir]    (default: docs/brand/logo-kit/svg)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
KIT = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "docs" / "brand" / "logo-kit" / "svg"
OUT = ROOT / "frontend" / "src" / "design" / "sw-logo-art.ts"

LAYOUTS = {"horizontal": "logo-horizontal", "stacked": "logo-stacked", "symbol": "symbol", "wordmark": "wordmark"}
TONES = ["brand", "white", "navy", "black"]
PATH = re.compile(r'<path fill="(#[0-9A-Fa-f]{6})" data-part="(symbol|wordmark)" fill-rule="evenodd" d="([^"]+)" transform="translate\(([\d.]+) ([\d.]+)\) scale\(([\d.]+)\)"/>')


def parse(path: Path):
    s = path.read_text(encoding="utf-8")
    vb = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', s)
    parts = {m.group(2): m.groups() for m in PATH.finditer(s)}
    return (float(vb.group(1)), float(vb.group(2))), parts


def num(x: str) -> str:
    return ("%s" % float(x)).rstrip("0").rstrip(".") if "." in x else x


def main() -> None:
    outlines: dict[str, str] = {}
    layouts: dict[str, dict] = {}
    fills: dict[str, dict[str, str]] = {}
    for lay, fname in LAYOUTS.items():
        vb, parts = parse(KIT / "brand" / (fname + ".svg"))
        info = {"w": vb[0], "h": vb[1], "parts": {}}
        for part, (fill, _p, d, tx, ty, sc) in parts.items():
            if outlines.setdefault(part, d) != d:
                raise SystemExit("the %s outline differs between layouts" % part)
            info["parts"][part] = (num(tx), num(ty), num(sc))
        layouts[lay] = info
    for tone in TONES:
        _vb, parts = parse(KIT / tone / "logo-horizontal.svg")
        fills[tone] = {part: g[0].lower() for part, g in parts.items()}
    lines = [
        "/**",
        " * LOGOKIT-295: the approved SmplWise logo, exactly as the developer kit draws it (docs/brand/logo-kit, from smplwise-developer-kit-v1,",
        " * the approved 02B-2 with the rounded w and the thin SW symbol). GENERATED by scripts/brand/gen_sw_logo_art.py: do not edit by hand.",
        " *",
        " * Every layout is the same two outlines (the SW symbol, the smplwise wordmark) placed by a transform; the tone only changes the fills.",
        " * Dark surfaces use the `white` tone and carry NO plate: the logo is transparent and sits on whatever the screen draws.",
        " * `swLogoSvg` returns plain SVG markup for the surfaces that draw HTML by string (the notice-board TV bundle, which reaches no other",
        " * file) and for `<sw-brand>` (components/sw-brand.ts), so there is one source of the artwork.",
        " */",
        "export type SwLayout = 'horizontal' | 'stacked' | 'symbol' | 'wordmark';",
        "export type SwTone = 'brand' | 'white' | 'navy' | 'black';",
        "",
        "const SYMBOL_D = '%s';" % outlines["symbol"],
        "const WORDMARK_D = '%s';" % outlines["wordmark"],
        "",
        "/** The viewBox and the per-part transform (x, y, scale) of each layout, read from the kit. */",
        "export const SW_LAYOUTS: Record<SwLayout, { w: number; h: number; symbol?: [number, number, number]; wordmark?: [number, number, number] }> = {",
    ]
    for lay, info in layouts.items():
        bits = ["w: %s" % num(str(info["w"])), "h: %s" % num(str(info["h"]))]
        for part in ("symbol", "wordmark"):
            if part in info["parts"]:
                tx, ty, sc = info["parts"][part]
                bits.append("%s: [%s, %s, %s]" % (part, tx, ty, sc))
        lines.append("  %s: { %s }," % (lay, ", ".join(bits)))
    lines += ["};", "", "/** The fill of each part per tone, read from the kit's logo-horizontal files. */",
              "export const SW_TONES: Record<SwTone, { symbol: string; wordmark: string }> = {"]
    for tone in TONES:
        lines.append("  %s: { symbol: '%s', wordmark: '%s' }," % (tone, fills[tone]["symbol"], fills[tone]["wordmark"]))
    lines += [
        "};",
        "",
        "/** The logo as an inline `<svg>` string. `alt` empty = decorative (hidden from assistive technology). */",
        "export function swLogoSvg(layout: SwLayout, tone: SwTone, alt = ''): string {",
        "  const l = SW_LAYOUTS[layout];",
        "  const c = SW_TONES[tone];",
        "  const part = (p: 'symbol' | 'wordmark', d: string): string => {",
        "    const t = l[p];",
        "    return t ? '<path fill=\"' + c[p] + '\" fill-rule=\"evenodd\" d=\"' + d + '\" transform=\"translate(' + t[0] + ' ' + t[1] + ') scale(' + t[2] + ')\"/>' : '';",
        "  };",
        "  return '<svg class=\"sw\" viewBox=\"0 0 ' + l.w + ' ' + l.h + '\" width=\"' + l.w + '\" height=\"' + l.h + '\" ' +",
        "    (alt ? 'role=\"img\" aria-label=\"' + alt + '\"' : 'role=\"presentation\" aria-hidden=\"true\"') +",
        "    ' data-brand-img=\"product\" data-brand-art=\"kit-' + layout + '-' + tone + '\">' + part('symbol', SYMBOL_D) + part('wordmark', WORDMARK_D) + '</svg>';",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote", OUT, OUT.stat().st_size, "bytes")


main()
